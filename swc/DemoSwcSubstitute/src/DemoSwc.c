/* DemoSwc: Board demo (Led1 follows Button1, Led2 blinks when PC_Command is valid, NTC low-pass) - C substitute
 *
 * Hand-written replacement of the code Embedded Coder generates from swc/DemoSwc/DemoSwc.slx (PLAT-119, decision
 * F9 A: generated code is not published). Written from the behaviour described in swc/README.md (section DemoSwc),
 * not derived from the generated code. Same RTE interface as the model: see ../swc.yaml (implementation: c), so
 * the runnables are DemoSwc_Run10ms and DemoSwc_Run100ms instead of the Embedded Coder names Run10ms and Run100ms.
 * Rte_DemoSwc.h (generated by tools/rtegen) declares the runnables and the port accesses.
 *
 *   Run10ms   Led1 = Button1; a blink state toggles every 50 calls (1 Hz at 10 ms), Led2 = blink state AND
 *             (PcCommandQlf == QLF_OK) - the qualifier releases the blink, it is no substitute value (COM-13)
 *   Run100ms  first order low-pass y = y + (MotorNtc_mV - y) * FilterAlpha, rounded to the nearest mV;
 *             FilterAlpha (calibration parameter, swc/DemoSwc/DemoSwc_data.m) is limited to 0..1 */

#include "Rte_DemoSwc.h"
#include "Rte_Qlf.h"

#define DEMOSWC_BLINK_CALLS 50U                /* calls of Run10ms per half period of the Led2 blink */
#define DEMOSWC_UINT32_LIMIT 4294967296.0F     /* 2^32: first float32 value that no longer fits into uint32 */

static uint8 blinkCount;   /* calls of Run10ms since the last toggle, 0..DEMOSWC_BLINK_CALLS-1 */
static boolean blinkOn;    /* blink state of Led2 before the release by the qualifier */
static float32 filtered;   /* state of the NTC low-pass in mV */

void DemoSwc_Init(void)
{
    blinkCount = 0U;
    blinkOn    = FALSE;
    filtered   = 0.0F;
}

/* Runnable Run10ms, every 10 ms: button to Led1, blink of Led2 released by the qualifier of PC_Command. */
void DemoSwc_Run10ms(void)
{
    boolean button = FALSE;
    uint8 qualifier = QLF_NOT_AVAILABLE;
    boolean led2   = FALSE;

    (void)Rte_Read_Button1_Button1(&button);
    (void)Rte_Read_PcCommandQlf_PcCommandQlf(&qualifier);

    if (blinkCount == 0U)
    {
        blinkOn = (blinkOn == FALSE) ? TRUE : FALSE;
    }
    blinkCount = (uint8)(blinkCount + 1U);
    if (blinkCount >= DEMOSWC_BLINK_CALLS)
    {
        blinkCount = 0U;
    }
    /* the counter keeps running while Led2 is blocked, so the blink goes on in phase after the healing */
    if ((blinkOn != FALSE) && (qualifier == QLF_OK))
    {
        led2 = TRUE;
    }

    (void)Rte_Write_Led1_Led1((button != FALSE) ? TRUE : FALSE);
    (void)Rte_Write_Led2_Led2(led2);
}

/* Runnable Run100ms, every 100 ms: low-pass of the NTC voltage. */
void DemoSwc_Run100ms(void)
{
    uint32 input_mV = 0U;
    uint32 output_mV;
    float32 alpha = Rte_Prm_CalPrm_FilterAlpha();
    float32 rounded;

    (void)Rte_Read_MotorNtc_mV_MotorNtc_mV(&input_mV);

    if (!(alpha >= 0.0F))          /* also NaN */
    {
        alpha = 0.0F;
    }
    else if (alpha > 1.0F)
    {
        alpha = 1.0F;
    }
    else
    {
        /* in range */
    }
    filtered = filtered + (((float32)input_mV - filtered) * alpha);

    rounded = filtered + 0.5F;
    if (!(rounded >= 0.0F))
    {
        output_mV = 0U;
    }
    else if (rounded >= DEMOSWC_UINT32_LIMIT)
    {
        output_mV = 0xFFFFFFFFU;
    }
    else
    {
        output_mV = (uint32)rounded;
    }
    (void)Rte_Write_MotorNtcFiltered_mV_MotorNtcFiltered_mV(output_mV);
}
