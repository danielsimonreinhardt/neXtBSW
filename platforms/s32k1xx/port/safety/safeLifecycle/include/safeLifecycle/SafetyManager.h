#pragma once

#include <integration/safeLifecycleConfiguration.h>

#include <cstdint>

namespace safety
{

class SafetyManager
{
public:
    // [PUBLIC_API_START]
    /**
     * Initializes the counter used for cyclic checks with 0.
     */
    SafetyManager();
    /**
     * Initializes the safety relevant components. Enables the watchdog, initializes Memory
     * protection unit and Rom check, starts the timer of the period check (SYS-40). It is called from the
     * safety task.
     */
    void init();
    void run();
    void shutdown();
    /**
     * Enables and disables the write access to the protected RAM region using the scoped unlock
     * because only safety relevant software can write to the safety RAM region. Services the
     * watchdog every WATCHDOG_CYCLIC_COUNTER cycles (demo: 70 ms) by calling cyclic method of
     * safeWatchdog. Calls the cyclic function of SafeMemory.
     */
    void cyclic();

    /**
     * SYS-40 (finding F9 of doc/safety/fmea.md, SM-04): nominal period of the safety task. SYS-25: one project value,
     * modules.safeLifecycle.task_period_ms (module.yaml of this directory, generated by tools/bswgen), the same
     * that SafetySystem (ecu/application) schedules the task with.
     */
    static constexpr uint32_t CYCLE_PERIOD_MS = NX_MODULE_SAFELIFECYCLE_PARAM_TASK_PERIOD_MS;
    /**
     * SYS-40: how late a cycle may start against its nominal grid point without a period violation (interrupt load,
     * critical sections, one tick of the OS timer). The safety task has the highest task priority; the value is an
     * assumption until the board measurement B4 of doc/safety/fmea.md confirms it. SYS-25: project value
     * modules.safeLifecycle.cycle_lateness_ms.
     */
    static constexpr uint32_t CYCLE_LATENESS_MS = NX_MODULE_SAFELIFECYCLE_PARAM_CYCLE_LATENESS_MS;
    // [PUBLIC_API_END]

private:
    /** SYS-41: configuration re-check of the supervision peripherals outside the watchdog (the deadman). */
    static void checkSupervisionPeripherals();
    /** SYS-40: the cycle's own period against the independent timer of the family (first thing of every cycle). */
    static void checkCyclePeriod();

    uint16_t _counter;
    /** Safety cycles per watchdog service. SYS-25: derived by tools/nxconfig - three services before the time-out
     * (finding F2 of doc/safety/concept.md); SYS-53: at the fastest LPO of the data sheet,
     * floor(watchdog_timeout_ms x 1000 / (3 x task_period_ms x lpo_max_per_mille)), demo 7. */
    static constexpr uint32_t WATCHDOG_CYCLIC_COUNTER = NX_MODULE_SAFELIFECYCLE_DERIVED_WATCHDOG_SERVICE_CYCLES;

public:
    /** SYS-40: cycles per window of the period check's lower bound - the watchdog service interval, so the window
     * is the software counterpart of the watchdog's window mode, measured against an independent clock. */
    static constexpr uint32_t CYCLE_PERIOD_WINDOW = WATCHDOG_CYCLIC_COUNTER;
};

class DeviceReportBox;

/**
 * SYS-194 (safety review BL38-P1 2026-10-03, SYS147-B1 b): the event box of the hold of the safe_off levels of the
 * integration (integration/SafeOffCommandHold.h, TASK_BSP) - its report-only messages (DEVICE_REPORT, S3) for the
 * safe supervisor. The box lies in ordinary RAM of the integration; SafetyManager::cyclic() hands it to
 * SafeSupervisor::deliverDeviceReports() in every cycle and keeps no reference. A project without safe_off outputs
 * keeps the weak default of SafetyManager.cpp (nullptr: nothing to deliver); the integration of the family port
 * replaces it with a strong definition (Integration.cpp, never inline - an inline definition is no strong one for
 * the linker). Safety task only.
 */
DeviceReportBox* safeOffReportBox();

} // namespace safety
