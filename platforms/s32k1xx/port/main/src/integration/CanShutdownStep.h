#pragma once

/* Run-down step CAN_STOP of the ECU state management (SYS-02, ecuState/IShutdownStep.h): logs the ECU off the
 * CAN buses before the OpenBSW lifecycle tears the CAN system down.
 *
 * Order per bus of the project (NX_BUSID_CAN_BUSES, generated from board and project, ARCH-07):
 *   1. mute() the transceiver: write() is refused and pending transmit buffers are deactivated, so the
 *      application and the RTE stop sending. Reception keeps running, a wake-up frame is still seen.
 *   2. wait the hardware queue timeout of the slowest bus, so a frame that is already in the queue can leave
 *      the ECU instead of being cut off in the middle.
 *   3. put every transceiver of the role can_phy into standby (::bios::CanPhy::CAN_PHY_MODE_STANDBY), the
 *      state in which it can still detect a wake-up. A transceiver of a SBC ignores this (its driver owns the
 *      mode and the SBC reaches standby with the mode change of the power down); a transceiver with STB pin
 *      switches over.
 * The transceiver objects are not closed here: that is the shutdown of the CAN system in the next lifecycle
 * level, and closing twice would only answer CAN_ERR_ILLEGAL_STATE.
 *
 * Private to the board integration (Integration.cpp wires it next to the roles can_phy and power_supply, SYS-08;
 * later generated by intgen). The bus list comes from busIdConfiguration.h, not from the FlexCAN configuration,
 * so the step itself knows no family. */

#include <bsp/can/canTransceiver/CanPhy.h>
#include <can/transceiver/ICanTransceiver.h>
#include <ecuState/IShutdownStep.h>
#include <systems/ICanSystem.h>

#include <cstdint>

namespace systems
{

class CanShutdownStep final : public ::ecustate::IShutdownStep
{
public:
    /**
     * \param canSystem resolver of the CAN system; called when the step runs, not when it is created, because
     *                  the CAN system appears one lifecycle level after the ECU state management
     * \param phys transceivers of the role can_phy in the order of the CAN buses, nullptr entries allowed;
     *             \p phyCount 0 leaves the transceiver mode alone (the power supply reaches standby itself)
     */
    CanShutdownStep(::can::ICanSystem& (*canSystem)(), ::bios::CanPhy* const* phys, uint8_t phyCount);

    char const* getName() const override;
    Result start(uint32_t nowMs) override;
    Result poll(uint32_t nowMs) override;
    char const* getFailureReason() const override;

    /** Bus the failure belongs to, "-" without one. */
    char const* getFailureBus() const { return _bus; }

    /** Buses whose transmission was stopped, for the log. */
    uint8_t getMutedBusCount() const { return _muted; }

private:
    bool muteBus(uint8_t busId, char const* name, uint16_t& drainMs);

    ::can::ICanSystem& (*_canSystem)();
    ::bios::CanPhy* const* _phys;
    uint8_t _phyCount;
    uint32_t _drainUntilMs = 0U;
    char const* _reason    = "-";
    char const* _bus       = "-";
    uint8_t _muted         = 0U;
};

} // namespace systems
