    def test_interrupt_stack_project_value_from_the_generator(self):
        """memory.application.isr_stack_size / isr_stack_guard_size: blgen writes them to memoryLayout.h and the
        template links them; the eval board layout without them keeps 4 KB / 1 KB (the demo image is unchanged)."""
        import dataclasses

        sys.path.insert(0, str(REPO / "tools" / "bswgen"))
        import blgen  # noqa: E402

        import nxconfig  # noqa: E402

        config = nxconfig.load(EVAL_PROJECT, nxconfig.MCUDB)
        for size, guard, expected in ((None, None, (0x1000, 0x400)), (0x1800, 0x200, (0x1800, 0x200))):
            with self.subTest(size=size, guard=guard), tempfile.TemporaryDirectory() as name:
                tmp = Path(name)
                config.memory = dataclasses.replace(config.memory, isr_stack_size=size, isr_stack_guard_size=guard)
                header = blgen.memory_files(config)["memory/memoryLayout.h"]
                self.assertEqual("NX_MEMORY_APP_ISR_STACK_SIZE" in header, size is not None)
                pre = self.preprocess(header, tmp)
                self.assertEqual(pre.returncode, 0, pre.stderr)
                link = self.link(tmp)
                self.assertEqual(link.returncode, 0, link.stderr)
                nm = subprocess.run([str(Path(ARM_GCC).with_name(Path(ARM_GCC).name.replace("gcc", "nm"))),
                                     str(tmp / "application.elf")], capture_output=True, text=True).stdout
                s = {parts[2]: int(parts[0], 16) for parts in (line.split() for line in nm.splitlines())
                     if len(parts) == 3}
                self.assertEqual((s["__StackTop"] - s["__StackLimit"], s["__StackGuardEnd"] - s["__StackGuardStart"]),
                                 expected)
                self.assertEqual(s["__StackGuardEnd"], s["__StackLimit"])


