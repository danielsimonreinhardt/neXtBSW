    # ------------------------------------------------------------------ SYS-89: calibration segment

    def calibration_link(self, production: bool) -> tuple[dict, dict, str]:
        """(memory regions, symbols, map text) of the template with a 4 KB segment at 0x9000 and three parameters."""
        with tempfile.TemporaryDirectory() as name:
            tmp = Path(name)
            header = layout_header([(0x1FFF8000, 0x8000), (0x20000000, 0x7000)], cal=(0x9000, 0x1000, production))
            pre = self.preprocess(header, tmp)
            self.assertEqual(pre.returncode, 0, pre.stderr)
            link = self.link(tmp, parameters=True)
            self.assertEqual(link.returncode, 0, link.stderr)
            self.assertEqual(link.stderr, "", "the linker warns")
            text = (tmp / "application.map").read_text(encoding="utf-8", errors="replace")
            config = text.split("Memory Configuration")[1].split("Linker script and memory map")[0]
            regions = {n: (int(o, 16), int(ln, 16)) for n, o, ln in MEMORY_CONFIG.findall(config)
                       if n not in ("Name", "*default*")}
            nm = subprocess.run([str(Path(ARM_GCC).with_name(Path(ARM_GCC).name.replace("gcc", "nm"))),
                                 str(tmp / "application.elf")], capture_output=True, text=True).stdout
            symbols = {parts[2]: int(parts[0], 16) for parts in (line.split() for line in nm.splitlines())
                       if len(parts) == 3}
            return regions, symbols, text

    def test_calibration_segment_behind_the_first_application_sector(self):
        for production in (False, True):
            with self.subTest(production=production):
                regions, symbols, _ = self.calibration_link(production)
                self.assertEqual(regions["Isr"], (0x8000, 0x400))
                self.assertEqual(regions["Calibration"], (0x9000, 0x1000))
                self.assertEqual(regions["Application"], (0xA000, 0x7F000 - 0xA000))
                self.assertEqual((symbols["__nx_cal_segment"], symbols["__nx_cal_values"]), (0x9000, 0x9020))
                self.assertGreaterEqual(symbols["__ROM_CRC_START"], 0xA000)
                # SYS-91: the whole region is the area with its own reference, outside the ROM check list
                self.assertEqual((symbols["__rom_check_own_area_start"], symbols["__rom_check_own_area_end"]),
                                 (0x9000, 0xA000))
                self.assertNotIn("__CRC_CAL_START", symbols)

    def test_without_calibration_no_own_area(self):
        with tempfile.TemporaryDirectory() as name:
            tmp = Path(name)
            pre = self.preprocess(layout_header([(0x1FFF8000, 0x8000), (0x20000000, 0x7000)]), tmp)
            self.assertEqual(pre.returncode, 0, pre.stderr)
            self.assertNotIn("__rom_check_own_area", (tmp / "application.dld").read_text(encoding="utf-8"))

    def test_calibration_production_reads_the_parameters_from_flash(self):
        _, symbols, text = self.calibration_link(production=True)
        names = ("Rte_Prm_A_P_X_data", "Rte_Prm_B_P_Y_data", "Rte_Prm_C_P_Z_data")
        addresses = [symbols[n] for n in names]
        self.assertTrue(all(0x9020 <= a < symbols["__nx_cal_values_end"] for a in addresses), addresses)
        # initialised storage sorted by name, the zero-initialised one behind it
        self.assertLess(symbols["Rte_Prm_B_P_Y_data"], symbols["Rte_Prm_C_P_Z_data"])
        self.assertGreater(symbols["Rte_Prm_A_P_X_data"], symbols["Rte_Prm_C_P_Z_data"])
        self.assertGreaterEqual(symbols["general"], 0x1FFF8000)     # other data stays in RAM
        self.assertNotIn("__nx_cal_ram_start", symbols)
        self.assertIn("LONG 0x5", text)                             # ROM check list: five areas (SYS-91)
        self.assertNotIn("LONG 0x6", text)

    def test_calibration_development_working_page_in_ram(self):
        _, symbols, text = self.calibration_link(production=False)
        start, end = symbols["__nx_cal_ram_start"], symbols["__nx_cal_ram_end"]
        self.assertEqual(start % 8, 0)
        self.assertGreaterEqual(start, 0x1FFF8000)
        for name in ("Rte_Prm_A_P_X_data", "Rte_Prm_B_P_Y_data", "Rte_Prm_C_P_Z_data"):
            self.assertTrue(start <= symbols[name] < end, name)
        self.assertFalse(start <= symbols["general"] < end)
        # the flash segment is header plus room for the copy of the working page
        self.assertEqual(symbols["__nx_cal_values_end"] - symbols["__nx_cal_values"], end - start)
        self.assertIn("LONG 0x5", text)                             # SYS-91: the segment is not in the list
        self.assertNotIn("LONG 0x6", text)

