// Family header of platforms/s32k1xx (PLAT-11), derived from the OpenBSW header
// external/openbsw/platforms/s32k1xx/bsp/bspMcu/include/mcu/mcu.h.
//
// Nothing here names a derivative:
//  - the device header comes from mcu/mcuDerivative.h, generated from the derivative database
//    (mcudb/<family>/<derivative>.yaml, field device_header; ARCH-03, bswgen),
//  - the CMSIS core header follows the architecture the compiler builds for (-mcpu from mcudb, PLAT-09),
//  - the IP remaps of OpenBSW exist only for the peripherals the derivative has (#ifdef instead of an #undef
//    chain after including a larger derivative's header),
//  - the NVIC priority bits come from the derivative database (mcu/derivativeFacts.h, ARCH-16); the device header
//    is only cross-checked against them in platforms/common/interruptPriority (PLAT-10), because S32K116.h claims
//    4 bits while the core has 2.

#pragma once

// Derivative facts from mcudb (generated by tools/bswgen): NVIC priority bits, MPU region descriptors (ARCH-16)
#include "mcu/derivativeFacts.h"
#include "mcu/mcuDerivative.h"

// The core follows the compiler's target architecture (-mcpu from the derivative, PLAT-09); the device header must
// agree, otherwise the build uses the wrong core registers and the wrong number of NVIC registers.
#if defined(__ARM_ARCH_6M__)
#if !defined(__CM0PLUS_REV)
#error "device header of mcu/mcuDerivative.h is not for a Cortex-M0+, but the build targets ARMv6-M"
#endif
#define NX_MCU_CORE_HEADER "core_cm0plus.h"
#elif defined(__ARM_ARCH_7EM__)
#if defined(__CM0PLUS_REV)
#error "device header of mcu/mcuDerivative.h is for a Cortex-M0+, but the build targets ARMv7E-M"
#endif
#define NX_MCU_CORE_HEADER "core_cm4.h"
#else
#error "unsupported core for platforms/s32k1xx (expected ARMv6-M or ARMv7E-M)"
#endif

#if defined(__MPU_PRESENT) && (__MPU_PRESENT == 1U)
// NXP has their own MPU, so we must not use the cmsis one.
#undef __MPU_PRESENT
#define INCLUDE_CORE_CM4_IN_MCU_H
#include NX_MCU_CORE_HEADER
#undef INCLUDE_CORE_CM4_IN_MCU_H
#define __MPU_PRESENT 1
#else
#include NX_MCU_CORE_HEADER
#endif /* defined (__MPU_PRESENT) && (__MPU_PRESENT == 1U) */

#include "mcu/typedefs.h"

// interrupt locking and nvic info used by the freertos ports
#define ENABLE_INTERRUPTS()  __enable_irq()
#define DISABLE_INTERRUPTS() __disable_irq()

// ARCH-16: number of priority bits of this derivative, from the derivative database
// (mcudb derivative.nvic_priority_bits -> NX_NVIC_PRIORITY_BITS in mcu/derivativeFacts.h). The device header value
// __NVIC_PRIO_BITS is not used, only compared against it in interrupts/nxInterruptPriority.h: for the S32K116 the
// two disagree (header 4, core 2, PLAT-10/PLAT-11).
#define FEATURE_NVIC_PRIO_BITS (NX_NVIC_PRIORITY_BITS)

// watchdog magic values (same for every S32K1 derivative, S32K1xx RM Rev. 14, chapter WDOG)
#define FEATURE_WDOG_UNLOCK_VALUE  (0xD928C520U)
#define FEATURE_WDOG_TRIGGER_VALUE (0xB480A602U)

// FIRCERR bit mask: missing in some device header revisions (S32K148.h), present in others (S32K116.h from SVD 1.6)
#ifndef SCG_FIRCCSR_FIRCERR_MASK
#define SCG_FIRCCSR_FIRCERR_MASK 0x4000000u
#endif

