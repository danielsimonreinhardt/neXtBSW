def generated_dir(tmp: Path) -> Path:
    """What tools/bswgen generates for the S32K116 and the family mcu.h needs: facts, mcuDerivative.h, board clock."""
    # derivative facts as bswgen generates them from mcudb/s32k1xx/S32K116.yaml (ARCH-16)
    (tmp / "mcu").mkdir(parents=True)
    (tmp / "mcu" / "derivativeFacts.h").write_text(
        "#pragma once\n#define NX_NVIC_PRIORITY_BITS 2\n#define NX_ADC_INSTANCE_COUNT 1\n"
        "#define NX_MPU_REGIONS 8\n#define NX_MPU_CESR_NRGD 0\n", encoding="utf-8")
    # bswgen generates this file from mcudb (device_header of the derivative); for S32K116 it is a plain include
    # because the header describes exactly this derivative - no #undef chain (ARCH-03, PLAT-11)
    (tmp / "mcu" / "mcuDerivative.h").write_text(
        '#pragma once\n#include "3rdparty/nxp/S32K116.h"\n', encoding="utf-8")
    (tmp / "bsp" / "clock").mkdir(parents=True)
    (tmp / "bsp" / "clock" / "boardClock.h").write_text(BOARD_CLOCK, encoding="utf-8")
    return tmp


@unittest.skipUnless(ARM_GPP, "arm-none-eabi-g++ not found")
class DeviceHeaderCompileTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp(prefix="bspmcu-"))
        cls.includes = includes(generated_dir(cls.tmp))

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def compile(self, source: Path, extra: list[str] = (), compiler=None) -> subprocess.CompletedProcess:
        args = [compiler or ARM_GPP, "-mcpu=cortex-m0plus", "-mthumb", "-Wall", "-Wextra", "-c", str(source),
                "-o", str(self.tmp / "probe.o")]
        if compiler is None:
            args += ["-std=c++17", "-fno-exceptions", "-fno-rtti"]
        args += [f"-I{p}" for p in self.includes] + list(extra)
        return subprocess.run(args, capture_output=True, text=True)

    def test_device_header_is_the_checked_in_one(self):
        """No workstation file: the header the build uses is in the repository and up to date."""
        rules = rtd_adapter.load_rules(rtd_adapter.rules_path("s32k1xx"))
        self.assertEqual(rtd_adapter.adapter_path(rules, "S32K116"), MODULE_INCLUDE / "3rdparty/nxp/S32K116.h")
        self.assertEqual(rtd_adapter.main(["check", "--derivative", "S32K116"]), 0)

    def test_bsp_mcu_source_compiles(self):
        """OpenBSW bspMcu (software reset) with our family mcu.h: device header, CMSIS M0+ core, NXP MPU."""
        out = self.compile(OPENBSW / "platforms/s32k1xx/bsp/bspMcu/src/reset/softwareSystemReset.cpp", ["-Werror"])
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_clock_driver_pll_guard_is_incomplete_upstream(self):
        """Finding for PLAT-12/PLAT-03: bspClock switches the SPLL code off with PLL_AVAILABLE
        (#ifdef SCG_SPLLCSR_SPLLEN_MASK), but pllOff() still calls isSpllSysClk()/spllStop() unconditionally.
        Everything else of the driver (PCC indices, SCG, RCM) accepts the S32K116 header."""
        out = self.compile(OPENBSW / "platforms/s32k1xx/bsp/bspClock/src/clockConfig.cpp")
        self.assertNotEqual(out.returncode, 0)
        errors = [line for line in out.stderr.splitlines() if ": error:" in line]
        self.assertTrue(errors)
        for line in errors:
            self.assertRegex(line, r"'(isSpllSysClk|spllStop)' was not declared", line)

    def test_probe_of_driver_symbols_compiles(self):
        """Register accesses of the FlexCAN, FTM, LPUART, LPSPI, ADC, WDOG and PORT drivers on the M0+ header."""
        source = self.tmp / "symbols.cpp"
        source.write_text(textwrap.dedent("""
            #include "mcu/mcu.h"
            void probe()
            {
                IP_FLEXCAN0->MCR |= FLEXCAN_MCR_HALT_MASK;
                IP_FLEXCAN0->RAMn[FLEXCAN_RAMn_COUNT - 1U] = 0U;
                FLEXCAN_Type* const can = IP_FLEXCAN0;
                can->ECR = FLEXCAN_ECR_TXERRCNT(1) | FLEXCAN_ESR1_FLTCONF_MASK;
                IP_FTM0->CONTROLS[3].CnV = FTM_CnV_VAL(100);
                IP_FTM1->MODE |= FTM_MODE_WPDIS_MASK;
                IP_LPUART0->CTRL |= LPUART_CTRL_TE(1);
                IP_LPSPI0->CR |= LPSPI_CR_MEN_MASK;
                IP_ADC0->SC1[0] = ADC_SC1A_ADCH(5) | ADC_SC1A_AIEN_MASK;
                WDOG->CNT = FEATURE_WDOG_UNLOCK_VALUE;
                PCC->PCCn[PCC_FlexCAN0_INDEX] |= PCC_PCCn_CGC_MASK;
                PORT_Type* const ports[] = PORT_BASE_PTRS;
                GPIO_Type* const gpios[] = GPIO_BASE_PTRS;
                ports[0]->PCR[3] = PORT_PCR_MUX(2);
                gpios[PORT_INSTANCE_COUNT - 1U]->PDDR |= 1U << 3;
                gpios[0]->PIDR |= 1U << 3;
                IP_MPU->RGD[0].WORD2 = MPU_RGD_WORD2_M3SM(3);
                IP_FTFC->FSTAT = FTFC_FSTAT_CCIF_MASK;
                SCG->FIRCCSR |= SCG_FIRCCSR_FIRCEN_MASK;
                (void)IP_ERM->EARn[ERM_EARn_COUNT - 1U].EAR;
                (void)SIM->SDID;
                (void)RCM->SRS;
                IP_LPIT0->TMR[0].TVAL = 1000U;
                (void)CRC->DATAu.DATA;
            }
            volatile int can_irq = CAN0_ORed_0_31_MB_IRQn;    // S32K116: one mailbox interrupt, not two
            volatile int wdg_irq = WDOG_IRQn;                 // S32K14x: WDOG_EWM_IRQn
            static_assert(FEATURE_NVIC_PRIO_BITS == 2, "S32K116 implements two NVIC priority bits");
            static_assert(__NVIC_PRIO_BITS == 2, "adapter corrects the RTD value 4 (PLAT-32)");
            static_assert(FTM_INSTANCE_COUNT == 2 && LPSPI_INSTANCE_COUNT == 1, "instances of the S32K116");
            static_assert(FLEXCAN_INSTANCE_COUNT == 1 && ERM_EARn_COUNT == 1, "instances of the S32K116");
            // adapted layouts keep the vendor offsets (RM: RAMn at 0x80, RXIMR at 0x880, EAR at 0x100, PIDR at 0x18)
            static_assert(offsetof(FLEXCAN_Type, RAMn) == 0x80 && offsetof(FLEXCAN_Type, RXIMR) == 0x880, "FlexCAN");
            static_assert(offsetof(FLEXCAN_Type, FDCTRL) == 0xC00, "FlexCAN");
            static_assert(offsetof(ERM_Type, EARn) == 0x100 && offsetof(GPIO_Type, PIDR) == 0x18, "ERM, GPIO");
            #ifdef IP_LMEM
            #error "S32K11x has no LMEM"
            #endif
            """), encoding="utf-8")
        out = self.compile(source, ["-Werror", "-include", "cstddef"])
        self.assertEqual(out.returncode, 0, out.stderr)

    @unittest.skipUnless(ARM_GCC, "arm-none-eabi-gcc not found")
    def test_header_compiles_as_c(self):
        """The bootloader (C) uses FLEXCAN_Type/RAMn of the same header."""
        source = self.tmp / "probe.c"
        source.write_text(textwrap.dedent("""
            #include "mcu/mcu.h"
            void probe(void)
            {
                FLEXCAN_Type* const can = IP_FLEXCAN0;
                can->RAMn[0] = FLEXCAN_MCR_MAXMB(3);
                can->CTRL1 |= FLEXCAN_CTRL1_CLKSRC_MASK;
            }
            """), encoding="utf-8")
        out = self.compile(source, ["-Werror", "-std=gnu11"], compiler=ARM_GCC)
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_cache_driver_needs_the_lmem_feature(self):
        """Finding for PLAT-12: cacheEnable() uses LMEM, which the S32K116 does not have (mcudb feature).
        The RTD header describes LMEM anyway; the adapter removes the instance (PLAT-32)."""
        out = self.compile(OPENBSW / "platforms/s32k1xx/bsp/bspCore/src/cache/cache.cpp")
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("'LMEM' was not declared", out.stderr)

    def test_watchdog_driver_uses_the_s32k14x_interrupt_name(self):
        """Finding for PLAT-12: the watchdog driver names WDOG_EWM_IRQn; the S32K116 interrupt is WDOG_IRQn."""
        out = self.compile(OPENBSW / "platforms/s32k1xx/safety/safeBspMcuWatchdog/src/watchdog/Watchdog.cpp")
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("WDOG_EWM_IRQn", out.stderr)
        # with the name of this derivative the driver compiles
        out = self.compile(OPENBSW / "platforms/s32k1xx/safety/safeBspMcuWatchdog/src/watchdog/Watchdog.cpp",
                           ["-DWDOG_EWM_IRQn=WDOG_IRQn"])
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_wrong_core_is_refused(self):
        """mcu.h stops a build whose -mcpu does not match the device header."""
        source = self.tmp / "core.cpp"
        source.write_text('#include "mcu/mcu.h"\n', encoding="utf-8")
        args = [ARM_GPP, "-mcpu=cortex-m4", "-mthumb", "-std=c++17", "-c", str(source), "-o", str(self.tmp / "c.o")]
        args += [f"-I{p}" for p in self.includes]
        out = subprocess.run(args, capture_output=True, text=True)
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("is for a Cortex-M0+, but the build targets ARMv7E-M", out.stderr)


@unittest.skipUnless(SVD and SVD.is_file(), "S32K116.svd not found (NX_SVD_DIR, optional cross-check, see "
                                            "mcudb/s32k1xx/sources/keil_s32k116_dfp)")
class SvdCrossCheckTest(unittest.TestCase):
    """PLAT-32: the adapter over the RTD headers against the header svd2header.py generates from the Keil SVD 1.6.

    Two independent NXP sources for the same registers; every symbol the drivers use must agree in offset, size and
    value (macro aliases of the adapter resolved). The remaining differences are listed with their reason.
    """

    # (difference, reason) - everything else must match
    KNOWN = {
        "macro __MPU_PRESENT: 0 != reference 1":
            "hal_nxp patch: S32K1 has the NXP SYSMPU, no Arm MPU; mcu.h hides __MPU_PRESENT 1 from CMSIS anyway",
        "macro __FPU_PRESENT: missing":
            "Cortex-M0+ has no FPU; the SVD rules set fpuPresent false, the RTD header does not define it",
        "macro RCM_SRS_LOL_MASK: missing":
            "Keil SVD 1.6 lists the bit, but S32K11x has no SPLL and so no loss-of-lock reset (RM Rev. 13, 28.1); "
            "adapter not_on_derivative, ClockCheck.cpp uses it only #ifdef",
        "type SIM_Type: member CLKDIV4 missing":
            "Keil SVD 1.6 lists it, RM Rev. 13, 11.3.1.15: CLKDIV4 (trace clock) is reserved for S32K11x variants",
    }

    @classmethod
    def setUpClass(cls):
        text, _ = s2h.generate("S32K116", s2h.rules_path("s32k1xx"), SVD)
        cls.svd = s2h.header_layout(text)
        adapter_text = s2h.read_header(MODULE_INCLUDE / "3rdparty/nxp/S32K116.h")
        cls.rtd = resolve_aliases(s2h.header_layout(adapter_text), adapter_text)
        cls.used = set(s2h.used_symbols(s2h.read_header(REPO / s2h.OPENBSW_S32K148)))

    def test_used_symbols_agree(self):
        diffs = s2h.compare_layouts(self.rtd, self.svd, symbols=self.used)
        self.assertEqual(sorted(diffs), sorted(self.KNOWN))

    def test_interrupt_numbers_agree(self):
        self.assertEqual(self.rtd["irqs"], self.svd["irqs"])


def resolve_aliases(layout: dict, text: str) -> dict:
    """Layout with `#define A B` aliases and `#define <vendor type> <type>` redirections of the adapter resolved."""
    macros = dict(layout["macros"])
    for _ in range(3):
        for name, value in macros.items():
            target = re.sub(r"\(x\)$", "", value)
            if re.fullmatch(r"[A-Za-z_]\w*", target) and target in macros and target != name:
                macros[name] = macros[target]
            elif target + "(x)" in macros and name.endswith("(x)"):
                macros[name] = macros[target + "(x)"]
    types = dict(layout["types"])
    code = s2h._strip_comments(text)
    for vendor, adapted in re.findall(r"^#define\s+(\w+_Type)\s+(\w+)\s*$", code, re.M):
        if adapted.startswith("NX_RTD_"):
            types[vendor] = types[adapted]              # same name for the drivers (GPIO_Type, ERM_Type)
        else:                                           # other name for the drivers (CAN_Type -> FLEXCAN_Type)
            macros = {k: v.replace(f"({vendor} *)", f"({adapted} *)") for k, v in macros.items()}
    return {"macros": macros, "types": types, "irqs": layout["irqs"]}


@unittest.skipUnless(ARM_GPP, "arm-none-eabi-g++ not found")
class DerivativeFactsTest(unittest.TestCase):
    """ARCH-16: the family mcu.h takes the NVIC priority bits and the MPU regions from mcudb, not from the header.

    The S32K144 builds with the S32K148 device header of OpenBSW, which claims what its own derivative has. The
    values the family header publishes must follow the derivative database (mcu/derivativeFacts.h, tools/bswgen):
    the check is a build with a facts header that deliberately disagrees with the device header.
    """

    # include directories of a board-less M4 build: generated facts first, then this module and OpenBSW
    def includes(self, generated: Path) -> list[Path]:
        return [generated, MODULE_INCLUDE, OPENBSW / "libs/3rdparty/cmsis",
                OPENBSW / "libs/3rdparty/cmsis/m-profile",
                OPENBSW / "platforms/s32k1xx/bsp/bspMcu/include"]

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="bspmcu-facts-"))
        (self.tmp / "mcu").mkdir(parents=True)
        # what bswgen generates from mcudb device_header for the S32K144 (superset header, ARCH-03)
        (self.tmp / "mcu" / "mcuDerivative.h").write_text(
            '#pragma once\n#include "3rdparty/nxp/S32K148.h"\n', encoding="utf-8")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def facts(self, bits: int, regions: int = 8, nrgd: int = 0):
        (self.tmp / "mcu" / "derivativeFacts.h").write_text(
            f"#pragma once\n#define NX_NVIC_PRIORITY_BITS {bits}\n"
            f"#define NX_MPU_REGIONS {regions}\n#define NX_MPU_CESR_NRGD {nrgd}\n", encoding="utf-8")

    def compile(self, body: str) -> subprocess.CompletedProcess:
        source = self.tmp / "probe.cpp"
        source.write_text('#include "mcu/mcu.h"\n' + textwrap.dedent(body), encoding="utf-8")
        args = [ARM_GPP, "-mcpu=cortex-m4", "-mthumb", "-std=c++17", "-fno-exceptions", "-fno-rtti",
                "-Wall", "-Wextra", "-Werror", "-c", str(source), "-o", str(self.tmp / "probe.o")]
        args += [f"-I{p}" for p in self.includes(self.tmp)]
        return subprocess.run(args, capture_output=True, text=True)

    def test_priority_bits_come_from_the_database(self):
        """4 bits (S32K144 in mcudb) equal the device header value, so both static_asserts hold."""
        self.facts(bits=4)
        out = self.compile("""
            static_assert(FEATURE_NVIC_PRIO_BITS == 4, "mcudb nvic_priority_bits of the S32K144");
            static_assert(__NVIC_PRIO_BITS == 4, "S32K148.h of OpenBSW");
            """)
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_database_wins_over_the_device_header(self):
        """A derivative with 2 bits (S32K116 case) keeps 2 although the device header says 4."""
        self.facts(bits=2)
        out = self.compile("""
            static_assert(FEATURE_NVIC_PRIO_BITS == 2, "value of the derivative database");
            static_assert(__NVIC_PRIO_BITS == 4, "the device header still says something else");
            """)
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_mpu_regions_reach_the_board_port(self):
        """The MPU region count of the derivative is visible through mcu.h (safeMemory/mpu.h uses it)."""
        self.facts(bits=4, regions=16, nrgd=2)
        out = self.compile("""
            static_assert(NX_MPU_REGIONS == 16, "region descriptors of the derivative");
            static_assert(NX_MPU_CESR_NRGD == 2, "CESR[NRGD] code of 16 regions");
            static_assert(MPU_RGD_COUNT == 16, "RGD[] of the S32K148 device header");
            """)
        self.assertEqual(out.returncode, 0, out.stderr)

    def test_without_the_generated_facts_the_build_stops(self):
        """No generated facts header: mcu.h does not fall back to the device header."""
        out = self.compile("int probe = FEATURE_NVIC_PRIO_BITS;\n")
        self.assertNotEqual(out.returncode, 0)
        self.assertIn("mcu/derivativeFacts.h", out.stderr)


