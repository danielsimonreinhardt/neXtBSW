"""Compile probes of the family mcu.h of platforms/s32k1xx (PLAT-11, ARCH-16, PLAT-32).

DeviceHeaderCompileTest: the checked-in S32K116 device header (NXP RTD headers from Zephyr hal_nxp, BSD-3-Clause, with
the adapter generated by mcudb/tools/rtd_adapter.py). Needs only arm-none-eabi-g++ - no workstation files.
DerivativeFactsTest: FEATURE_NVIC_PRIO_BITS comes from the derivative database, not from the device header
(ARCH-16); needs only arm-none-eabi-g++ and the S32K148 header OpenBSW ships.
SvdCrossCheckTest: optional cross-check of the adapter against the header svd2header.py generates from the Keil SVD
(PLAT-11 path, workstation level); skipped without NX_SVD_DIR.

Builds OpenBSW s32k1xx driver sources for Cortex-M0+ against 3rdparty/nxp/S32K116.h, using only this module's
mcu/mcu.h (no board port). It also records, as expectations, the places where an OpenBSW driver does not survive the
derivative change (findings for PLAT-12).

Run: .venv/Scripts/python -m unittest platforms/s32k1xx/bsp/bspMcu/test/test_device_header.py
     (needs arm-none-eabi-g++ from PATH or NX_ARM_GCC_BIN)
"""

