function mdlFile = swc_create(swcDir, varargin)
%SWC_CREATE Creates the Simulink model of a software component from its swc/<Swc>/swc.yaml (RTE-07).
%   swc_create('swc/NewSwc') reads swc/NewSwc/swc.yaml (runnables with period, ports with direction,
%   type and the runnables using them; schema and checks in tools/swc/swc_yaml.py) and writes
%   swc/NewSwc/NewSwc.slx following the model rules of swc/README.md:
%     - export-function model, one function-call inport per runnable (sample time = period)
%     - one function-call subsystem <Swc>_task<Period>ms per runnable (TOOL-180; two runnables of the same
%       period: <Swc>_task<Period>ms_<Runnable>), with an In/Out block per port it uses, named after the port;
%       required ports (root inports) fan out to every reader. Models of older versions have
%       <Runnable>_Subsystem; tools find the subsystem by its trigger line (swc_runnable_subsystem)
%     - Inport blocks green, Outport blocks red (TOOL-180), at the root and in the subsystems
%     - root inports: runnables first, then the ports in the order of swc.yaml
%     - unused In blocks end in a Terminator, unconnected Out blocks get a Ground, so a new model
%       builds right away (swc_build); replace them with the logic
%     - named data types of swc.yaml (types:, RTE-15): records (Simulink.Bus, root ports as nonvirtual buses),
%       enumerations (Simulink.defineIntEnumType) and fixed point (named Simulink.NumericType), all imported
%       from Rte_Type.h; their definitions go to <Swc>_types.m next to the model (generated by swc_yaml.py,
%       run by the PreLoadFcn of the model and by swc_load_init); unconnected record/enumeration outputs get
%       a Constant of their type instead of a Ground
%     - AUTOSAR mapping (autosar.api.create default, ExplicitReceive/ExplicitSend) and code settings: swc_prepare,
%       the same function the Studio's model import runs on its copy of an existing model (TOOL-135)
%   The model is created once; afterwards the .slx is the master and is edited in Simulink.
%
%   Options (name/value):
%     'Overwrite'  false (default): error if the .slx exists; true: replace it
%     'Logic'      function handle or name, called as logic(mdl, spec) after the subsystems and the
%                  root wiring exist and before placeholders and mapping (test data, e.g. DemoSwc)
%     'Autosar'    true (default): AUTOSAR mapping and code settings; false: plain Simulink model
%     'Spec'       already decoded description (struct as from swc_yaml.py json); skips Python
%     'Python'     Python interpreter for swc_yaml.py (default: NX_PYTHON, then .venv of the repo or
%                  of a parent folder, then python on the PATH)
%
%   The library of the component template (swc/template/NxSwcLib.slx, e.g. SensorQualifier) is put on
%   the path, and the QLF_* constants are loaded (swc_load_qlf) if the logic needs them.

opts = parseOptions(varargin{:});
swcDir = char(java.io.File(char(swcDir)).getCanonicalPath());
if ~isfolder(swcDir)
    error('swc_create:noDir', 'folder %s not found', swcDir);
end
repo = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(repo, 'swc', 'template'));   % NxSwcLib (library blocks of new components)

if isempty(opts.Spec)
    spec = swc_read_spec(swcDir, opts.Python);
else
    spec = opts.Spec;
end
mdl = spec.name;
[~, folderName] = fileparts(swcDir);
if ~strcmp(mdl, folderName)
    error('swc_create:name', 'component %s must be in a folder of the same name, not %s', mdl, folderName);
end

mdlFile = fullfile(swcDir, [mdl '.slx']);
if isfile(mdlFile) && ~opts.Overwrite
    error('swc_create:exists', ['%s exists; the model is the master after creation. ' ...
        'Pass ''Overwrite'', true to create it again.'], mdlFile);
end
if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
if isfile(mdlFile)
    delete(mdlFile);
end

% RTE-15: named data types of swc.yaml (types:) - their MATLAB definitions <Swc>_types.m next to the model, defined
% now and by the PreLoadFcn of the model (and swc_load_init) whenever it is loaded again
typesFn = '';
enums = false;
if isfield(spec, 'types_file') && isstruct(spec.types_file) && ~isempty(spec.types_file)
    typesFile = fullfile(swcDir, spec.types_file.name);
    fid = fopen(typesFile, 'w');
    fwrite(fid, spec.types_file.text);
    fclose(fid);
    [~, typesFn] = fileparts(typesFile);
    addpath(swcDir);
    clear(typesFn);                                   % a file written again in this session
    feval(typesFn);
    types = toCell(spec.types);
    enums = any(cellfun(@(t) strcmp(t.kind, 'enum'), types));
end

runnables = toCell(spec.runnables);
ports = toCell(spec.ports);
parameters = {};
if isfield(spec, 'parameters')
    parameters = toCell(spec.parameters);   % RTE-03: calibration parameters, values from <Swc>_data.m
end

% base rate of the model: greatest common divisor of the runnable periods
baseMs = 0;
for r = 1:numel(runnables)
    baseMs = gcd(baseMs, round(runnables{r}.period_ms));
end

new_system(mdl);
closeOnError = onCleanup(@() closeIfLoaded(mdl));
set_param(mdl, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
    'FixedStep', sprintf('%g', baseMs / 1000), 'StopTime', '10', 'IsExportFunctionModel', 'off');
set_param(mdl, 'ProdHWDeviceType', 'ARM Compatible->ARM Cortex-M');
if isfield(spec, 'description') && ~isempty(spec.description)
    set_param(mdl, 'Description', spec.description);
end
if ~isempty(typesFn)
    % RTE-15: the named types exist before the model loads (the folder is on the path in swc_build, swc_prepare,
    % swc_ports and swc_mil_test; swc_load_init runs the file by its full path as well)
    set_param(mdl, 'PreLoadFcn', sprintf('if exist(''%s'', ''file'') == 2, %s(); end', typesFn, typesFn));
end
if enums
    % an enumeration of Rte_Type.h in a MATLAB Function block simulates only if the simulation target defines the
    % imported type itself (RTE-04); the generated code keeps including Rte_Type.h
    set_param(mdl, 'SimGenImportedTypeDefs', 'on');
end

%% ---- root ports: runnables, then ports in the order of swc.yaml ----
rowIn = 0;
rowOut = 0;
for r = 1:numel(runnables)
    h = add_block('simulink/Sources/In1', [mdl '/' runnables{r}.name], 'Position', rootPos(30, rowIn), ...
        'BackgroundColor', 'green');
    set_param(h, 'OutputFunctionCall', 'on', 'SampleTime', runnables{r}.sample_time);
    rowIn = rowIn + 1;
end
for p = 1:numel(ports)
    port = ports{p};
    % RTE-25: array ports get their number of elements (swc.yaml dimension, resolved by swc_yaml.py)
    dims = '1';
    if isfield(port, 'dimension') && ~isempty(port.dimension)
        dims = num2str(port.dimension);
    end
    if strcmp(port.direction, 'in')
        h = add_block('simulink/Sources/In1', [mdl '/' port.name], 'Position', rootPos(30, rowIn), ...
            'BackgroundColor', 'green');
        set_param(h, 'OutDataTypeStr', port.simulink_type, 'PortDimensions', dims);
        rowIn = rowIn + 1;
    else
        h = add_block('simulink/Sinks/Out1', [mdl '/' port.name], 'Position', rootPos(620, rowOut), ...
            'BackgroundColor', 'red');
        set_param(h, 'OutDataTypeStr', port.simulink_type);
        if ~strcmp(dims, '1')
            set_param(h, 'PortDimensions', dims);
        end
        rowOut = rowOut + 1;
    end
    if startsWith(port.simulink_type, 'Bus:')
        set_param(h, 'BusOutputAsStruct', 'on');      % RTE-15: a record is a nonvirtual bus (a struct in C)
    end
end

%% ---- one function-call subsystem per runnable ----
subsystems = subsystemNames(mdl, runnables);
top = 40;
for r = 1:numel(runnables)
    rname = runnables{r}.name;
    sname = subsystems{r};
    sys = [mdl '/' sname];
    users = cellfun(@(q) any(strcmp(toCellstr(q.runnables), rname)), ports);
    ins = ports(users & cellfun(@(q) strcmp(q.direction, 'in'), ports));
    outs = ports(users & cellfun(@(q) strcmp(q.direction, 'out'), ports));
    height = max(80, 40 * max(numel(ins), numel(outs)) + 40);
    add_block('simulink/Ports & Subsystems/Function-Call Subsystem', sys, ...
        'Position', [250 top 430 top + height]);
    clearSubsystem(sys);
    % periodic trigger with the runnable period: blocks that use the elapsed time (SensorQualifier of
    % NxSwcLib: Weighted Sample Time Math) are not allowed in a merely triggered subsystem of an
    % export-function model. Consequence for model-in-the-loop tests: the function-call inports then
    % call the runnables every period by themselves; a Dataset element with explicit call times is
    % rejected, it must be [] (SwcCreateTest.simulateQlfTestSwc).
    set_param([sys '/function'], 'SampleTimeType', 'periodic', 'SampleTime', runnables{r}.sample_time);
    for k = 1:numel(ins)
        add_block('simulink/Sources/In1', [sys '/' ins{k}.name], 'Position', rootPos(40, k - 1), ...
            'Port', num2str(k), 'BackgroundColor', 'green');
    end
    for k = 1:numel(outs)
        add_block('simulink/Sinks/Out1', [sys '/' outs{k}.name], 'Position', rootPos(600, k - 1), ...
            'Port', num2str(k), 'BackgroundColor', 'red');
    end
    add_line(mdl, [rname '/1'], [sname '/Trigger'], 'autorouting', 'on');
    for k = 1:numel(ins)
        add_line(mdl, [ins{k}.name '/1'], sprintf('%s/%d', sname, k), 'autorouting', 'on');
    end
    for k = 1:numel(outs)
        add_line(mdl, sprintf('%s/%d', sname, k), [outs{k}.name '/1'], 'autorouting', 'on');
    end
    top = top + height + 40;
end
% root ports no runnable uses cannot occur: swc_yaml.py requires at least one runnable per port

%% ---- calibration parameters (RTE-03): model workspace, value from <Swc>_data.m ----
% The logic uses them by name (e.g. Gain 'FilterAlpha'); a parameter the model does not use gets no type in the
% ARXML, which tools/rtegen reports.
mw = get_param(mdl, 'ModelWorkspace');
for k = 1:numel(parameters)
    prm = Simulink.Parameter(reshape(double(parameters{k}.values), 1, []));
    prm.DataType = parameters{k}.simulink_type;
    assignin(mw, parameters{k}.name, prm);
end

%% ---- logic (optional), placeholders, mapping ----
if ~isempty(opts.Logic)
    logic = opts.Logic;
    if ischar(logic) || isstring(logic)
        logic = str2func(char(logic));
    end
    logic(mdl, spec);
end
defaults = placeholderValues(spec, ports);
for r = 1:numel(runnables)
    % found by its trigger: the logic may rename it
    addPlaceholders(swc_runnable_subsystem(mdl, runnables{r}.name), defaults);
end

set_param(mdl, 'IsExportFunctionModel', 'on');
save_system(mdl, mdlFile);
if opts.Autosar
    swc_prepare(mdl, spec);
    if ~isempty(parameters)
        swc_map_parameters(mdl, cellfun(@(q) q.name, parameters, 'UniformOutput', false), spec.parameter_port);
    end
    save_system(mdl, mdlFile);
end
close_system(mdl, 0);
clear closeOnError;
fprintf('created %s (%d runnables, %d ports, %d parameters)\n', mdlFile, numel(runnables), numel(ports), ...
    numel(parameters));
end

%% ======================================================================================
function opts = parseOptions(varargin)
p = inputParser;
p.addParameter('Overwrite', false, @(v) islogical(v) || isnumeric(v));
p.addParameter('Logic', [], @(v) isempty(v) || ischar(v) || isstring(v) || isa(v, 'function_handle'));
p.addParameter('Autosar', true, @(v) islogical(v) || isnumeric(v));
p.addParameter('Spec', [], @(v) isempty(v) || isstruct(v));
p.addParameter('Python', '', @(v) ischar(v) || isstring(v));
p.parse(varargin{:});
opts = p.Results;
opts.Python = char(opts.Python);
end

function c = toCell(v)
% jsondecode gives a struct array for uniform objects, a cell array otherwise, [] for an empty list
if isempty(v)
    c = {};
elseif iscell(v)
    c = reshape(v, 1, []);
else
    c = num2cell(reshape(v, 1, []));
end
end

function c = toCellstr(v)
if ischar(v)
    c = {v};
else
    c = cellstr(v);
end
end

function names = subsystemNames(mdl, runnables)
% TOOL-180: the subsystem of a runnable is named after its rate, <Swc>_task<Period>ms; runnables sharing a
% period get their name appended, so every name stays unique.
periods = cellfun(@(q) round(q.period_ms), runnables);
names = cell(size(runnables));
for r = 1:numel(runnables)
    names{r} = sprintf('%s_task%dms', mdl, periods(r));
    if nnz(periods == periods(r)) > 1
        names{r} = [names{r} '_' runnables{r}.name];
    end
end
end

function pos = rootPos(x, row)
y = 40 + 50 * row;
pos = [x y x + 30 y + 14];
end

function clearSubsystem(sys)
% Removes the default In1 -> Out1 connection of a new function-call subsystem.
lines = find_system(sys, 'SearchDepth', 1, 'FindAll', 'on', 'Type', 'line');
delete_line(lines);
delete_block([sys '/In1']);
delete_block([sys '/Out1']);
end

function defaults = placeholderValues(spec, ports)
% RTE-15: provided ports of a record or enumeration type get a Constant of their type instead of a Ground (a Ground
% is no bus, and an enumeration starts at its default literal): port name -> {OutDataTypeStr, Value}
defaults = containers.Map();
literal = containers.Map();
if isfield(spec, 'types')
    types = toCell(spec.types);
    for k = 1:numel(types)
        if strcmp(types{k}.kind, 'enum')
            literal(types{k}.name) = types{k}.default;
        end
    end
end
for p = 1:numel(ports)
    port = ports{p};
    if ~isfield(port, 'type_kind') || strcmp(port.direction, 'in')
        continue;
    end
    switch port.type_kind
        case 'record'
            defaults(port.name) = {port.simulink_type, '0'};       % 0: the ground value of every element
        case 'enum'
            defaults(port.name) = {port.simulink_type, sprintf('%s.%s', port.type, literal(port.type))};
    end
end
end

function addPlaceholders(sys, defaults)
% Terminator behind every unused In block, Ground before every unconnected Out block: the new model
% compiles and builds without warnings about unconnected ports until the logic replaces them. A record or an
% enumeration gets a Constant of its type (defaults, RTE-15).
blocks = find_system(sys, 'SearchDepth', 1, 'BlockType', 'Inport');
for k = 1:numel(blocks)
    pc = get_param(blocks{k}, 'PortConnectivity');
    if isempty(pc(end).DstBlock)
        name = get_param(blocks{k}, 'Name');
        pos = get_param(blocks{k}, 'Position');
        add_block('simulink/Sinks/Terminator', [sys '/' name '_Unused'], ...
            'Position', [pos(3) + 60, pos(2) - 3, pos(3) + 80, pos(4) + 3]);
        add_line(sys, [name '/1'], [name '_Unused/1']);
    end
end
blocks = find_system(sys, 'SearchDepth', 1, 'BlockType', 'Outport');
for k = 1:numel(blocks)
    pc = get_param(blocks{k}, 'PortConnectivity');
    if pc(1).SrcBlock == -1
        name = get_param(blocks{k}, 'Name');
        pos = get_param(blocks{k}, 'Position');
        if isKey(defaults, name)
            value = defaults(name);
            add_block('simulink/Sources/Constant', [sys '/' name '_Default'], ...
                'Position', [pos(1) - 120, pos(2) - 3, pos(1) - 60, pos(4) + 3], ...
                'OutDataTypeStr', value{1}, 'Value', value{2});
        else
            add_block('simulink/Sources/Ground', [sys '/' name '_Default'], ...
                'Position', [pos(1) - 80, pos(2) - 3, pos(1) - 60, pos(4) + 3]);
        end
        add_line(sys, [name '_Default/1'], [name '/1']);
    end
end
end

function closeIfLoaded(mdl)
if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
end
