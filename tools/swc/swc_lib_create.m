function libFile = swc_lib_create(libFile)
%SWC_LIB_CREATE Creates swc/template/NxSwcLib.slx, the block library for new components (RTE-07).
%   The library is generated from this script, so its logic can be reviewed as text; after a change
%   run it again (matlab -batch "addpath tools/swc; swc_lib_create") and check in the .slx.
%   swc_lib_create(file) writes the library to another file (SwcCreateTest compares it with the
%   checked-in one).
%
%   Blocks:
%     SensorQualifier  signal qualifier of a measured value (range check with debounce time)
%
%   SensorQualifier (inputs Value and InQlf, output Qlf as uint8, parameters min_value, max_value,
%   debounce_ms). One value with precedence instead of a bit OR, as the CAN qualifiers of the RTE
%   (doc/architecture/signal-qualifier.md):
%     1. InQlf ~= QLF_OK            -> InQlf unchanged (the source is not valid: QLF_ERROR, _TIMEOUT,
%                                      _CRC, _ALIVE, QLF_NOT_AVAILABLE (no source, RTE-28) or
%                                      QLF_DEBOUNCE; a range check says nothing then)
%     2. value outside [min_value, max_value] for at least debounce_ms -> QLF_ERROR_RANGE
%     3. value outside the range, debounce time still running         -> QLF_DEBOUNCE
%     4. otherwise                                                      -> QLF_OK
%   The range is inclusive. NaN is not detected: the models build with SupportNonFinite off, and the
%   code generator may turn the range check into (u < min) || (u > max).
%   The debounce time runs from the first call with the value outside the range (0 ms at that call)
%   and grows by the period of the calling runnable, which the block takes from its sample time
%   (Weighted Sample Time Math, folded to a constant in the code). That needs a periodic trigger of the
%   runnable subsystem, which swc_create sets. debounce_ms = 0 reports at once, debounce_ms = 30 at a
%   10 ms runnable in the fourth call. Healing is immediate: the first call with the value back in
%   range (or with a source error) restarts the debounce time. This is the turn-on delay of the old
%   BACE_lib (BACE_TurnOnDelay: output after the input was true for T) combined with
%   GenerateQualifier (st_OutOfRange -> error) of the MBDT project, and the timing of the RTE's
%   E2E debounce (errorMs from 0 at the first error, error when errorMs >= debounceMs).
%   InQlf: connect the qualifier of the source (e.g. capture.<Channel>.qlf, can.qlf.<Message>), or a
%   Constant QLF_OK when the source has none. The QLF_* values come from Rte_Qlf.m (swc_load_qlf).

lib = 'NxSwcLib';
repo = fileparts(fileparts(fileparts(mfilename('fullpath'))));
if nargin < 1 || isempty(libFile)
    libFile = fullfile(repo, 'swc', 'template', [lib '.slx']);
end
libFile = char(libFile);
if bdIsLoaded(lib)
    close_system(lib, 0);
end
if isfile(libFile)
    delete(libFile);
end

new_system(lib, 'Library');
cleanup = onCleanup(@() closeIfLoaded(lib));
set_param(lib, 'Description', ['SPDX-License-Identifier: Apache-2.0. neXtBSW block library for ' ...
    'software components (RTE-07), generated by tools/swc/swc_lib_create.m - do not edit by hand.']);

addSensorQualifier([lib '/SensorQualifier']);

set_param(lib, 'EnableLBRepository', 'on');
save_system(lib, libFile);
close_system(lib, 0);
fprintf('created %s\n', libFile);
end

function addSensorQualifier(blk)
add_block('simulink/Ports & Subsystems/Subsystem', blk, 'Position', [100 100 260 180]);
lines = find_system(blk, 'SearchDepth', 1, 'FindAll', 'on', 'Type', 'line');
delete_line(lines);
delete_block([blk '/In1']);
delete_block([blk '/Out1']);

add_block('simulink/Sources/In1', [blk '/Value'], 'Position', [30 103 60 117]);
add_block('simulink/Sources/In1', [blk '/InQlf'], 'Position', [30 353 60 367], 'Port', '2');
add_block('simulink/Sinks/Out1', [blk '/Qlf'], 'Position', [1090 353 1120 367], 'OutDataTypeStr', 'uint8');

%% range check: out of range = NOT (min_value <= Value <= max_value)
add_block('simulink/Logic and Bit Operations/Compare To Constant', [blk '/AtLeastMin'], ...
    'Position', [120 80 180 110], 'relop', '>=', 'const', 'min_value');
add_block('simulink/Logic and Bit Operations/Compare To Constant', [blk '/AtMostMax'], ...
    'Position', [120 130 180 160], 'relop', '<=', 'const', 'max_value');
add_block('simulink/Logic and Bit Operations/Logical Operator', [blk '/OutOfRange'], ...
    'Position', [230 95 260 145], 'Operator', 'NAND', 'Inputs', '2');
add_line(blk, 'Value/1', 'AtLeastMin/1', 'autorouting', 'on');
add_line(blk, 'Value/1', 'AtMostMax/1', 'autorouting', 'on');
add_line(blk, 'AtLeastMin/1', 'OutOfRange/1', 'autorouting', 'on');
add_line(blk, 'AtMostMax/1', 'OutOfRange/2', 'autorouting', 'on');

%% source qualifier
add_block('simulink/Signal Attributes/Data Type Conversion', [blk '/InQlfU8'], ...
    'Position', [120 345 180 375], 'OutDataTypeStr', 'uint8', 'SaturateOnIntegerOverflow', 'on');
add_block('simulink/Logic and Bit Operations/Compare To Constant', [blk '/SourceOk'], ...
    'Position', [230 280 290 310], 'relop', '==', 'const', 'QLF_OK');
add_line(blk, 'InQlf/1', 'InQlfU8/1');
add_line(blk, 'InQlfU8/1', 'SourceOk/1', 'autorouting', 'on');

add_block('simulink/Logic and Bit Operations/Logical Operator', [blk '/Pending'], ...
    'Position', [330 110 360 160], 'Operator', 'AND', 'Inputs', '2');
add_line(blk, 'OutOfRange/1', 'Pending/1', 'autorouting', 'on');
add_line(blk, 'SourceOk/1', 'Pending/2', 'autorouting', 'on');

%% debounce time (turn-on delay): elapsed ms since the first pending call, capped at debounce_ms
add_block('simulink/Discrete/Unit Delay', [blk '/ElapsedMs'], 'Position', [420 200 460 240], ...
    'InitialCondition', '0', 'SampleTime', '-1');
add_block('simulink/Math Operations/Weighted Sample Time Math', [blk '/PeriodMs'], ...
    'Position', [420 260 470 290], 'TsampMathOp', 'Ts Only', 'weightValue', '1000', ...
    'OutDataTypeStr', 'uint32', 'RndMeth', 'Nearest');
add_block('simulink/Math Operations/Sum', [blk '/AddPeriod'], 'Position', [520 215 540 275], ...
    'Inputs', '++', 'OutDataTypeStr', 'uint32', 'SaturateOnIntegerOverflow', 'off');
add_block('simulink/Sources/Constant', [blk '/DebounceMs'], 'Position', [520 300 580 320], ...
    'Value', 'debounce_ms', 'OutDataTypeStr', 'uint32');
add_block('simulink/Math Operations/MinMax', [blk '/Cap'], 'Position', [620 220 650 320], ...
    'Function', 'min', 'Inputs', '2');
add_block('simulink/Sources/Constant', [blk '/ZeroMs'], 'Position', [620 350 650 370], ...
    'Value', '0', 'OutDataTypeStr', 'uint32');
add_block('simulink/Signal Routing/Switch', [blk '/NextElapsedMs'], 'Position', [700 220 730 370], ...
    'Criteria', 'u2 ~= 0', 'InputSameDT', 'off');
set_param([blk '/ElapsedMs'], 'Orientation', 'left');
add_block('simulink/Logic and Bit Operations/Compare To Constant', [blk '/Debounced'], ...
    'Position', [520 140 580 170], 'relop', '>=', 'const', 'debounce_ms');
add_block('simulink/Logic and Bit Operations/Logical Operator', [blk '/RangeError'], ...
    'Position', [640 100 670 170], 'Operator', 'AND', 'Inputs', '2');

add_line(blk, 'ElapsedMs/1', 'AddPeriod/1', 'autorouting', 'on');
add_line(blk, 'PeriodMs/1', 'AddPeriod/2', 'autorouting', 'on');
add_line(blk, 'AddPeriod/1', 'Cap/1', 'autorouting', 'on');
add_line(blk, 'DebounceMs/1', 'Cap/2', 'autorouting', 'on');
add_line(blk, 'Cap/1', 'NextElapsedMs/1', 'autorouting', 'on');
add_line(blk, 'Pending/1', 'NextElapsedMs/2', 'autorouting', 'on');
add_line(blk, 'ZeroMs/1', 'NextElapsedMs/3', 'autorouting', 'on');
add_line(blk, 'NextElapsedMs/1', 'ElapsedMs/1', 'autorouting', 'on');
add_line(blk, 'ElapsedMs/1', 'Debounced/1', 'autorouting', 'on');
add_line(blk, 'Pending/1', 'RangeError/1', 'autorouting', 'on');
add_line(blk, 'Debounced/1', 'RangeError/2', 'autorouting', 'on');

%% one value with precedence: source error > QLF_ERROR_RANGE > QLF_DEBOUNCE > QLF_OK
qlfConst = {'QlfOk', 'QLF_OK', 420; 'QlfDebounce', 'QLF_DEBOUNCE', 460; 'QlfErrorRange', 'QLF_ERROR_RANGE', 500};
for k = 1:size(qlfConst, 1)
    add_block('simulink/Sources/Constant', [blk '/' qlfConst{k, 1}], ...
        'Position', [760 qlfConst{k, 3} 860 qlfConst{k, 3} + 20], 'Value', qlfConst{k, 2}, 'OutDataTypeStr', 'uint8');
end
add_block('simulink/Signal Routing/Switch', [blk '/SelectPending'], 'Position', [900 400 930 500], ...
    'Criteria', 'u2 ~= 0', 'InputSameDT', 'off');
add_block('simulink/Signal Routing/Switch', [blk '/SelectRange'], 'Position', [960 330 990 450], ...
    'Criteria', 'u2 ~= 0', 'InputSameDT', 'off');
add_block('simulink/Signal Routing/Switch', [blk '/SelectSource'], 'Position', [1030 300 1060 420], ...
    'Criteria', 'u2 ~= 0', 'InputSameDT', 'off');
add_line(blk, 'QlfDebounce/1', 'SelectPending/1', 'autorouting', 'on');
add_line(blk, 'Pending/1', 'SelectPending/2', 'autorouting', 'on');
add_line(blk, 'QlfOk/1', 'SelectPending/3', 'autorouting', 'on');
add_line(blk, 'QlfErrorRange/1', 'SelectRange/1', 'autorouting', 'on');
add_line(blk, 'RangeError/1', 'SelectRange/2', 'autorouting', 'on');
add_line(blk, 'SelectPending/1', 'SelectRange/3', 'autorouting', 'on');
add_line(blk, 'SelectRange/1', 'SelectSource/1', 'autorouting', 'on');
add_line(blk, 'SourceOk/1', 'SelectSource/2', 'autorouting', 'on');
add_line(blk, 'InQlfU8/1', 'SelectSource/3', 'autorouting', 'on');
add_line(blk, 'SelectSource/1', 'Qlf/1', 'autorouting', 'on');

%% mask
m = Simulink.Mask.create(blk);
m.Type = 'neXtBSW Sensor Qualifier';
m.Description = sprintf(['Signal qualifier of a measured value (RTE-07). One value with precedence:\n' ...
    '1. InQlf ~= QLF_OK: InQlf unchanged (source not valid)\n' ...
    '2. Value outside [min_value, max_value] for at least debounce_ms: QLF_ERROR_RANGE\n' ...
    '3. Value outside, debounce time running: QLF_DEBOUNCE\n' ...
    '4. otherwise QLF_OK\n' ...
    'The range is inclusive (NaN is not detected). The debounce time grows by the period of the calling ' ...
    'runnable (sample time) from 0 at the first call outside the range; debounce_ms = 0 reports at ' ...
    'once. Healing is immediate. Without a source qualifier connect a Constant QLF_OK to InQlf.']);
m.addParameter('Name', 'min_value', 'Prompt', 'Lowest valid value (inclusive, unit of Value)', ...
    'Type', 'edit', 'Value', '0');
m.addParameter('Name', 'max_value', 'Prompt', 'Highest valid value (inclusive, unit of Value)', ...
    'Type', 'edit', 'Value', '4095');
m.addParameter('Name', 'debounce_ms', 'Prompt', 'Debounce time of a range violation [ms] (0 = at once)', ...
    'Type', 'edit', 'Value', '0');
m.Initialization = sprintf([ ...
    'if ~isscalar(debounce_ms) || ~isreal(debounce_ms) || debounce_ms < 0 || debounce_ms ~= floor(debounce_ms) || debounce_ms > 2147483647\n' ...
    '    error(''SensorQualifier: debounce_ms must be a whole number of milliseconds from 0 to 2147483647'');\n' ...
    'end\n' ...
    'if ~isscalar(min_value) || ~isscalar(max_value) || ~(min_value <= max_value)\n' ...
    '    error(''SensorQualifier: min_value must not be greater than max_value'');\n' ...
    'end\n']);
m.Display = sprintf(['disp(''SensorQualifier'');\n' ...
    'port_label(''input'', 1, ''Value'');\n' ...
    'port_label(''input'', 2, ''InQlf'');\n' ...
    'port_label(''output'', 1, ''Qlf'');\n']);
end

function closeIfLoaded(name)
if bdIsLoaded(name)
    close_system(name, 0);
end
end
