"""Host tests of the update workflow (TOOL-64, doc/architecture/customer-project.md gap N9).

Everything runs against **synthetic git repositories in %TEMP%**, never against this repository and never
against a board or real network (a "fetch"/"clone" here always talks to a local path, which git treats like any
other remote - no traffic leaves the machine). Two invented neXtBSW releases (`1.0.0` and `1.1.0`, with an
intermediate `1.0.5` to exercise "skipped releases") live as two commits, each an annotated tag on `master`, in
one invented upstream repository - exactly the shape of a real neXtBSW release history. The synthetic trees carry
tiny stub `tools/bswgen/bswgen.py` and `tools/rtegen/rtegen.py` scripts instead of the real generators (the real
ones need a full derivative/board database that has nothing to do with what this module is responsible for): the
scripts differ between the two releases so `nxupdate` has something real to diff, in one file that looks
field-relevant (`memory_layout.h`, `can_ids.h`) and one that does not (`notes.txt`, `tasks.h`) - proving the
classifier does not flag everything indiscriminately.

`TestMigrateWiring` is the exception: it points `update.run_migrate` at *this* repository's own `tools/nxconfig`
(read-only, `write=False` only) to prove the migration step is wired to a real migration engine, not just to the
synthetic stand-ins used everywhere else - the migration logic itself is TOOL-66's own tests, not retested here.
"""

