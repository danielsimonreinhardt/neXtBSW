def git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    done = subprocess.run([GIT, "-C", str(repo), *IDENTITY, *args], capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=60)
    if done.returncode != 0:
        raise AssertionError(f"git {' '.join(args)} in {repo}: {done.returncode} {done.stderr.strip()}")
    return done


@unittest.skipUnless(GIT, "git is not installed")
class UpdateWorkflow(unittest.TestCase):
    """An invented workspace `acme-ctl` pinned to an invented upstream `nextbsw-upstream` in %TEMP%."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="nxupdate-test-")).resolve()
        self.upstream = self.tmp / "nextbsw-upstream"
        self._init_repo(self.upstream)
        self._release(self.upstream, "1.0.0")
        self._release(self.upstream, "1.0.5")
        self._release(self.upstream, "1.1.0")

        self.ws = self.tmp / "acme-ctl"
        self.ws.mkdir(parents=True)
        self.tree = self.ws / "nextbsw"
        git(self.tmp, "clone", "--quiet", "--branch", "v1.0.0", str(self.upstream), str(self.tree))

        (self.ws / "nextbsw.yaml").write_text(
            "schema_version: 1\nnextbsw:\n  version: 1.0.0\n  source: submodule\n  path: nextbsw\n",
            encoding="utf-8")
        project_dir = self.ws / "projects" / "demo"
        project_dir.mkdir(parents=True)
        (project_dir / "project.yaml").write_text("name: demo\nboard: nowhere\n", encoding="utf-8")

    def tearDown(self):
        update.rmtree(self.tmp)

    # ------------------------------------------------------------------ fixtures

    def _init_repo(self, folder: Path) -> None:
        folder.mkdir(parents=True)
        git(folder, "init", "-q")
        git(folder, "checkout", "-q", "-B", "master")

    def _release(self, folder: Path, version: str) -> None:
        (folder / "VERSION").write_text(f"{version}\n", encoding="utf-8")
        (folder / "tools" / "nxconfig").mkdir(parents=True, exist_ok=True)
        (folder / "tools" / "bswgen").mkdir(parents=True, exist_ok=True)
        (folder / "tools" / "rtegen").mkdir(parents=True, exist_ok=True)
        (folder / "tools" / "bswgen" / "bswgen.py").write_text(BSWGEN_STUB[version], encoding="utf-8")
        (folder / "tools" / "rtegen" / "rtegen.py").write_text(RTEGEN_STUB[version], encoding="utf-8")
        changelog = folder / "CHANGELOG.md"
        previous = changelog.read_text(encoding="utf-8") if changelog.is_file() else ""
        changelog.write_text(f"## {version}\n\nsynthetic release {version}\n\n{previous}", encoding="utf-8")
        git(folder, "add", "-A")
        git(folder, "commit", "-q", "-m", f"release {version}")
        git(folder, "tag", "-a", f"v{version}", "-m", f"release {version}")

    # ------------------------------------------------------------------ dry run

    def test_dry_run_changes_nothing_and_reports_the_diff(self):
        before_pin = (self.ws / "nextbsw.yaml").read_text(encoding="utf-8")
        result = update.run(self.ws, "1.1.0", python=PYTHON)

        self.assertFalse(result.written)
        self.assertFalse(result.committed)
        self.assertIsNone(result.report_file)
        self.assertEqual((self.ws / "nextbsw.yaml").read_text(encoding="utf-8"), before_pin, "dry run must not "
                         "touch the pin file")
        self.assertTrue(result.pin_status.ok, f"target tag should check out clean: {result.pin_status.text}")
        self.assertFalse((self.ws / "doc").exists(), "dry run must not create doc/nextbsw-updates")

        by_path = {d.path.replace("\\", "/"): d for d in result.file_diffs}
        self.assertIn("projects/demo/board/memory_layout.h", by_path)
        self.assertIn("projects/demo/rte/can_ids.h", by_path)
        self.assertTrue(by_path["projects/demo/board/memory_layout.h"].field_relevant)
        self.assertTrue(by_path["projects/demo/rte/can_ids.h"].field_relevant)
        self.assertIn("projects/demo/board/notes.txt", by_path)
        self.assertFalse(by_path["projects/demo/board/notes.txt"].field_relevant, "an unrelated stub file must not be "
                         "flagged - the classifier would be useless if it flagged everything")
        self.assertFalse(by_path["projects/demo/rte/tasks.h"].field_relevant)

        self.assertIn("FLASH_ORIGIN", by_path["projects/demo/board/memory_layout.h"].diff)
        self.assertEqual(result.skipped, ["v1.0.5"])
        self.assertIn("1.0.5", result.changelog)
        self.assertIn("1.1.0", result.changelog)
        self.assertNotIn("## 1.0.0", result.changelog, "the base version's own section must not show up as added")
        self.assertIn(result.old_version, result.report_text)
        self.assertIn("1.1.0", result.report_text)

        # the pinned tree's own checkout is untouched: still on the old tag
        self.assertIn("v1.0.0", git(self.tree, "describe", "--tags").stdout.strip())

    def test_field_relevance_classifier_on_diff_trees(self):
        """diff_trees()/field_relevance() directly, without generation - the exact boundary the report relies on."""
        before = self.tmp / "gen-before"
        after = self.tmp / "gen-after"
        (before / "sub").mkdir(parents=True)
        (after / "sub").mkdir(parents=True)
        (before / "sub" / "memory_layout.h").write_text("#define FLASH_ORIGIN 0x0\n", encoding="utf-8")
        (after / "sub" / "memory_layout.h").write_text("#define FLASH_ORIGIN 0x10000\n", encoding="utf-8")
        (before / "sub" / "readme.txt").write_text("v1\n", encoding="utf-8")
        (after / "sub" / "readme.txt").write_text("v2\n", encoding="utf-8")
        (after / "sub" / "new_file.h").write_text("#define DID_SESSION 0x10\n", encoding="utf-8")

        diffs = update.diff_trees(before, after)
        by_path = {d.path: d for d in diffs}
        self.assertEqual(by_path["sub/memory_layout.h"].change, "changed")
        self.assertTrue(by_path["sub/memory_layout.h"].field_relevant)
        self.assertEqual(by_path["sub/readme.txt"].change, "changed")
        self.assertFalse(by_path["sub/readme.txt"].field_relevant)
        self.assertEqual(by_path["sub/new_file.h"].change, "added")
        self.assertTrue(by_path["sub/new_file.h"].field_relevant, "a new file naming a DID is field-relevant "
                        "by content even though its path gives no hint")

    def test_release_strictness_blocks_a_non_annotated_target(self):
        """A lightweight tag at the target version fails the TOOL-65 rule; --write must refuse to move the pin."""
        git(self.upstream, "checkout", "-q", "master")
        (self.upstream / "VERSION").write_text("1.2.0\n", encoding="utf-8")
        git(self.upstream, "add", "-A")
        git(self.upstream, "commit", "-q", "-m", "release 1.2.0 (lightweight by mistake)")
        git(self.upstream, "tag", "v1.2.0")            # lightweight, not annotated

        result = update.run(self.ws, "1.2.0", write=True, python=PYTHON)

        self.assertFalse(result.pin_status.ok)
        self.assertFalse(result.written, "a bad tag must not move the pin even with --write")
        self.assertIn("tag-lightweight", [f.code for f in result.pin_status.findings])
        self.assertIn("--write was given, but nextbsw.yaml was NOT changed", result.report_text)

    # ------------------------------------------------------------------ release candidates (TOOL-232)

    def _candidate(self, version: str, tag: str) -> None:
        """A commit on upstream master with VERSION `version` (generators as in 1.1.0), annotated tag `tag`."""
        git(self.upstream, "checkout", "-q", "master")
        (self.upstream / "VERSION").write_text(f"{version}\n", encoding="utf-8")
        git(self.upstream, "add", "-A")
        git(self.upstream, "commit", "-q", "-m", f"candidate {tag}")
        git(self.upstream, "tag", "-a", tag, "-m", f"release candidate {tag}")

    def test_to_names_a_release_or_a_release_candidate(self):
        self.assertEqual(update.target_of("1.1.0"), ("1.1.0", "v1.1.0"))
        self.assertEqual(update.target_of("v1.1.0"), ("1.1.0", "v1.1.0"))
        self.assertEqual(update.target_of("v1.2.0-rc1"), ("1.2.0", "v1.2.0-rc1"))
        self.assertEqual(update.target_of("1.2.0-rc12"), ("1.2.0", "v1.2.0-rc12"))
        # counter-checks: no other spelling of a candidate, no other suffix
        for wrong in ("v1.2.0-rc", "v1.2.0-beta1", "v1.2.0-rc0", "v1.2.0-rc01", "v1.2.0-rc.1", "1.2", "v01.2.0",
                      "1.2.0-RC1", ""):
            with self.subTest(wrong=wrong), self.assertRaises(update.UpdateError):
                update.target_of(wrong)

    def test_write_to_a_release_candidate_moves_the_tree_to_the_tag_and_the_pin_to_its_version(self):
        self._candidate("1.2.0", "v1.2.0-rc1")
        result = update.run(self.ws, "v1.2.0-rc1", write=True, release=True, python=PYTHON)

        self.assertTrue(result.pin_status.ok, result.pin_status.text)
        self.assertTrue(result.written)
        self.assertEqual(result.new_version, "1.2.0")
        self.assertIn("version: 1.2.0\n", (self.ws / "nextbsw.yaml").read_text(encoding="utf-8"))
        self.assertEqual(git(self.tree, "describe", "--tags", "--exact-match").stdout.strip(), "v1.2.0-rc1")
        self.assertEqual(result.report_file, self.ws / "doc" / "nextbsw-updates" / "v1.0.0-v1.2.0-rc1.md")
        self.assertIn("v1.2.0-rc1", result.report_text)

    def test_a_release_candidate_of_another_version_is_refused_before_anything_moves(self):
        before_pin = (self.ws / "nextbsw.yaml").read_text(encoding="utf-8")
        self._candidate("1.2.0", "v1.2.1-rc1")              # the tag names 1.2.1, the tree is 1.2.0
        with self.assertRaisesRegex(update.UpdateError, "1.2.1"):
            update.run(self.ws, "v1.2.1-rc1", write=True, python=PYTHON)
        self.assertEqual((self.ws / "nextbsw.yaml").read_text(encoding="utf-8"), before_pin)
        self.assertEqual(git(self.tree, "describe", "--tags", "--exact-match").stdout.strip(), "v1.0.0")
        # the same rule for --tree: a materialised tree whose VERSION is not the version of --to
        materialised = self.tmp / "materialised-rc"
        git(self.tmp, "clone", "--quiet", "--branch", "v1.2.1-rc1", str(self.upstream), str(materialised))
        with self.assertRaisesRegex(update.UpdateError, "1.2.1"):
            update.run(self.ws, "v1.2.1-rc1", tree=materialised, python=PYTHON)
        # a candidate that does not exist at all is named as such
        with self.assertRaisesRegex(update.UpdateError, "v1.2.0-rc7 not found"):
            update.run(self.ws, "v1.2.0-rc7", offline=True, python=PYTHON)

    def test_a_malformed_candidate_is_refused_on_the_command_line(self):
        from nxupdate import __main__ as cli

        for wrong in ("v1.2.0-rc", "v1.2.0-beta1"):
            with self.subTest(wrong=wrong):
                self.assertEqual(cli.main([str(self.ws), "--to", wrong]), 1)

    # ------------------------------------------------------------------ write and commit

    def test_write_moves_pin_and_tree_and_writes_the_report(self):
        result = update.run(self.ws, "1.1.0", write=True, python=PYTHON)

        self.assertTrue(result.written)
        self.assertFalse(result.committed)
        pin_text = (self.ws / "nextbsw.yaml").read_text(encoding="utf-8")
        self.assertIn("version: 1.1.0", pin_text)
        self.assertIn("v1.1.0", git(self.tree, "describe", "--tags").stdout.strip())
        self.assertIsNotNone(result.report_file)
        self.assertTrue(result.report_file.is_file())
        self.assertEqual(result.report_file, self.ws / "doc" / "nextbsw-updates" / "v1.0.0-v1.1.0.md")
        self.assertEqual(result.report_file.read_text(encoding="utf-8"), result.report_text)

    def test_commit_adds_one_commit_and_never_pushes(self):
        git(self.ws, "init", "-q")
        git(self.ws, "checkout", "-q", "-B", "main")
        git(self.ws, "add", "-A")
        git(self.ws, "commit", "-q", "-m", "initial import")

        result = update.run(self.ws, "1.1.0", write=True, commit=True, python=PYTHON)

        self.assertTrue(result.written)
        self.assertTrue(result.committed)
        log = git(self.ws, "log", "--oneline", "-1").stdout
        self.assertIn("v1.0.0 -> v1.1.0", log)
        status = git(self.ws, "status", "--porcelain").stdout
        self.assertEqual(status.strip(), "", "the commit must include everything the update touched")
        # nothing pushed anywhere - there is no remote to push to, and this tool never configures or calls one
        remotes = git(self.ws, "remote").stdout.strip()
        self.assertEqual(remotes, "")

    # ------------------------------------------------------------------ errors

    def test_missing_pin_file_is_a_clean_error(self):
        empty = self.tmp / "no-workspace"
        empty.mkdir()
        with self.assertRaises(update.UpdateError):
            update.run(empty, "1.1.0", python=PYTHON)

    def test_archive_source_without_tree_override_is_refused(self):
        (self.ws / "nextbsw.yaml").write_text(
            "schema_version: 1\nnextbsw:\n  version: 1.0.0\n  source: archive\n  path: nextbsw\n"
            "  url: https://example.invalid/nextbsw-1.0.0.zip\n"
            "  sha256: " + "0" * 64 + "\n", encoding="utf-8")
        with self.assertRaises(update.UpdateError):
            update.run(self.ws, "1.1.0", python=PYTHON)

    def test_tree_override_bypasses_the_submodule_history(self):
        """--tree <path> (the source: archive fallback, 4.4): an already-materialised tree is used as it is."""
        materialised = self.tmp / "materialised-1.1.0"
        git(self.tmp, "clone", "--quiet", "--branch", "v1.1.0", str(self.upstream), str(materialised))
        result = update.run(self.ws, "1.1.0", tree=materialised, python=PYTHON)
        self.assertTrue(result.pin_status.ok)
        by_path = {d.path.replace("\\", "/"): d for d in result.file_diffs}
        self.assertIn("projects/demo/board/memory_layout.h", by_path)


@unittest.skipUnless(GIT, "git is not installed")
class MigrateWiring(unittest.TestCase):
    """`run_migrate` against *this* repository's real `tools/nxconfig` - proves the wiring to a real migration
    engine (dry run only; nothing here is ever written, this must never touch the repository)."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="nxupdate-migrate-test-")).resolve()

    def tearDown(self):
        update.rmtree(self.tmp)

    def test_a_format_1_rte_yaml_is_recognised_and_would_be_raised(self):
        rte = self.tmp / "rte.yaml"
        rte.write_text("components: []\ncan:\n  dbc: some.dbc\n", encoding="utf-8")

        result = update.run_migrate(PYTHON, REPO, self.tmp, write=False)

        self.assertTrue(result.ran)
        self.assertEqual(result.returncode, 0)
        self.assertIn("rte.yaml", result.output)
        self.assertIn("schema_version", result.output)
        self.assertEqual(rte.read_text(encoding="utf-8"), "components: []\ncan:\n  dbc: some.dbc\n",
                         "a dry run must not write anything, not even against a real tree")

    def test_no_nxconfig_in_the_tree_is_a_graceful_skip(self):
        fake_tree = self.tmp / "no-nxconfig-tree"
        fake_tree.mkdir()
        result = update.run_migrate(PYTHON, fake_tree, self.tmp, write=False)
        self.assertFalse(result.ran)
        self.assertIn("skipped", result.output)


class StagedWorkspaceHelpers(unittest.TestCase):
    """TOOL-215: the layout of the staged "after" workspace and the mapping of its paths back (no git, no tree)."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="nxupdate-staging-test-")).resolve()

    def tearDown(self):
        update.rmtree(self.tmp)

    def _pin(self, path: str) -> update.Pin:
        ws = self.tmp / "acme"
        ws.mkdir(exist_ok=True)
        (ws / "nextbsw.yaml").write_text(f"nextbsw:\n  version: 1.0.0\n  path: {path}\n", encoding="utf-8")
        return update.Pin(ws / "nextbsw.yaml", "1.0.0", "submodule", path)

    def test_a_tree_outside_the_workspace_keeps_its_relative_place(self):
        staged = update.after_layout(self._pin("../shared/nextbsw"), self.tmp / "scratch")
        self.assertTrue(staged.slot.is_relative_to(self.tmp / "scratch"), staged.slot)
        self.assertFalse(staged.slot.is_relative_to(staged.root))
        self.assertEqual(Path(os.path.normpath(staged.root / "../shared/nextbsw")), staged.slot)
        self.assertEqual(staged.pin_path, "../shared/nextbsw")

    def test_generated_paths_and_their_hashes_are_mapped_back(self):
        import hashlib
        staged = update.after_layout(self._pin("nextbsw"), self.tmp / "scratch")
        out = self.tmp / "after" / "rte"
        (out / "identity").mkdir(parents=True)
        text = f'set(DIRS "{(staged.root / "nextbsw" / "swc").as_posix()}")\n'
        (out / "c.cmake").write_text(text, encoding="utf-8", newline="")
        staged_hash = hashlib.sha256(text.encode("utf-8")).hexdigest()
        (out / "identity" / "gen.sha256").write_text(f"{staged_hash}  c.cmake\n", encoding="utf-8", newline="")

        self.assertEqual(update.normalise_generated(self.tmp / "after", staged), 1)

        real = f'set(DIRS "{(self.tmp / "acme" / "nextbsw" / "swc").as_posix()}")\n'
        self.assertEqual((out / "c.cmake").read_text(encoding="utf-8"), real)
        self.assertEqual((out / "identity" / "gen.sha256").read_text(encoding="utf-8"),
                         f"{hashlib.sha256(real.encode('utf-8')).hexdigest()}  c.cmake\n")


@unittest.skipUnless(GIT, "git is not installed")
class CommitTakesMigratedFiles(unittest.TestCase):
    """TOOL-215: `--commit` takes the configuration files `migrate --write` changed (tracked ones only)."""

    def setUp(self):
        self.ws = Path(tempfile.mkdtemp(prefix="nxupdate-commit-test-")).resolve()

    def tearDown(self):
        update.rmtree(self.ws)

    def test_tracked_configuration_is_committed_untracked_is_left_alone(self):
        (self.ws / "nextbsw.yaml").write_text(
            "schema_version: 1\nnextbsw:\n  version: 1.0.0\n  source: submodule\n  path: nextbsw\n", encoding="utf-8")
        (self.ws / "nextbsw").mkdir()
        project = self.ws / "projects" / "demo" / "project.yaml"
        project.parent.mkdir(parents=True)
        project.write_text("project:\n  name: demo\n", encoding="utf-8")
        git(self.ws, "init", "-q")
        git(self.ws, "add", "-A")
        git(self.ws, "commit", "-q", "-m", "initial import")

        project.write_text("schema_version: 1\nproject:\n  name: demo\n", encoding="utf-8")   # "migrated"
        draft = self.ws / "projects" / "draft" / "project.yaml"
        draft.parent.mkdir(parents=True)
        draft.write_text("project:\n  name: draft\n", encoding="utf-8")                      # not committed yet
