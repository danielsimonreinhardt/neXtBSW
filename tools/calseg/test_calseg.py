"""Host tests of tools/calseg (SYS-89): sealing the calibration segment and the segment HEX of a dataset.

Own profile: tools/rtegen/test/calib (C component CalMapSwc: shared axis, map, curves, value table, RTE-03 parameter,
three asil_b parameters) on buildtest_s32k148_min, generated by tools/rtegen and cross-compiled with zig
(-fdata-sections, as the toolchain file of the target) into two images whose linker scripts do what
platforms/s32k1xx/port/main/linkerscript/application.dld.in does with the parameter storage:

- production: .data.Rte_Prm_* / .bss.Rte_Prm_* sorted by name behind the 32-byte header in the flash segment
- development: the same input sections as RAM working page at the start of .data (defaults of the build, loaded
  from flash), the segment in flash as header plus room for its copy

Checked: seal writes header (layout identifier of RteCalibration.json, dataset identifier 0 or the values identifier
of a dataset build, length, CRCs) and, in development, the copy of the working page; the result passes the start-up
check (the same rules as ecu/calibration CalibrationSegment.cpp, whose host test uses a header written by this tool);
both profiles give the same segment content; every parameter address is checked against the page; the segment HEX
of the build and of a calibration dataset of tools/calgen (base and variant sport) carries the stored values at the
addresses of the ELF; errors: parameter storage outside the segment, dataset of another layout, incomplete dataset,
unknown parameter, value outside its type, unsealed image; the command line. SYS-91 `merge`: the download image
with the segment of another dataset or with a flipped header/value bit changes only segment bytes and reports the
status of the start-up check (VALID, HEADER_CRC, VALUES_CRC); wrong --flip, a flip beyond the segment and an image
without segment are refused.

Run: .venv/Scripts/python -m unittest tools/calseg/test_calseg.py
"""

import copy
import json
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO / "tools" / "rtegen"))

import calseg  # noqa: E402
from elf32 import Elf32  # noqa: E402

CALIB = REPO / "tools" / "rtegen" / "test" / "calib"
TARGET = "arm-linux-musleabi"
SEGMENT = 0x9000
HEADER = """  .nx_cal : {
    __nx_cal_segment = .;
    LONG(0xFFFFFFFF) LONG(0xFFFFFFFF) LONG(0xFFFFFFFF) LONG(0xFFFFFFFF)
    LONG(0xFFFFFFFF) LONG(0xFFFFFFFF) LONG(0xFFFFFFFF) LONG(0xFFFFFFFF)
    __nx_cal_values = .;
"""
PARAMETERS = """    KEEP(*(SORT_BY_NAME(.data.Rte_Prm_*)))
    KEEP(*(SORT_BY_NAME(.bss.Rte_Prm_*)))
    . = ALIGN(4);
"""
MEMORY = """MEMORY {
  CAL (r) : ORIGIN = 0x9000, LENGTH = 0x1000
  FLASH (rx) : ORIGIN = 0xA000, LENGTH = 0x40000
  RAM (rw) : ORIGIN = 0x20000000, LENGTH = 0x10000
}
ENTRY(_start)
"""
SCRIPTS = {
    "production": MEMORY + "SECTIONS {\n" + HEADER + PARAMETERS + """    __nx_cal_values_end = .;
  } > CAL
  .text : { *(.text*) *(.rodata*) } > FLASH
  .data : { *(.data*) } > RAM AT > FLASH
  .bss : { *(.bss*) *(COMMON) } > RAM
}
""",
    "development": MEMORY + """SECTIONS {
  .text : { *(.text*) *(.rodata*) } > FLASH
  .data : {
    . = ALIGN(8);
    __nx_cal_ram_start = .;
""" + PARAMETERS + """    __nx_cal_ram_end = .;
    *(.data*)
  } > RAM AT > FLASH
  .bss : { *(.bss*) *(COMMON) } > RAM
""" + HEADER + """    . += (__nx_cal_ram_end - __nx_cal_ram_start);
    __nx_cal_values_end = .;
  } > CAL
}
""",
    # the parameter storage is not collected: it stays in the general data (what a missing -fdata-sections or a
    # linker template without the statements would give)
    "stray": MEMORY + "SECTIONS {\n" + HEADER + """    __nx_cal_values_end = .;
  } > CAL
  .text : { *(.text*) *(.rodata*) } > FLASH
  .data : { *(.data*) } > RAM AT > FLASH
  .bss : { *(.bss*) *(COMMON) } > RAM
}
""",
}


def zig(*args: str) -> None:
    r = subprocess.run([sys.executable, "-m", "ziglang", *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise AssertionError(f"zig {args[0]}: {r.stderr[-3000:]}")


class Images(unittest.TestCase):
    tmp: Path

    @classmethod
    def setUpClass(cls):
        import rtegen
        cls.tmp = Path(tempfile.mkdtemp(prefix="calseg_"))
        project = rtegen.nxconfig.load(REPO / "projects" / "buildtest_s32k148_min" / "project.yaml")
        tasks = REPO / "ecu" / "asyncCoreConfiguration" / "tasks.yaml"
        cls.gen = cls.tmp / "gen"
        rtegen.generate(CALIB / "rte.yaml", project, cls.gen, REPO, tasks, calibration=None)
        # the same software built with the values of the calibration dataset of the profile (TOOL-145)
        cls.gen_dataset = cls.tmp / "gen_dataset"
        rtegen.generate(CALIB / "rte.yaml", project, cls.gen_dataset, REPO, tasks,
                        calibration=rtegen.CalibrationChoice(CALIB / "calibration"))
        (cls.tmp / "start.c").write_text("void _start(void) { for (;;) {} }\n")
        cls.images = {}
        for gen_name, gen in (("defaults", cls.gen), ("dataset", cls.gen_dataset)):
            includes = [f"-I{gen}", f"-I{gen / 'tasks'}", f"-I{REPO / 'libs/bsw/autosarBase/include'}",
                        f"-I{REPO / 'tools/rtegen/test/can_host/stubs'}"]
            objects = []
            for src in (gen / "Rte.c", CALIB / "CalMapSwc/src/CalMapSwc.c", cls.tmp / "start.c",
                        gen / "RteConfig.cpp"):
                obj = cls.tmp / f"{src.stem}.{gen_name}.o"
                lang = (["c++", "-std=c++17", "-fno-exceptions", "-fno-rtti"] if src.suffix == ".cpp"
                        else ["cc", "-std=c99"])
                zig(*lang, "-target", TARGET, "-O1", "-ffreestanding", "-ffunction-sections", "-fdata-sections",
                    *includes, "-c", str(src), "-o", str(obj))
                objects.append(str(obj))
            for profile, script in SCRIPTS.items():
                ld = cls.tmp / f"{profile}.ld"
                ld.write_text(script)
                elf = cls.tmp / f"{gen_name}.{profile}.elf"
                zig("ld.lld", "--unresolved-symbols=ignore-all", "-T", str(ld), *objects, "-o", str(elf))
                cls.images[gen_name, profile] = elf

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def fresh(self, gen_name: str, profile: str) -> Path:
        """A copy of an unsealed image (seal writes into the file)."""
        target = self.tmp / f"work.{gen_name}.{profile}.{self.id().rsplit('.', 1)[-1]}.elf"
        shutil.copyfile(self.images[gen_name, profile], target)
        return target

    def seal(self, gen_name: str = "defaults", profile: str = "production"):
        gen = self.gen if gen_name == "defaults" else self.gen_dataset
        elf = self.fresh(gen_name, profile)
        layout, segment = calseg.seal(elf, gen / "RteCalibration.json", gen / "RteConfig.h")
        return elf, layout, segment, gen

    def layout_id(self, gen: Path) -> int:
        return int(json.loads((gen / "RteCalibration.json").read_text(encoding="utf-8"))["layout"], 16)


class SealTest(Images):
    def test_production(self):
        elf, layout, segment, gen = self.seal()
        self.assertTrue(layout.production)
        self.assertEqual((layout.segment, layout.values), (SEGMENT, SEGMENT + 32))
        header = calseg.read_header(segment)
        self.assertEqual((header.magic, header.format, header.header_size), (0x564C4143, 1, 32))
        self.assertEqual((header.layout, header.dataset, header.reserved), (self.layout_id(gen), 0, 0xFFFFFFFF))
        self.assertEqual(header.length, layout.length)
        self.assertEqual(segment[:4], b"CALV")
        self.assertEqual(calseg.check(segment, self.layout_id(gen), layout.length), "VALID")
        # the parameters are read from the segment itself
        image = Elf32(elf)
        address = image.symbols["Rte_Prm_CalMapSwc_CalPrm_MaxTorque_Nm_data"].value
        self.assertTrue(layout.values <= address < layout.values + layout.length)

    def test_development_copies_the_working_page(self):
        elf, layout, segment, gen = self.seal(profile="development")
        self.assertFalse(layout.production)
        self.assertEqual(layout.ram % 8, 0)
        image = Elf32(elf)
        self.assertEqual(segment[32:], image.read(layout.ram, layout.length))
        self.assertEqual(calseg.check(segment, self.layout_id(gen), layout.length), "VALID")
        address = image.symbols["Rte_Prm_CalMapSwc_CalPrm_MaxTorque_Nm_data"].value
        self.assertTrue(layout.ram <= address < layout.ram + layout.length)

    def test_both_profiles_give_the_same_segment(self):
        _, _, production, _ = self.seal(profile="production")
        _, _, development, _ = self.seal(profile="development")
        self.assertEqual(production, development)

    def test_dataset_build_names_its_values(self):
        _, layout, segment, gen = self.seal("dataset")
        values = json.loads((gen / "RteCalibration.json").read_text(encoding="utf-8"))["dataset"]["values"]
        self.assertEqual(calseg.read_header(segment).dataset, int(values, 16))
        self.assertEqual(calseg.check(segment, self.layout_id(gen), layout.length), "VALID")

    def test_parameter_outside_the_segment_stops_the_build(self):
        elf = self.fresh("defaults", "stray")
        with self.assertRaisesRegex(calseg.CalsegError, r"lies outside the flash segment .*-fdata-sections"):
            calseg.seal(elf, self.gen / "RteCalibration.json", self.gen / "RteConfig.h")

    def test_missing_symbols(self):
        other = self.tmp / "nosegment.elf"
        zig("ld.lld", "--unresolved-symbols=ignore-all", "-e", "_start", str(self.tmp / "start.defaults.o"), "-o",
            str(other))
        with self.assertRaisesRegex(calseg.CalsegError, "__nx_cal_segment, __nx_cal_values, __nx_cal_values_end"):
            calseg.layout_of(Elf32(other))

    def test_start_up_check_on_damaged_copies(self):
        _, layout, segment, gen = self.seal()
        expected = self.layout_id(gen)
        damaged = bytearray(segment)
        damaged[40] ^= 1
        self.assertEqual(calseg.check(bytes(damaged), expected, layout.length), "VALUES_CRC")
        damaged = bytearray(segment)
        damaged[12] ^= 1
        self.assertEqual(calseg.check(bytes(damaged), expected, layout.length), "HEADER_CRC")
        self.assertEqual(calseg.check(segment, expected ^ 1, layout.length), "LAYOUT")
        self.assertEqual(calseg.check(segment, expected, layout.length + 4), "LENGTH")
        self.assertEqual(calseg.check(b"\xff" * len(segment), expected, layout.length), "ERASED")


class DatasetTest(Images):
    def image(self, profile="production"):
        elf, layout, _, _ = self.seal(profile=profile)
        return elf, layout

    def values(self, variant=None):
        return calseg.dataset_values(CALIB / "rte.yaml", variant)

    def test_segment_of_the_build(self):
        elf, _ = self.image()
        address, data = calseg.segment_image(elf, self.gen / "RteConfig.h")
        self.assertEqual((address, data), (SEGMENT, Elf32(elf).read(SEGMENT, len(data))))

    def test_dataset_values_at_the_addresses_of_the_elf(self):
        for profile in ("production", "development"):
            with self.subTest(profile=profile):
                elf, layout = self.image(profile)
                for variant in (None, "sport"):
                    dataset = self.values(variant)
                    address, data = calseg.segment_image(elf, self.gen / "RteConfig.h", dataset)
                    self.assertEqual(address, SEGMENT)
                    header = calseg.read_header(data)
                    self.assertEqual(header.dataset, int(dataset["values_id"], 16))
                    self.assertEqual(calseg.check(data, int(dataset["layout"], 16), layout.length), "VALID")
                    image = Elf32(elf)
                    for component in dataset["components"].values():
                        for entry in component.values():
                            p = next(q for q in calseg.parameters_of(elf, self.gen / "RteConfig.h")
                                     if q.name == entry["name"])
                            size = calseg.a2lgen.TYPES[p.type][1]
                            at = 32 + layout.offset(p.address)
                            got = [struct.unpack_from("<" + calseg.PACK[p.type], data, at + i * size)[0]
                                   for i in range(p.count)]
                            # as stored: a float32 value reads back rounded to single precision
                            expected = [struct.unpack("<" + calseg.PACK[p.type],
                                                      struct.pack("<" + calseg.PACK[p.type], v))[0]
                                        for v in entry["stored"]]
                            self.assertEqual(got, expected, entry["name"])
                    self.assertIsNotNone(image)

    def test_same_values_as_a_build_with_the_dataset(self):
        """The segment HEX of a dataset equals the segment a build with that dataset seals (values and header)."""
        elf, _ = self.image()
        _, data = calseg.segment_image(elf, self.gen / "RteConfig.h", self.values())
        _, _, built, _ = self.seal("dataset")
        self.assertEqual(data, built)

    def test_errors(self):
        elf, _ = self.image()
        config = self.gen / "RteConfig.h"
        good = self.values()
        cases = []
        other = copy.deepcopy(good)
        other["layout"] = "00000000"
        cases.append((other, "bound to layout 00000000"))
        incomplete = copy.deepcopy(good)
        del incomplete["components"]["CalMapSwc"]["Gain"]
        cases.append((incomplete, "incomplete, CalMapSwc.CalPrm.Gain missing"))
        unknown = copy.deepcopy(good)
        unknown["components"]["CalMapSwc"]["Nope"] = {"name": "CalMapSwc.CalPrm.Nope", "stored": [1]}
        cases.append((unknown, "CalMapSwc.CalPrm.Nope is no parameter of the image"))
        wide = copy.deepcopy(good)
        wide["components"]["CalMapSwc"]["Mode"]["stored"] = [256]
        cases.append((wide, r"Mode\[0\] = 256 outside UINT8"))
        short = copy.deepcopy(good)
        short["components"]["CalMapSwc"]["Offsets_Nm"]["stored"] = [0]
        cases.append((short, "Offsets_Nm needs a list of 3 stored value"))
        for dataset, text in cases:
            with self.subTest(text=text):
                with self.assertRaisesRegex(calseg.CalsegError, text):
                    calseg.segment_image(elf, config, dataset)

    def test_unsealed_image_is_refused(self):
        with self.assertRaisesRegex(calseg.CalsegError, r"not sealed \(ERASED\)"):
            calseg.segment_image(self.fresh("defaults", "production"), self.gen / "RteConfig.h")

    def test_command_line(self):
        elf = self.fresh("defaults", "development")
        config = str(self.gen / "RteConfig.h")
        self.assertEqual(calseg.main(["show", "--elf", str(elf)]), 1)                       # not sealed yet
        self.assertEqual(calseg.main(["seal", "--elf", str(elf), "--description",
                                      str(self.gen / "RteCalibration.json"), "--rte-config", config]), 0)
        self.assertEqual(calseg.main(["show", "--elf", str(elf)]), 0)
        segment_hex = self.tmp / "segment.hex"
        self.assertEqual(calseg.main(["hex", "--elf", str(elf), "--rte-config", config, "-o", str(segment_hex)]), 0)
        self.assertEqual(calseg.main(["show", "--elf", str(elf), "--hex", str(segment_hex)]), 0)
        variant_hex = self.tmp / "sport.hex"
        self.assertEqual(calseg.main(["hex", "--elf", str(elf), "--rte-config", config, "--dataset",
                                      str(CALIB / "rte.yaml"), "--variant", "sport", "-o", str(variant_hex)]), 0)
        length = calseg.layout_of(Elf32(elf)).length
        data = calseg.read_hex(variant_hex, SEGMENT, 32 + length)
        self.assertEqual(calseg.read_header(data).dataset, int(self.values("sport")["values_id"], 16))
        values_file = self.tmp / "values.json"
        values_file.write_text(json.dumps(self.values("sport")), encoding="utf-8")
        from_file = self.tmp / "sport2.hex"
        self.assertEqual(calseg.main(["hex", "--elf", str(elf), "--rte-config", config, "--values",
                                      str(values_file), "-o", str(from_file)]), 0)
        self.assertEqual(calseg.read_hex(from_file, SEGMENT, 32 + length), data)
        self.assertEqual(calseg.main(["hex", "--elf", str(elf), "--rte-config", config, "--dataset",
                                      str(CALIB / "rte.yaml"), "--variant", "nosuch", "-o", str(from_file)]), 1)


class MergeTest(Images):
    """SYS-91: the download image with another dataset or a damaged segment (test aid for the board test of the
    start-up check); only the segment bytes change."""

    def image_hex(self, profile="production"):
        elf, layout, segment, _ = self.seal(profile=profile)
        image_hex = self.tmp / f"image.{profile}.{self.id().rsplit('.', 1)[-1]}.hex"
        # the flash content of the image (sections with contents below the RAM), like objcopy -O ihex of the build
        from intelhex import IntelHex
        image, ih = Elf32(elf), IntelHex()
        for s in image.sections:
            if s.flags & 0x2 and s.kind != 8 and s.size and s.address < 0x20000000:
                ih.frombytes(image.read(s.address, s.size), offset=s.address)
        ih.write_hex_file(str(image_hex))
        return elf, layout, segment, image_hex

    def bytes_of(self, path: Path) -> dict[int, int]:
        from intelhex import IntelHex
        ih = IntelHex(str(path))
        return {a: ih[a] for a in ih.addresses()}

    def test_other_dataset_and_damaged_header(self):
        elf, layout, segment, image_hex = self.image_hex()
        size = 32 + layout.length
        before = self.bytes_of(image_hex)
        variant_hex = self.tmp / "merge_sport.hex"
        address, data = calseg.segment_image(elf, self.gen / "RteConfig.h", calseg.dataset_values(CALIB / "rte.yaml",
                                                                                                  "sport"))
        calseg.write_hex(address, data, variant_hex)
        out = self.tmp / "merged_sport.hex"
        status, merged = calseg.merge(elf, image_hex, out, variant_hex)
        self.assertEqual(status, "VALID")
        self.assertEqual(merged, data)
        after = self.bytes_of(out)
        changed = [a for a in before if before[a] != after.get(a)]
        self.assertTrue(changed and all(SEGMENT <= a < SEGMENT + size for a in changed), changed[:4])
        self.assertEqual(set(after) - set(before), set())            # nothing added outside the image
        # one flipped bit of the layout identifier: the start-up check says HEADER_CRC (refuse)
        out = self.tmp / "merged_damaged.hex"
        status, merged = calseg.merge(elf, image_hex, out, flips=[(9, 2)])
        self.assertEqual(status, "HEADER_CRC")
        self.assertEqual(merged[9], segment[9] ^ 0x04)
        self.assertEqual(calseg.read_hex(out, SEGMENT, size), merged)
        # one flipped bit of a value: VALUES_CRC
        status, _ = calseg.merge(elf, image_hex, out, flips=[(32, 0)])
        self.assertEqual(status, "VALUES_CRC")

    def test_errors_and_command_line(self):
        elf, _, _, image_hex = self.image_hex("development")
        out = self.tmp / "merged_cli.hex"
        self.assertEqual(calseg.main(["merge", "--elf", str(elf), "--image", str(image_hex), "--flip", "0x9:2",
                                      "-o", str(out)]), 0)
        with self.assertRaisesRegex(calseg.CalsegError, "OFFSET:BIT"):
            calseg.parse_flip("9")
        with self.assertRaisesRegex(calseg.CalsegError, "bit 0..7"):
            calseg.parse_flip("9:8")
        with self.assertRaisesRegex(calseg.CalsegError, "the segment has"):
            calseg.merge(elf, image_hex, out, flips=[(0x1000, 0)])
        other = self.tmp / "no_segment.hex"
        calseg.write_hex(0xA000, b"\x00" * 16, other)
        with self.assertRaisesRegex(calseg.CalsegError, "no calibration segment"):
            calseg.merge(elf, other, out)


if __name__ == "__main__":
    unittest.main()
