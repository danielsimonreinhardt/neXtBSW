def _cxx_string(value: str) -> str:
    out = []
    for ch in value:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append(f'\\{ord(ch):03o}')
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


_CXX_VALUES = {UINT8: "static_cast<unsigned>(0x7aU)", UINT16: "static_cast<unsigned>(0xbeefU)",
               SINT16: "-12345", UINT32: "0xdeadbeefU", SINT32: "static_cast<int>(-2147483647 - 1)",
               UINT64: "static_cast<unsigned long long>(0xfedcba9876543210ULL)",
               SINT64: "static_cast<long long>(-9223372036854775807LL - 1)",
               VOIDPTR: "static_cast<void const*>(&storage)"}


def host_test_source(calls: list[Call], pointer_bytes: int = 8) -> str:
    """C++ program: every checkable call with worst-case arguments through the real OpenBSW entry path.

    Prints one line per call: "<index> <serialized bytes> <expected bytes> <complete 0/1>"."""
    cases = []
    for idx, c in enumerate(calls):
        size = c.entry_bytes(pointer_bytes)
        if size is None or c.errors:
            continue
        args = []
        for a in c.args:
            args.extend(["static_cast<int>(-1)"] * a.param.star_args)  # '*' width: printed with any width
            if a.param.datatype == CHARPTR:
                args.append(_cxx_string("W" * a.max_len))
            elif a.param.datatype >= 0:
                args.append(_CXX_VALUES.get(a.param.datatype, "0"))
        call_args = ", ".join([_cxx_string(c.fmt)] + args)
        cases.append(f"    report({idx}U, {size}U, {_cxx_string(c.file + ':' + str(c.line))}, {call_args});")
    body = "\n".join(cases)
    return _HOST_TEMPLATE.replace("@CASES@", body).replace("@MAX@", str(MAX_ENTRY_BYTES))


_HOST_TEMPLATE = r"""/* Generated by tools/logcheck (SYS-16) - do not edit.
 * Every logger call of the repository with worst-case arguments through the real OpenBSW entry path:
 * EntrySerializer::serialize() into MaxEntrySize bytes, EntryBuffer::addEntry()/getNextEntry(), deserialize()
 * and PrintfFormatter. */
#include <logger/EntryBuffer.h>
#include <logger/EntrySerializer.h>
#include <util/format/PrintfFormatter.h>
#include <util/stream/IOutputStream.h>

#include <cstdarg>
#include <cstdint>
#include <cstdio>
#include <string>

namespace
{
constexpr uint8_t MAX_ENTRY_BYTES = @MAX@U;
using Serializer = ::logger::EntrySerializer<uint16_t, uint32_t>;
[[maybe_unused]] int storage = 0;

class CaptureStream : public ::util::stream::IOutputStream
{
public:
    bool isEof() const override { return false; }
    void write(uint8_t const data) override { text.push_back(static_cast<char>(data)); }
    void write(::etl::span<uint8_t const> const& buffer) override
    {
        text.append(reinterpret_cast<char const*>(buffer.data()), buffer.size());
    }
    std::string text;
};

class Printer : public ::logger::IEntrySerializerCallback<uint32_t>
{
public:
    void onEntry(uint32_t, uint8_t, ::util::logger::Level, char const* const str,
                 ::util::format::IPrintfArgumentReader& argReader) override
    {
        ::util::format::PrintfFormatter formatter(stream, false);
        formatter.format(str, argReader);
    }
    CaptureStream stream;
};

void report(unsigned const index, unsigned const expected, char const* const where, char const* const format, ...)
{
    // a buffer larger than an entry: the serializer reports the full size, the entry buffer keeps MaxEntrySize
    uint8_t entry[512];
    va_list ap;
    va_start(ap, format);
    Serializer const serializer;
    uint16_t const size = serializer.serialize(
        ::etl::span<uint8_t>(entry, MAX_ENTRY_BYTES), 0x12345678U, 3U, ::util::logger::LEVEL_INFO, format, ap);
    va_end(ap);
    size_t const offered = (size > MAX_ENTRY_BYTES) ? MAX_ENTRY_BYTES : size;
    uint8_t ring[1024];
    ::logger::EntryBuffer<MAX_ENTRY_BYTES, uint32_t> buffer{::etl::span<uint8_t>(ring)};
    buffer.addEntry(::etl::span<uint8_t const>(entry, offered));
    ::logger::EntryBuffer<MAX_ENTRY_BYTES, uint32_t>::EntryRef ref(0U);
    uint8_t read[MAX_ENTRY_BYTES];
    uint8_t const stored = buffer.getNextEntry(::etl::span<uint8_t>(read), ref);
    Printer printer;
    Serializer::deserialize(::etl::span<uint8_t const>(read, stored), printer);
    bool const complete = (size <= MAX_ENTRY_BYTES) && (printer.stream.text.find("<?>") == std::string::npos);
    std::printf("%u %u %u %d %s\n", index, static_cast<unsigned>(size), expected, complete ? 1 : 0, where);
}
} // namespace

int main()
{
@CASES@
    return 0;
}
"""


# ------------------------------------------------------------------------------------------------ CLI

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="logcheck", description=__doc__.split("\n\n")[0])
    parser.add_argument("command", nargs="?", default="check", choices=["check", "hosttest"])
    parser.add_argument("--repo", type=Path, default=REPO)
    parser.add_argument("--bounds", type=Path, default=BOUNDS_FILE)
    parser.add_argument("--limit", type=int, default=MAX_ENTRY_BYTES)
    parser.add_argument("--all", action="store_true", help="list every call, not only findings")
    parser.add_argument("--out", type=Path, help="hosttest: C++ file to write")
    ns = parser.parse_args(argv)
    report = check(ns.repo, ns.limit, ns.bounds)
    if ns.command == "hosttest":
        if ns.out is None:
            parser.error("hosttest needs --out")
        ns.out.parent.mkdir(parents=True, exist_ok=True)
        ns.out.write_text(host_test_source(report.calls), encoding="utf-8")
        print(f"{ns.out}: {len(report.calls)} call(s)")
        return 0
    table = format_table(report, ns.all)
    if table:
        print(table)
    findings = report.findings()
    sizes = [s for s in (c.entry_bytes() for c in report.calls) if s is not None]
    print(f"{len(report.calls)} logger call(s), largest entry {max(sizes, default=0)} of {ns.limit} bytes, "
          f"{len(findings)} finding(s)")
    for f in findings:
        print("  " + f)
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
