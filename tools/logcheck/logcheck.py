"""Checks every OpenBSW logger call of the repository against the size of one logger entry (SYS-16).

OpenBSW's buffered logger (logger::BufferedLoggerOutput, logger/Config.h generated by the root CMakeLists, PLAT-04)
serialises every call into ONE entry of at most MaxEntrySize = 128 bytes and silently cuts the rest: the last
argument that does not fit prints as "<?>" (IO-25 "TMC6200 ready" line, COM-25 "can log" line). The layout follows
logger::EntrySerializer::serialize():

    timestamp (sizeof Timestamp = 4) + component (1) + level (1)
    + the format string as char array: type 1 + length sizeof(T) = 2 + characters + terminating zero
    + per argument: type byte + value (%c/%d/%u/%x 4 bytes, %h.. 2, %l../%ll.. 8, %p pointer size, %* one extra
      int), strings (%s) like the format string - the default SectionPredicate copies every string, also literals
      (a null pointer is stored as a pointer instead).

The tool finds every Logger::debug/info/warn/error/critical/log call outside external/, parses the format string
(adjacent literals) with a copy of util::format::PrintfFormatScanner and computes the worst-case entry. Integer
arguments have a fixed size. %s arguments need an upper bound for their length: string literals and conditional
expressions of literals are measured, everything else needs an entry in bounds.yaml with a proof the tool checks
(the literals of a function, or a text such as a static_assert that must exist in a file). A call without bound, a
format that is not a literal and every entry over the limit are errors.

The size model is checked against the real OpenBSW serializer: `hosttest` writes a C++ program that runs every found
call with its worst-case arguments through logger::EntrySerializer, EntryBuffer and PrintfFormatter
(test_logcheck.py compiles it with zig and compares byte for byte).

    python tools/logcheck [check] [--repo DIR] [--limit 128] [--all]     table of calls, exit 1 on findings
    python tools/logcheck hosttest --out FILE.cpp                         C++ check through the real serializer
"""

from __future__ import annotations

