"""Figure 7 of doc/figures: the module map with the verification of each module (DOC-64).

Generated from the same module list as doc/reference/modules.md (modules.collect: libs/bsw, libs/bsp and the port
modules with their manifests), so map and module reference cannot disagree. The page holds a Mermaid figure
(colour = verification) and a status table (symbol = verification) for readers who do not see the colours.

    text = render(modules.collect())          # the whole page, deterministic
"""

from __future__ import annotations

import re
from collections import Counter

from . import modules
from .modules import ModuleDoc

FILE = "07-modulkarte.md"
OUT_DIR = modules.REPO / "doc" / "figures"
REFERENCE_LINK = "../reference/modules.md"           # relative from doc/figures
GENERATED_NOTE = (f"<!-- Generated by tools/docgen from {modules.SOURCES} (like doc/reference/modules.md). "
                  "Do not edit: change the manifest field `verification` and run `.venv/Scripts/python tools/docgen`. "
                  "-->")

# Diagram style B1 (DOC-82): the header and the classDefs are the same in every Mermaid block of the documentation
# (tools/docgen/test_mermaid.py checks them); the status classes ok / part / no are used in status figures only.
HEADER = ("%%{init: {'theme':'base','flowchart':{'curve':'basis'},'themeVariables':{'fontFamily':'Segoe UI, "
          "Helvetica, Arial, sans-serif','fontSize':'14px','background':'#ffffff','primaryColor':'#ffffff',"
          "'primaryBorderColor':'#64748b','primaryTextColor':'#0f172a','lineColor':'#475569',"
          "'edgeLabelBackground':'#ffffff','tertiaryColor':'#f8fafc','clusterBkg':'#f8fafc',"
          "'clusterBorder':'#cbd5e1'}}}%%")
CLASSDEFS = {
    "grp": "fill:#f8fafc,stroke:#cbd5e1,rx:8,ry:8",
    "ok": "fill:#dcfce7,stroke:#15803d,stroke-width:1.5px,color:#0f172a",
    "part": "fill:#fef3c7,stroke:#b45309,stroke-width:1.5px,color:#0f172a",
    "no": "fill:#fee2e2,stroke:#b91c1c,stroke-width:1.5px,color:#0f172a",
}

# verification level -> (Mermaid class, colour name for the legend, table symbol, German text for the legend and table)
LEVELS = {
    "hardware": ("ok", "grün", "🟩", "Board"),
    "mock": ("part", "gelb", "🟨", "Mock"),
    "none": ("no", "rot", "🟥", "keiner"),
}
# no field, or a value the list above does not know: drawn without a status colour, never guessed
UNSTATED = ("", "ohne Farbe", "❔", "nicht angegeben")
LEGEND = {
    "hardware": "Verhalten an einem echten Board bestätigt",
    "mock": "nur Host-Tests, Registermodelle, Generator- und Bau-Tests",
    "none": "noch nicht geprüft",
}
# subgroups inside a layer or port, bottom-up; kinds not listed follow alphabetically, a module without kind last
KIND_ORDER = ("contract", "mcu_driver", "device_driver", "service", "library")
NO_KIND = "(no kind)"


def level_of(mod: ModuleDoc) -> tuple[str, str, str, str]:
    return LEVELS.get(mod.verification or "", UNSTATED)


def node_id(mod: ModuleDoc) -> str:
    """Mermaid node id from the module anchor: unique even for equal module names in two ports, never a keyword."""
    return re.sub(r"\W", "_", mod.anchor)


def _groups(mods: list[ModuleDoc]) -> list[tuple[str, list[tuple[str, list[ModuleDoc]]]]]:
    """[(layer or port path, [(kind, modules)])] in the order of the module list, kinds in KIND_ORDER."""
    roots: dict[str, dict[str, list[ModuleDoc]]] = {}
    for mod in mods:
        roots.setdefault(mod.root, {}).setdefault(mod.kind or NO_KIND, []).append(mod)
    rank = {k: i for i, k in enumerate(KIND_ORDER)}

    def key(kind: str) -> tuple:
        return (kind == NO_KIND, rank.get(kind, len(rank)), kind)

    return [(root, [(k, kinds[k]) for k in sorted(kinds, key=key)]) for root, kinds in roots.items()]


def mermaid(mods: list[ModuleDoc]) -> list[str]:
    lines = ["```mermaid", HEADER, "flowchart TB"]
    groups = []                                                    # subgraph ids, drawn as grp
    for i, (root, kinds) in enumerate(_groups(mods), 1):
        lines += [f'    subgraph G{i}["{root}"]', "        direction LR"]
        groups.append(f"G{i}")
        for j, (kind, members) in enumerate(kinds, 1):
            lines.append(f'        subgraph G{i}K{j}["{kind}"]')
            groups.append(f"G{i}K{j}")
            for mod in members:
                label = f"{mod.name} (pending)" if mod.pending else mod.name
                lines.append(f'            {node_id(mod)}("{label}")')
            lines.append("        end")
        lines += ["    end", ""]
    used = {level_of(m)[0] for m in mods}
    for name in ("grp", *(spec[0] for spec in LEVELS.values())):
        if name == "grp" or name in used:
            lines.append(f"    classDef {name} {CLASSDEFS[name]}")
    lines.append(f"    class {','.join(groups)} grp")
    for spec in LEVELS.values():
        for root in dict.fromkeys(m.root for m in mods):          # one line per layer or port keeps lines short
            members = [node_id(m) for m in mods if m.root == root and level_of(m) == spec]
            if members:
                lines.append(f"    class {','.join(members)} {spec[0]}")
    lines.append("```")
    return lines


def counts_text(mods: list[ModuleDoc]) -> str:
    counts = Counter(m.verification or modules.NOT_STATED for m in mods)
    order = {lvl: i for i, lvl in enumerate(modules.VERIFICATION_ORDER)}
    parts = [f"{n} × `{lvl}`" if lvl != modules.NOT_STATED else f"{n} × nicht angegeben"
             for lvl, n in sorted(counts.items(), key=lambda kv: (kv[0] == modules.NOT_STATED,
                                                                   order.get(kv[0], len(order)), kv[0]))]
    return ", ".join(parts) + f", {len(mods)} Module"


def legend(mods: list[ModuleDoc]) -> list[str]:
    lines = ["**Legende**", ""]
    present = {m.verification for m in mods}
    for lvl, (_, colour, symbol, text) in LEVELS.items():
        if lvl in present:
            lines.append(f"- {symbol} {colour.capitalize()}, {text} (`{lvl}`): {LEGEND[lvl]}.")
    if any(level_of(m) == UNSTATED for m in mods):
        lines.append(f"- {UNSTATED[2]} {UNSTATED[3]}: das Manifest hat kein Feld `{modules.VERIFICATION_FIELD}` "
                     "oder einen unbekannten Wert; ohne Statusfarbe.")
    lines += [
        f"- Stand: {counts_text(mods)}.",
        f"- Der Prüfstand ist das Manifestfeld `{modules.VERIFICATION_FIELD}`; was am Board bestätigt ist und was "
        f"nicht, sagt je Modul der Satz `{modules.NOTE_FIELD}` in der [Modulreferenz]({REFERENCE_LINK}). "
        "„Board“ heißt nicht, dass jede Funktion des Moduls am Board geprüft ist.",
    ]
    pending = [m for m in mods if m.pending]
    if pending:
        names = ", ".join(f"`{m.name}`" for m in pending)
        lines.append(f"- {names} {'ist' if len(pending) == 1 else 'sind'} geparkt (`{modules.PENDING}`) und von "
                     "keinem Projekt nutzbar.")
    lines.append("- Gruppen: Ort im Repository, darin die Art des Moduls (Manifestfeld `kind`).")
    return lines


def table(mods: list[ModuleDoc]) -> list[str]:
    lines = ["## Statusmatrix", "",
             "| Modul | Ort | Art | Prüfstand |",
             "|---|---|---|---|"]
    for mod in mods:
        _, _, symbol, text = level_of(mod)
        value = f" (`{mod.verification}`)" if mod.verification else ""
        name = f"{mod.name} (pending)" if mod.pending else mod.name
        kind = f"`{mod.kind}`" if mod.kind else "–"
        lines.append(f"| [{name}]({REFERENCE_LINK}#{mod.anchor}) | {mod.root} | {kind} | {symbol} {text}{value} |")
    return lines


def render(mods: list[ModuleDoc]) -> str:
    lines = ["<!-- SPDX-License-Identifier: Apache-2.0 -->", GENERATED_NOTE, "",
             "# Bild 7: Modulkarte mit Prüfstand", ""]
    lines += mermaid(mods) + [""]
    lines += legend(mods) + [""]
    lines += table(mods) + [""]
    lines += [f"Quelle: die Manifeste `module.yaml`, dieselbe Modulliste wie die [Modulreferenz]({REFERENCE_LINK}). "
              "Die Seite ist **erzeugt**; `tools/docgen --check` meldet, sobald sie von den Manifesten abweicht."]
    return "\n".join(lines) + "\n"
