"""Mermaid blocks of the documentation and the figure pages (DOC-63).

1. Every ```mermaid block in README.md, doc/**/*.md, libs/**/*.md and bootloader/**/*.md (DOC-68: the module
   documents) is checked for syntax at the level a reader notices first:
   a known diagram type in the first line, balanced brackets and quotes, no empty nodes. If the Mermaid CLI
   (`mmdc`) is on PATH, every block is also rendered for real; without it that part is skipped.
2. The figure pages (doc/figures, doc/safety/figures) have no broken relative link, anchors included.

The module map (doc/figures/07-modulkarte.md) is generated by tools/docgen since DOC-64; its agreement with the
module manifests is checked there (`docgen --check`, test_docgen.py), its Mermaid block and links here.

Each check has a counter-test with a broken input. doc/confidential is never read.
"""

