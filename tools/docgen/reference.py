SCHEMA_FILE = "tools/nxconfig/model.py"
GENERATED_NOTE = (f"<!-- Generated by tools/docgen from {SCHEMA_FILE}. Do not edit: change the schema and run "
                  f"`{REGENERATE}`. -->")


@dataclass
class Root:
    """One YAML file kind documented on a page."""

    model: type[BaseModel]
    file: str                                        # file pattern, e.g. boards/<board>/board.yaml
    title: str                                       # heading if a page has several roots
    prefix: str = ""                                 # anchor prefix (unique per page)
    sections: list[Section] = field(default_factory=list)

    def fields(self) -> list[FieldDoc]:
        return [f for s in self.sections for f in s.fields]


@dataclass
class Page:
    file: str                                        # file name in doc/reference
    title: str
    level: str                                       # configuration level
    intro: str
    roots: list[Root]
    missing: str | None = None                       # text of a page without schema model
    pattern: str = ""                                # file pattern of a page without schema model

    def fields(self) -> list[FieldDoc]:
        return [f for r in self.roots for f in r.fields()]

    def sections(self) -> list[Section]:
        return [s for r in self.roots for s in r.sections]


