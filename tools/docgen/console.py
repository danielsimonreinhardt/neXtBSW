@dataclass
class CMakeFile:
    path: str                                        # repository relative
    text: str                                        # comments removed
    stack: list[tuple[str, ...]]                     # if-conditions active per line

    def conds_at(self, offset: int) -> tuple[str, ...]:
        return self.stack[self.text.count("\n", 0, offset)]


def _cmake_strip(text: str) -> str:
    return "\n".join(re.sub(r'#(?![^"]*"[^"]*$).*', "", line) for line in text.replace("\r\n", "\n").split("\n"))


def _parse_cmake(repo: Path, path: Path) -> CMakeFile:
    text = _cmake_strip(path.read_text(encoding="utf-8", errors="replace"))
    lines = text.split("\n")
    stack: list[str] = []
    per_line = []
    pending, depth, kind = None, 0, None
    for line in lines:
        per_line.append(tuple(stack))
        if pending is not None:
            pending += " " + line
            depth += line.count("(") - line.count(")")
            if depth <= 0:
                _cmake_apply(stack, kind, pending)
                pending = None
            continue
        m = re.match(r"\s*(if|elseif|else|endif)\s*\((.*)$", line, re.IGNORECASE)
        if not m:
            continue
        kind = m.group(1).lower()
        rest = m.group(2)
        depth = 1 + rest.count("(") - rest.count(")")
        if depth > 0:
            pending = rest
            continue
        _cmake_apply(stack, kind, rest)
    return CMakeFile(path.relative_to(repo).as_posix(), text, per_line)


def _cmake_apply(stack: list[str], kind: str, args: str):
    args = " ".join(args.strip()[:-1].split()) if args.strip().endswith(")") else " ".join(args.split())
    if kind == "if":
        stack.append(args)
    elif kind == "elseif" and stack:
        stack[-1] = args
    elif kind == "else" and stack:
        stack[-1] = f"NOT ({stack[-1]})"
    elif kind == "endif" and stack:
        stack.pop()


@functools.lru_cache(maxsize=16)
def _cmake_files(repo: Path) -> tuple[CMakeFile, ...]:
    files = []
    for top in NX_SCAN + ("",):
        base = repo / top if top else repo
        cands = sorted(base.rglob("CMakeLists.txt")) if top else [repo / "CMakeLists.txt"]
        for p in cands:
            if p.is_file() and not (set(p.relative_to(repo).parts[:-1]) & (SKIP_DIRS - {"doc"})):
                files.append(_parse_cmake(repo, p))
    return tuple(files)


def cmake_options(repo: Path) -> dict[str, tuple[str, str]]:
    """option(NX_... "description" OFF) of the neXtBSW CMake files: {name: (default, description)}."""
    out = {}
    for cm in _cmake_files(repo):
        for m in re.finditer(r'\boption\s*\(\s*(NX_\w+)\s+("(?:[^"\\]|\\.)*")\s*(ON|OFF)?\s*\)', cm.text):
            out.setdefault(m.group(1), (m.group(3) or "OFF", " ".join(m.group(2)[1:-1].split())))
    return out


@functools.lru_cache(maxsize=8)
def project_files(repo: Path) -> tuple[Path, ...]:
    """The project.yaml files of the repository - the ones git knows (TOOL-81).

    A generated page describes the state of the repository, not the state of one workstation. Someone trying out
    their own project under `projects/` would otherwise land in `doc/reference/console.md` and make the
    comparison test red; that happened three times before this was fixed. Outside a git checkout (an exported
    tree, a test fixture) every project counts - there is nothing to tell them apart by.
    """
    found = sorted((repo / "projects").glob("*/project.yaml"))
    try:
        listed = subprocess.run(["git", "-C", str(repo), "ls-files", "--", "projects/*/project.yaml"],
                                capture_output=True, text=True, check=True, timeout=30).stdout.split()
    except (OSError, subprocess.SubprocessError):
        return tuple(found)                          # no git: take what is on disk
    if not listed:
        return tuple(found)
    tracked = {(repo / rel).resolve() for rel in listed}
    return tuple(f for f in found if f.resolve() in tracked)


def board_ports(repo: Path) -> dict[str, dict[str, bool]]:
    """PLATFORM_SUPPORT_* switches per project of the repository.

    ARCH-58: the switches are no longer written by hand into `ecu/platforms/<board>/Options.cmake` - they are
    derived from what the project uses, what the board offers and what the family port provides. So the honest
    answer to "where is this switch on" is a list of projects, not of board ports; reading the old file would
    show a state nothing follows any more.
    """
    tools = str(repo / "tools")
    if tools not in sys.path:
        sys.path.insert(0, tools)
    try:
        import nxconfig
        from nxconfig import features
    except ImportError:
        return _declared_switches(repo)              # a synthetic tree without the tools: read what is declared

    out = {}
    for project in project_files(repo):
        try:
            cfg, _ = nxconfig.check(str(project))
        except Exception:                            # noqa: BLE001 - a broken project is not this page's job
            continue
        if cfg is None:
            continue
        try:
            switches = features.derive(cfg, repo=repo)
        except Exception:                            # noqa: BLE001
            continue
        out[project.parent.name] = {f"PLATFORM_SUPPORT_{name}": switch.value
                                    for name, switch in switches.items()}
    return out or _declared_switches(repo)


def _declared_switches(repo: Path) -> dict[str, dict[str, bool]]:
    """Switches still written by hand into ecu/platforms/<board>/Options.cmake.

    Before ARCH-58 this was the only source. It stays as the fallback for a tree that has no projects to derive
    from - the synthetic trees of these tests - and for a board port that keeps a switch as a stated exception.
    """
    out = {}
    base = repo / "ecu" / "platforms"
    for opt in sorted(base.glob("*/Options.cmake")) if base.is_dir() else []:
        text = _cmake_strip(opt.read_text(encoding="utf-8", errors="replace"))
        declared = {m.group(1): m.group(2).upper() == "ON"
                    for m in re.finditer(r"set\s*\(\s*(PLATFORM_SUPPORT_\w+)\s+(ON|OFF)\b", text)}
        if declared:
            out[opt.parent.name] = declared
    return out


def _source_cmake_conds(repo: Path, rel: str) -> list[str]:
    """Raw CMake conditions under which a neXtBSW source file is built into the application."""
    files = {cm.path: cm for cm in _cmake_files(repo)}
    path = Path(rel)
    for parent in [path.parent, *path.parent.parents]:
        cm = files.get((parent / "CMakeLists.txt").as_posix())
        if cm is None:
            continue
        local = path.relative_to(parent).as_posix()
        hit = re.search(rf'(?<![\w/.]){re.escape(local)}(?![\w/.])', cm.text)
        if not hit:
            continue
        conds = list(cm.conds_at(hit.start()))
        target = None
        for t in re.finditer(r"\b(add_library|add_executable|target_sources)\s*\(\s*([\w.\-]+)", cm.text, 0):
            if t.start() < hit.start():
                target = t.group(2)
        conds += _subdir_conds(files, parent)
        if target:
            conds += _link_conds(files.values(), target)
        return list(dict.fromkeys(conds))
    return []


def _subdir_conds(files: dict[str, CMakeFile], directory: Path) -> list[str]:
    """Conditions around add_subdirectory(<name>) in the parent CMake files, up to the repository root."""
    conds = []
    while directory != Path("."):
        cm = files.get((directory.parent / "CMakeLists.txt").as_posix())
        hit = cm and re.search(rf'add_subdirectory\s*\(\s*"?{re.escape(directory.name)}"?[\s)]', cm.text)
        if not hit:
            break
        conds += cm.conds_at(hit.start())
        directory = directory.parent
    return conds


def _link_conds(files, target: str) -> list[str]:
    """Conditions shared by every place that links `target` (none if it is linked unconditionally somewhere)."""
    sets = []
    for cm in files:
        for m in re.finditer(r"\btarget_link_libraries\s*\(\s*([\w.\-]+)([^)]*)\)", cm.text):
            if m.group(1) != target and re.search(rf"(?<![\w.\-]){re.escape(target)}(?![\w.\-])", m.group(2)):
                sets.append(cm.conds_at(m.start()))
    if not sets:
        return []
    common = [c for c in sets[0] if all(c in s for s in sets[1:])]
    return common


def _define_origin(repo: Path, name: str) -> tuple[str, tuple[str, ...]] | None:
    """(CMake file, conditions) where target_compile_definitions sets `name`."""
    for cm in _cmake_files(repo):
        for m in re.finditer(r"\btarget_compile_definitions\s*\(([^)]*)\)", cm.text):
            if re.search(rf"(?<![\w]){re.escape(name)}(?![\w])", m.group(1)):
                return cm.path, cm.conds_at(m.start())
    return None


def translate(raw: str, options: dict[str, tuple[str, str]]) -> list[Cond]:
    """Raw CMake condition -> conditions (AND split, known forms named, the rest kept as written)."""
    out = []
    for part in re.split(r"\s+AND\s+", raw):
        part = part.strip()
        neg = False
        m = re.fullmatch(r"NOT\s*\(?\s*(.*?)\s*\)?", part)
        if m and not re.search(r"\bIN_LIST\b", part):
            part, neg = m.group(1), True
        m = re.fullmatch(r'"?([\w.\-]+)"?\s+IN_LIST\s+(NX_MODULES|NX_FEATURES)', part)
        if m:
            out.append(Cond("module" if m.group(2) == "NX_MODULES" else "feature", m.group(1), neg))
        elif part in options:
            out.append(Cond("option", part, neg, options[part][1]))
        elif re.fullmatch(r"PLATFORM_SUPPORT_\w+", part):
            out.append(Cond("platform", part, neg))
        else:
            out.append(Cond("cmake", ("NOT " if neg else "") + part))
    return out


def _top_level_and(expr: str) -> list[str]:
    """Operands of the top-level `&&` of a preprocessor expression, outer parentheses of each removed."""
    parts, depth, start = [], 0, 0
    for i, ch in enumerate(expr):
        depth += (ch == "(") - (ch == ")")
        if depth == 0 and expr.startswith("&&", i):
            parts.append(expr[start:i])
            start = i + 2
    parts.append(expr[start:])
    out = []
    for p in (p.strip() for p in parts):
        while p.startswith("(") and p.endswith(")") and _balanced(p[1:-1]):
            p = p[1:-1].strip()
        out.append(p)
    return out


def _balanced(text: str) -> bool:
    depth = 0
    for ch in text:
        depth += (ch == "(") - (ch == ")")
        if depth < 0:
            return False
    return depth == 0


def resolve_pp(repo: Path, cond: Cond, options) -> list[Cond]:
    """Preprocessor macro -> build option, or compile definition with the CMake condition that sets it."""
    if cond.kind != "pp":
        return [cond]
    expr = cond.name.strip()
    # PLAT-106: "(A) && (B)" of a registration is two conditions (only when not negated: !(A && B) is not split)
    parts = _top_level_and(expr)
    if len(parts) > 1 and not cond.negated:
        out = []
        for part in parts:
            out += resolve_pp(repo, Cond("pp", part, False), options)
        return out
    # PLAT-106: console commands only in an image with console - project.yaml console.enabled -> NX_CONSOLE (the
    # family port and modules define it 1 when the project leaves it unset)
    if re.fullmatch(r"\(?\s*(?:!\s*defined\s*\(\s*NX_CONSOLE\s*\)\s*\|\|\s*)?NX_CONSOLE\s*\)?", expr):
        return [Cond("console", "NX_CONSOLE", cond.negated)]
    if cond.name in options:
        return [Cond("option", cond.name, cond.negated, options[cond.name][1])]
    if re.fullmatch(r"PLATFORM_SUPPORT_\w+", cond.name):  # the board port's switch, passed on as a macro
        return [Cond("platform", cond.name, cond.negated)]
    origin = _define_origin(repo, cond.name)
    if origin:
        cm_path, raw = origin
        via = "; ".join(raw) if raw else "always"
        return [Cond("define", cond.name, cond.negated, f"`{cm_path}`, if `{via}`" if raw else f"`{cm_path}`")]
    return [Cond("cmake", ("!" if cond.negated else "") + cond.name, False, "preprocessor macro")]


