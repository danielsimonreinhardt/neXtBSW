def _link(path: str) -> str:
    return f"../../{path}"


def cond_text(c: Cond, doc: ConsoleDoc) -> str:
    neg = "not " if c.negated else ""
    if c.kind == "family":
        return f"{neg}family `{c.name}`"
    if c.kind == "module":
        return f"{neg}module [`{c.name}`](modules.md#m-{c.name.lower()})"
    if c.kind == "feature":
        return f"{neg}derivative feature `{c.name}`"
    if c.kind == "platform":
        # ARCH-58: derived per project (use.can, diagnostics, the I/O of the board, the family port), so the
        # list names the projects it is on in - "no project" means nothing in this tree switches it on.
        on = [p for p, sw in sorted(doc.ports.items()) if sw.get(c.name)]
        where = ", ".join(f"`{p}`" for p in on) if on else "no project"
        return f"{neg}`{c.name}`, derived from project and board (on in {where})"
    if c.kind == "option":
        default = doc.options.get(c.name, ("OFF", ""))[0]
        value = "OFF" if c.negated else "ON"
        return f"build option `-D{c.name}={value}` (default {default})"
    if c.kind == "define":
        return f"{neg}compile definition `{c.name}`, set in {c.detail}"
    if c.kind == "console":
        # PLAT-106: NX_CONSOLE of the project (tools/nxconfig/console.py), on when the project leaves it unset
        return f"{'without' if c.negated else 'with'} console (`NX_CONSOLE`)"
    return f"`{c.name}`" + (f" ({c.detail})" if c.detail else "")


def conds_text(conds: list[Cond], doc: ConsoleDoc, empty: str = "always") -> str:
    return "; ".join(cond_text(c, doc) for c in conds) if conds else empty


def marker_of(text: str) -> str | None:
    """The board-rule marker a help text carries, if any (BOARD_RULE_MARKER wins over a legacy wording)."""
    low = text.lower()
    return next((m for m in MARKERS if m in low), None)


def legacy_marker_of(text: str) -> str | None:
    """A pre-SYS-17 wording in a help text that does not carry BOARD_RULE_MARKER; None otherwise."""
    low = text.lower()
    if BOARD_RULE_MARKER in low:
        return None
    return next((m for m in LEGACY_MARKERS if m in low), None)


def _board_rule_cells(g: Group, cmd: Command, doc: ConsoleDoc) -> str:
    notes = []
    if marker_of(cmd.help):
        notes.append("yes (help text)")
    for rules in doc.boards:
        for item, (anchor, name) in sorted(rules.resolved.items()):
            if anchor == g.anchor and name == cmd.name:
                notes.append(f"yes on [`{rules.board}`]({_link(rules.source)}) as `{item}`")
    return "; ".join(notes)


def syntax(g: Group, cmd: Command | None) -> str:
    head = g.name if g.name else f"<{g.default_name or 'name'}>"
    if cmd is None:
        return f"`{head}`"
    params = cmd.params
    return f"`{head} {cmd.name}{(' ' + params) if params else ''}`"


def _group_heading(g: Group) -> str:
    if g.name:
        return f"`{g.name}`" + (f" - {g.help}" if g.help else "")
    default = f", default `{g.default_name}`" if g.default_name else ", no default"
    after = " (after R1)" if g.module in AFTER_R1_MODULES else ""     # DOC-76
    return f"per device of module `{g.module}`{after} (name from the project{default})"


def group_section(g: Group, doc: ConsoleDoc) -> list[str]:
    lines = [f'<a id="{g.anchor}"></a>', "", f"### {md.prose(_group_heading(g))}", ""]
    src = f"[`{g.source.rsplit('/', 1)[-1]}`]({_link(g.source)})"   # no line anchor: an edit above would make it stale
    lines.append(f"- **Available:** {md.prose(conds_text(g.conds, doc, 'in every application'))}")
    if g.name is None:
        lines.append(f"- **Name:** the parameter `console` of each device the module serves "
                     f"(`project.yaml`, `modules.<device>.console`), the help text is set with it; see "
                     f"[project description](project.md) and [modules](modules.md#m-{(g.module or '').lower()})")
    lines.append(f"- **Defined in:** {src} ({g.origin}, class `{g.cls}`)")
    lines.append("")
    if g.simple:
        params = params_of(g.help or "")
        if params is None and g.cls == "HelpCommand":
            params = HELP_PARAMS
        text = f"`{g.name}{(' ' + params) if params else ''}`"
        lines += ["| Syntax | Purpose |", "|---|---|", f"| {md.cell(text)} | {md.cell(md.prose(g.help or ''))} |", ""]
        return lines
    header = ("Command", "Syntax", "Purpose", "Only in", "Board rule")
    lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for cmd in g.commands:
        cells = (f"`{cmd.name}`", syntax(g, cmd), md.prose(cmd.help), md.prose(conds_text(cmd.conds, doc, "")),
                 _board_rule_cells(g, cmd, doc))
        lines.append("| " + " | ".join(md.cell(c) for c in cells) + " |")
    lines.append("")
    return lines


def _project_rows(doc: ConsoleDoc) -> list[str]:
    header = ("Project", "Board", "Family", "Command groups (standard build)", "With a build option", "Undecided")
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for p in doc.projects:
        if p.error:
            lines.append(f"| `{p.name}` | | | {md.cell(p.error)} | | |")
            continue
        yes, opt, unknown = [], [], []
        for g in doc.groups:
            names = [g.name] if g.name else sorted(p.instances.get(g.module or "", []))
            if not names:
                continue
            base = [c for c in g.conds if c.kind != "option"]
            options = [c for c in g.conds if c.kind == "option"]
            state = availability(base, p, doc)
            links = [f"[`{n}`](#{g.anchor})" for n in names]
            if state is False:
                continue
            if state is None:
                unknown += links
            elif options and availability(options, p, doc) is not True:
                opt += [f"{link} (`{o.name}`)" for link in links for o in options]
            else:
                yes += links
            for cmd in g.commands:
                extra = [c for c in cmd.conds if c.kind == "option"]
                if state and extra and availability(extra, p, doc) is not True:
                    opt += [f"[`{n} {cmd.name}`](#{g.anchor}) (`{extra[0].name}`)" for n in names]
        cells = (f"`{p.name}`", f"`{p.board}`" if p.board else "", f"`{p.family}`" if p.family else "",
                 ", ".join(yes), ", ".join(opt), ", ".join(unknown))
        lines.append("| " + " | ".join(md.cell(c) for c in cells) + " |")
    return lines


