def _location_conds(rel: str, repo: Path) -> list[Cond]:
    parts = rel.split("/")
    out = []
    if parts[0] == "external":
        parts = parts[2:]                            # external/openbsw/...
    if len(parts) > 2 and parts[0] == "platforms":
        out.append(Cond("family", parts[1]))
    if len(parts) > 2 and parts[0] == "libs" and parts[1] in LAYERS and rel.split("/")[0] != "external" \
            and (repo / "libs" / parts[1] / parts[2] / "module.yaml").is_file():
        out.append(Cond("module", parts[2]))
    return out


def _manifests(repo: Path) -> dict[str, dict]:
    """Module manifests by module name; a parked module.yaml.pending counts where no module.yaml exists."""
    out = {}
    for layer in LAYERS:
        for name in ("module.yaml.pending", "module.yaml"):
            for p in sorted((repo / "libs" / layer).glob(f"*/{name}")):
                data = yaml.safe_load(p.read_text(encoding="utf-8"))
                out[p.parent.name] = data if isinstance(data, dict) else {}
    return out


def _dedupe(conds: list[Cond]) -> list[Cond]:
    seen, out = set(), []
    for c in sorted(conds, key=Cond.key):
        k = (c.kind, c.name, c.negated)
        if k not in seen:
            seen.add(k)
            out.append(c)
    return out


def collect_groups(repo: Path = REPO) -> list[Group]:
    if not (repo / OPENBSW / "libs").is_dir():
        raise SourceMissing(f"{OPENBSW} is not checked out; run `git submodule update --init {OPENBSW}` - the console "
                            "reference needs the OpenBSW commands (help, logger, adc, in, out, pwm)")
    nx = load_sources(repo, NX_SCAN)
    ob = load_sources(repo, OPENBSW_SCAN, OPENBSW, DEFINING)
    options = cmake_options(repo)
    manifests = _manifests(repo)

    def origin_of(path: str) -> str:
        return "OpenBSW" if path.startswith(OPENBSW + "/") else "neXtBSW"

    found: list[Group] = []
    for src in nx:
        found += _groups_from_macros(src, "neXtBSW") + _groups_from_tables(src, "neXtBSW")
    found += _groups_from_parents(nx + ob, origin_of)
    nx_classes = {g.cls.split("::")[-1] for g in found if g.origin == "neXtBSW"}
    for src in ob:
        for g in _groups_from_macros(src, "OpenBSW") + _groups_from_tables(src, "OpenBSW"):
            if g.cls.split("::")[-1] not in nx_classes:        # neXtBSW's own copy (ecu/consoleCommands) wins
                found.append(g)

    groups = []
    for g in found:
        conds = list(g.conds) + _location_conds(g.source, repo)
        if g.origin == "neXtBSW":
            conds += [c for raw in _source_cmake_conds(repo, g.source) for c in translate(raw, options)]
        if "::" not in g.cls:                        # a class of its own: where does the application create it?
            sites = [(f, off) for f, off in _instantiations(g.cls, nx)]
            if not sites:
                g.registered = False
            else:
                per_site = []
                for f, off in sites:
                    sc = _pp_raw(f.pp_at(off)) + _location_conds(f.path, repo)
                    impl = f.path if f.path.endswith(".cpp") else next(
                        (s.path for s in nx if Path(s.path).stem == Path(f.path).stem and s.path.endswith(".cpp")
                         and Path(s.path).parts[:2] == Path(f.path).parts[:2]), None)
                    if impl:
                        sc += [c for raw in _source_cmake_conds(repo, impl) for c in translate(raw, options)]
                    per_site.append({(c.kind, c.name, c.negated): c for c in sc})
                common = [c for k, c in per_site[0].items() if all(k in s for s in per_site[1:])]
                conds += common
        resolved = []
        for c in conds:
            resolved += resolve_pp(repo, c, options)
        g.conds = _dedupe(resolved)
        group_keys = {(c.kind, c.name, c.negated) for c in g.conds}
        for cmd in g.commands:
            rc = []
            for c in cmd.conds:
                rc += resolve_pp(repo, c, options)
            cmd.conds = [c for c in _dedupe(rc) if (c.kind, c.name, c.negated) not in group_keys]
        if g.name is None:                           # per-instance group: the module decides
            g.module = next((c.name for c in g.conds if c.kind == "module"), None)
            m = manifests.get(g.module or "", {})
            spec = (m.get("parameters") or {}).get("console") or {}
            g.default_name = spec.get("default") if isinstance(spec, dict) else None
        groups.append(g)
    help_cmd = _help_command(repo)
    if help_cmd:
        groups.append(help_cmd)
    groups = [g for g in groups if g.registered]
    return sorted(groups, key=lambda g: (g.name is None, (g.name or g.module or "").lower(), g.source))


def load_projects(repo: Path = REPO) -> list[ProjectInfo]:
    """Board, family, modules and per-instance console names of every projects/<p>/project.yaml (tools/nxconfig)."""
    import sys
    tools = str(repo / "tools")
    if tools not in sys.path:
        sys.path.insert(0, tools)
    import nxconfig

    out = []
    for p in project_files(repo):
        info = ProjectInfo(p.parent.name, None, None)
        try:
            cfg, _ = nxconfig.check(str(p))
        except Exception as exc:                     # noqa: BLE001 - shown on the page, never fatal
            cfg, info.error = None, f"not loadable: {type(exc).__name__}"
        if cfg is None:
            info.error = info.error or "not loadable (see `tools/nxconfig check`)"
            out.append(info)
            continue
        if getattr(cfg, "board_file", None):
            info.board = Path(cfg.board_file).parent.name
        if getattr(cfg, "derivative_file", None):
            info.family = Path(cfg.derivative_file).parent.name
        try:                                         # PLAT-106: the project's NX_CONSOLE (tools/nxconfig/console.py)
            from nxconfig import console as nxconsole
            info.console = bool(nxconsole.enabled(cfg))
        except Exception:                            # noqa: BLE001 - unknown, never fatal
            info.console = None
        integ = getattr(cfg, "integration", None)
        if integ is not None:
            for d in integ.devices:
                info.modules.add(d.module)
                name = (d.parameters or {}).get("console")
                if name:
                    info.instances.setdefault(d.module, []).append(str(name))
            for c in integ.can:
                if c.module and not str(c.module).startswith("<"):
                    info.modules.add(c.module)
        out.append(info)
    return out


def board_rules(repo: Path = REPO) -> list[BoardRules]:
    out = []
    for readme in sorted((repo / "boards").glob("*/README.md")):
        lines = readme.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")
        for i, line in enumerate(lines):
            if BOARD_RULE_HEADING in line:
                text = line
                for nxt in lines[i + 1:]:
                    if not nxt.startswith("  ") or nxt.lstrip().startswith("- "):
                        break
                    text += " " + nxt.strip()
                items = re.findall(r"`([^`]+)`", text.split(BOARD_RULE_HEADING, 1)[1])
                out.append(BoardRules(readme.parent.name, readme.relative_to(repo).as_posix(), items))
                break
    return out


def _resolve_rules(doc: ConsoleDoc):
    for rules in doc.boards:
        projects = [p for p in doc.projects if p.board == rules.board]
        for item in rules.items:
            words = item.split()
            if len(words) < 2:
                continue
            for g in doc.groups:
                names = {g.name} if g.name else {n for p in projects for n in p.instances.get(g.module or "", [])}
                if words[0] in names and any(c.name == words[1] for c in g.commands):
                    rules.resolved[item] = (g.anchor, words[1])
                    break


