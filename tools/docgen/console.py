# ----------------------------------------------------------------------------------------------- evaluate


def evaluate(cond: Cond, project: ProjectInfo, doc: ConsoleDoc) -> bool | None:
    """Whether a condition holds for a project in the standard build (options at their default); None: unknown."""
    if cond.kind == "family":
        value = None if project.family is None else project.family == cond.name
    elif cond.kind == "module":
        value = cond.name in project.modules
    elif cond.kind == "platform":
        port = doc.ports.get(project.board or "")
        value = None if port is None or cond.name not in port else port[cond.name]
    elif cond.kind == "option":
        value = doc.options.get(cond.name, ("OFF", ""))[0] == "ON"
    elif cond.kind == "console":
        value = project.console
    else:
        return None
    return value if not cond.negated or value is None else not value


def availability(conds: list[Cond], project: ProjectInfo, doc: ConsoleDoc) -> bool | None:
    values = [evaluate(c, project, doc) for c in conds]
    if any(v is False for v in values):
        return False
    return None if any(v is None for v in values) else True


