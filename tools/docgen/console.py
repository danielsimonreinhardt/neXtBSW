# ----------------------------------------------------------------------------------------------- C++ scanning

STR = r'"(?:[^"\\\n]|\\.)*"'
STRS = rf"(?:{STR}\s*)+"


def c_string(literals: str) -> str:
    """Value of adjacent C string literals, whitespace collapsed."""
    parts = re.findall(STR, literals)
    text = "".join(bytes(p[1:-1], "utf-8").decode("unicode_escape") if "\\" in p else p[1:-1] for p in parts)
    return " ".join(text.split())


_LEXEME = re.compile(r'//[^\n]*|/\*.*?(?:\*/|\Z)|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'', re.S)


def strip_comments(text: str) -> str:
    """C/C++ comments replaced by blanks (newlines kept, so offsets and line numbers stay valid)."""
    def blank(m: re.Match) -> str:
        s = m.group(0)
        return s if s[0] in "\"'" else re.sub(r"[^\n]", " ", s)
    return _LEXEME.sub(blank, text)


RELEVANT_MACRO = re.compile(r"\b(NX_\w+|PLATFORM_SUPPORT_\w+)\b")


@dataclass(frozen=True)
class Pp:
    """A preprocessor condition: macro name (or raw expression) and whether it must be true."""

    expr: str
    positive: bool = True


def pp_conditions(text: str) -> list[tuple[Pp, ...]]:
    """Active relevant preprocessor conditions per line (index 0 = line 1). Only conditions that name an NX_* or
    PLATFORM_SUPPORT_* macro count; include guards and compiler switches are ignored."""
    stack: list[Pp | None] = []
    per_line = []
    for line in text.split("\n"):
        per_line.append(tuple(p for p in stack if p is not None))
        m = re.match(r"\s*#\s*(ifdef|ifndef|if|elif|else|endif)\b(.*)", line)
        if not m:
            continue
        kind, expr = m.group(1), " ".join(m.group(2).split())
        if kind in ("ifdef", "ifndef", "if", "elif"):
            simple = re.fullmatch(r"(?:defined\s*\(?\s*)?(\w+)\s*\)?", expr)
            name = simple.group(1) if simple else expr
            p = Pp(name, kind != "ifndef") if RELEVANT_MACRO.search(expr) else None
            if kind == "elif" and stack:
                stack[-1] = p
            else:
                stack.append(p)
        elif kind == "else" and stack:
            top = stack[-1]
            stack[-1] = Pp(top.expr, not top.positive) if top else None
        elif kind == "endif" and stack:
            stack.pop()
    return per_line


@dataclass
class SourceFile:
    path: str                                        # repository relative, posix
    text: str                                        # comments stripped
    pp: list[tuple[Pp, ...]]

    def line_of(self, offset: int) -> int:
        return self.text.count("\n", 0, offset) + 1

    def pp_at(self, offset: int) -> tuple[Pp, ...]:
        return self.pp[self.line_of(offset) - 1]


def _walk(base: Path):
    """Source files below `base` in sorted order, without test, mock and third-party directories."""
    if not base.is_dir():
        return
    for root, dirs, files in os.walk(base):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            if os.path.splitext(name)[1] in SOURCE_SUFFIXES:
                yield Path(root) / name


@functools.lru_cache(maxsize=4096)
def _read_source(path: Path, rel: str) -> SourceFile:
    text = strip_comments(path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n"))
    return SourceFile(rel, text, pp_conditions(text))


# Words a file must contain to define a command (OpenBSW files without them are not parsed at all).
DEFINING = ("COMMAND_GROUP", "nullptr", "ParentCommand", "SimpleCommand")


def load_sources(repo: Path, tops: tuple[str, ...], base: str = "",
                 needs: tuple[str, ...] | None = None) -> list[SourceFile]:
    paths = [p for top in tops for p in _walk(repo / base / top if base else repo / top)]
    if needs is not None:                            # plus the companions (X.h -> X.cpp) of every file that passes
        stems = {p.stem for p in paths
                 if any(w in p.read_text(encoding="utf-8", errors="replace") for w in needs)}
        paths = [p for p in paths if p.stem in stems]
    return [_read_source(p, p.relative_to(repo).as_posix()) for p in paths]


def params_of(help_text: str) -> str | None:
    """Parameters stated in a help text: `(param: <address> <value>)` or `Usage: logger level [<component>]`."""
    m = re.search(r"\bparam:\s*([^,;)]*(?:\([^)]*\)[^,;)]*)*)", help_text)
    if m:
        return m.group(1).strip() or None
    m = re.search(r"\bUsage:\s*\S+\s+\S+\s*(.*)$", help_text)
    if m:
        return m.group(1).strip() or ""
    return None


def _groups_from_macros(src: SourceFile, origin: str) -> list[Group]:
    groups = []
    begin = re.compile(rf"DEFINE_COMMAND_GROUP_GET_INFO_BEGIN\(\s*([\w:]+)\s*,\s*({STRS})\s*,\s*({STRS})\s*\)")
    item = re.compile(rf"COMMAND_GROUP_COMMAND\(\s*[^,]+?\s*,\s*({STRS})\s*,\s*({STRS})\s*\)")
    for m in begin.finditer(src.text):
        end = src.text.find("DEFINE_COMMAND_GROUP_GET_INFO_END", m.end())
        end = len(src.text) if end < 0 else end
        g = Group(c_string(m.group(2)), c_string(m.group(3)), m.group(1), src.path, src.line_of(m.start()), origin)
        outer = set(src.pp_at(m.start()))
        g.conds = [c for c in _pp_raw(outer)]
        for s in item.finditer(src.text, m.end(), end):
            inner = [p for p in src.pp_at(s.start()) if p not in outer]
            g.commands.append(Command(c_string(s.group(1)), c_string(s.group(2)), _pp_raw(inner),
                                      src.line_of(s.start())))
        groups.append(g)
    return groups


def _pp_raw(pps) -> list[Cond]:
    """Preprocessor conditions as unresolved conditions (resolved against CMake later)."""
    return [Cond("pp", p.expr, not p.positive) for p in pps]


TABLE_END = re.compile(r"\{\s*nullptr\s*,\s*nullptr\s*,\s*0U?\s*\}")
TABLE_ENTRY = re.compile(rf"\{{\s*({STRS}|[\w.\->]+)\s*,\s*({STRS}|[\w.\->]+)\s*,\s*([\w:]+)\s*\}}")
CTOR = re.compile(r"((?:\w+::)*(\w+))::(\w+)\s*\(")


def _groups_from_tables(src: SourceFile, origin: str) -> list[Group]:
    """PlainCommandInfo tables written out in a constructor: first entry the group, last {nullptr, nullptr, 0U}."""
    groups = []
    for end in TABLE_END.finditer(src.text):
        depth, i = 0, end.start() - 1
        while i >= 0:
            if src.text[i] == "}":
                depth += 1
            elif src.text[i] == "{":
                if depth == 0:
                    break
                depth -= 1
            i -= 1
        if i < 0:
            continue
        entries = list(TABLE_ENTRY.finditer(src.text, i + 1, end.start()))
        if not entries:
            continue
        cls = None
        for c in CTOR.finditer(src.text, 0, i):
            if c.group(2) == c.group(3):
                cls = c.group(1)
        head = entries[0]
        is_str = head.group(1).startswith('"')
        g = Group(c_string(head.group(1)) if is_str else None, c_string(head.group(2)) if is_str else None,
                  cls or "?", src.path, src.line_of(head.start()), origin)
        outer = set(src.pp_at(head.start()))
        g.conds = _pp_raw(outer)
        for e in entries[1:]:
            inner = [p for p in src.pp_at(e.start()) if p not in outer]
            g.commands.append(Command(c_string(e.group(1)), c_string(e.group(2)), _pp_raw(inner),
                                      src.line_of(e.start())))
        groups.append(g)
    return groups


def _member_inits(src: SourceFile, members: set[str]):
    """(member, id, description, offset, constructor class) of `member("id", "description"` initializers."""
    if not members:
        return
    pat = re.compile(rf"[:,]\s*({'|'.join(sorted(map(re.escape, members)))})\s*\(\s*({STRS})\s*,\s*({STRS})")
    for m in pat.finditer(src.text):
        cls = None
        for c in CTOR.finditer(src.text, 0, m.start()):
            if c.group(2) == c.group(3):
                cls = c.group(1)
        yield m.group(1), c_string(m.group(2)), c_string(m.group(3)), m.start(), cls


def _declared_members(files: list[SourceFile], type_name: str) -> set[str]:
    pat = re.compile(rf"\b{type_name}\s+(\w+)\s*;")
    return {m.group(1) for f in files for m in pat.finditer(f.text)}


def _companions(src: SourceFile, by_stem: dict[str, list[SourceFile]]) -> list[SourceFile]:
    return [src] + [f for f in by_stem.get(Path(src.path).stem, []) if f is not src]


def _groups_from_parents(sources: list[SourceFile], origin_of) -> list[Group]:
    """ParentCommand members with SimpleCommand members attached: in the same file, or in a file that uses the class
    whose constructor builds the ParentCommand (logger.cpp adds `logger lost` to DefaultLoggerCommand)."""
    by_stem: dict[str, list[SourceFile]] = {}
    for f in sources:
        by_stem.setdefault(Path(f.path).stem, []).append(f)
    parents, simples = [], []
    for src in sources:
        group = _companions(src, by_stem)
        pm = _declared_members(group, "ParentCommand")
        sm = _declared_members(group, "SimpleCommand")
        for member, ident, desc, off, cls in _member_inits(src, pm):
            g = Group(ident, desc, cls or "?", src.path, src.line_of(off), origin_of(src.path))
            g.conds = _pp_raw(src.pp_at(off))
            parents.append(g)
        for member, ident, desc, off, cls in _member_inits(src, sm):
            simples.append((src, Command(ident, desc, _pp_raw(src.pp_at(off)), src.line_of(off))))
    own = {g.source for g in parents}
    for src, cmd in simples:                         # built by the parent's own constructor: registered first
        g = next((g for g in parents if g.source == src.path), None)
        if g:
            g.commands.append(cmd)
    for src, cmd in simples:                         # added later by a user of the parent's class
        if src.path in own:
            continue
        g = next((g for g in parents if re.search(rf"\b{re.escape(g.cls.split('::')[-1])}\b", src.text)), None)
        if g:
            g.commands.append(cmd)
    return parents


def _help_command(repo: Path) -> Group | None:
    """`help` of the OpenBSW console (asyncConsole registers a HelpCommand with its default id)."""
    rel = f"{OPENBSW}/libs/bsw/util/src/util/command/HelpCommand.cpp"
    path = repo / rel
    if not path.is_file():
        return None
    src = _read_source(path, rel)
    m = re.search(rf"HelpCommand\(\s*cmd\s*,\s*({STR})\s*,\s*({STR})", src.text)
    if not m:
        return None
    return Group(c_string(m.group(1)), c_string(m.group(2)), "HelpCommand", rel, src.line_of(m.start()), "OpenBSW",
                 simple=True)


def _instantiations(cls: str, sources: list[SourceFile]) -> list[tuple[SourceFile, int]]:
    """Declarations of an object of `cls` (last name component) in neXtBSW sources - or of a neXtBSW class derived
    from it, which registers the same group (SYS-150: `SafeOffOutputTester : public ::bios::OutputTester`)."""
    name = cls.split("::")[-1]
    names = {name}
    derived = re.compile(rf"\bclass\s+(\w+)\s*(?:final\s*)?:\s*(?:public\s+)?(?:::)?(?:\w+::)*{re.escape(name)}\b")
    for f in sources:
        if name in f.text:
            names.update(derived.findall(f.text))
    found = []
    for n in sorted(names):
        pat = re.compile(rf"(?<!\w){re.escape(n)}\s+\w+\s*[;({{]")
        found += [(f, m.start()) for f in sources if n in f.text for m in pat.finditer(f.text)]
    return found


