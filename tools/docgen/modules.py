"""Catalogue of the driver and service modules in libs/bsw, the contracts in libs/bsp (DOC-04) and the modules
with a manifest in the ports (DOC-16). No Qt.

Everything on the page is collected, nothing is maintained by hand:

- purpose, kind, board wiring, project parameters, roles: the module manifest `module.yaml` (a parked
  `module.yaml.pending` is shown as such - tools/nxconfig and tools/bswgen do not load it);
- documentation: `doc/<module>.md` (else the first `*.md`) in the module directory;
- public headers: `include/**/*.h`;
- host tests: the entries of tools/test/tests.yaml whose `covers` names a file in the module directory, and the
  entries that name the module in their optional field `modules` (DOC-18: tests outside the module directory;
  tools/test refuses a name that is no manifest);
- state of verification: only the manifest fields `verification` and `verification_note` (DOC-14). Without them
  the page says "not stated" - it is never guessed from the changelog or prose;
- port modules: every `module.yaml` below the places tools/nxconfig reads port modules from
  (tools/nxconfig/config.py port_module_dirs): the family port templates `platforms/<family>/port` and the board
  ports `ecu/platforms/<board>`. Which of them a project gets depends on its derivative and board.

    mods = collect()                     # [ModuleDoc], libs/bsw, libs/bsp, then the ports, each sorted by name
    text = render_catalogue(mods)        # Markdown of doc/reference/modules.md, deterministic
    gaps(mods)                           # [(module, what is missing)]
    summary(mods)                        # sentence on manifests and verification, also used in README.md
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import yaml

from . import render

REPO = Path(__file__).resolve().parents[2]
LIBS = REPO / "libs"
TESTS_FILE = REPO / "tools" / "test" / "tests.yaml"
FILE = "modules.md"
MANIFEST = "module.yaml"
PENDING = "module.yaml.pending"
# Manifest fields for the state of verification (DOC-14, tools/nxconfig/model.py Manifest); read, never guessed.
VERIFICATION_FIELD = "verification"
NOTE_FIELD = "verification_note"
# order in which the levels are counted on the page (tools/nxconfig/model.py VERIFICATION_LEVELS, best first)
VERIFICATION_ORDER = ("hardware", "mock", "none")
NOT_STATED = "not stated"
SOURCES = ("libs/*/*/module.yaml, platforms/*/port/**/module.yaml, ecu/platforms/*/**/module.yaml, libs/*/*/doc "
           "and tools/test/tests.yaml")
GENERATED_NOTE = (f"<!-- Generated by tools/docgen from {SOURCES}. Do not edit: change the manifest, the module "
                  "documentation or the test list and run `.venv/Scripts/python tools/docgen`. -->")

# layer directory under libs/ -> repository path
LAYERS = {"bsw": "libs/bsw", "bsp": "libs/bsp"}
# layer key of the modules in a port (their root is the port directory, see PORT_GLOBS)
PORT = "port"
# port directories tools/nxconfig reads manifests from (tools/nxconfig/config.py family_ports_dir(), board_ports_dir()):
# (glob relative to the repository, how the page names such a port)
PORT_GLOBS = (("platforms/*/port", "family port"), ("ecu/platforms/*", "board port"))
# module.yaml connect kind -> board.yaml list the connection names an entry of (tools/nxconfig/checks.py CONNECT_KINDS)
CONNECT_BOARD = {"digital_output": "dio.outputs[]", "digital_input": "dio.inputs[]", "analog_input": "adc[]"}


@dataclass
class HostTest:
    name: str                                        # entry name in tools/test/tests.yaml (-k <name>)
    group: str
    files: list[str]                                 # covered files of this module, relative to the module directory
    named: bool = False                              # the entry names the module in its field `modules` (DOC-18)


@dataclass
class ListEntry:
    """What the catalogue reads of one entry of tools/test/tests.yaml."""
    name: str
    group: str
    covers: list[str]                                # covered repository paths
    modules: list[str] = field(default_factory=list)     # field `modules`: module names or module directories


@dataclass
class ModuleDoc:
    name: str
    layer: str                                       # key of LAYERS
    manifest: dict | None = None                     # parsed module.yaml or module.yaml.pending
    manifest_file: str | None = None                 # file name of the manifest in the module directory
    doc: str | None = None                           # repository relative path of the module documentation
    headers: list[str] = field(default_factory=list)     # relative to include/
    tests: list[HostTest] = field(default_factory=list)
    # port modules only: repository path of the port and of the module directory, and how the port is named
    port_root: str | None = None                     # e.g. platforms/s32k1xx/port
    port_dir: str | None = None                      # e.g. platforms/s32k1xx/port/safety/safeSystem
    port_kind: str | None = None                     # "family port" or "board port" (PORT_GLOBS)

    @property
    def path(self) -> str:
        return self.port_dir if self.layer == PORT else f"{LAYERS[self.layer]}/{self.name}"

    @property
    def root(self) -> str:
        """Repository path of the layer or port the module belongs to (column Layer)."""
        return self.port_root if self.layer == PORT else LAYERS[self.layer]

    @property
    def anchor(self) -> str:
        if self.layer == PORT:
            # the same module name may exist in several ports: the port's family or board name keeps it unique
            owner = [p for p in self.port_root.split("/") if p not in ("ecu", "platforms", "port")]
            return "m-" + "-".join(owner + [self.name]).lower()
        return "m-" + self.name.lower()

    @property
    def pending(self) -> bool:
        return self.manifest_file == PENDING

    def get(self, key: str, default=None):
        return (self.manifest or {}).get(key, default)

    @property
    def kind(self) -> str | None:
        return self.get("kind")

    @property
    def description(self) -> str | None:
        text = self.get("description")
        return " ".join(str(text).split()) if text else None

    @property
    def verification(self) -> str | None:
        value = self.get(VERIFICATION_FIELD)
        return " ".join(str(value).split()) if value not in (None, "") else None

    @property
    def verification_note(self) -> str | None:
        value = self.get(NOTE_FIELD)
        return " ".join(str(value).split()) if value not in (None, "") else None

    # --- configuration keys, derived from the manifest the way tools/nxconfig reads it (checks.py)
    def board_keys(self) -> list[str]:
        m = self.manifest or {}
        parts, connect = m.get("parts") or [], m.get("connect") or {}
        requires, provides = m.get("requires") or {}, m.get("provides") or []
        device = self.kind == "device_driver"
        out = []
        if parts:
            out.append("`devices[].part` matching " + ", ".join(f"`{p}`" for p in parts) +
                       f" - one instance per board device; `devices[].module: {self.name}` chooses this module "
                       "where several modules serve the part")
        elif device:
            out.append("`devices[].part` - the manifest lists no part pattern, so no board device can use the "
                       "module yet")
        for name, spec in connect.items():
            spec = spec or {}
            target = CONNECT_BOARD.get(spec.get("kind"), f"`{spec.get('kind')}`")
            flags = [spec.get("kind", "?")] + (["optional"] if spec.get("optional") else []) + \
                    (["switched off first by the fault handlers"] if spec.get("safe_off") else [])
            text = f"`devices[].connect.{name}` -> an entry of `{target}` ({', '.join(flags)})"
            if spec.get("description"):
                text += ": " + str(spec["description"])
            out.append(text)
        if "spi_device" in requires:
            out.append("`spi[].device` - the SPI bus the device sits on (the module requires `spi_device`)")
        if device and "can_phy" in provides:
            out.append("`can[].phy` - the CAN buses the device is the transceiver of (role `can_phy`)")
        return out

    def project_keys(self) -> list[str]:
        m = self.manifest or {}
        requires, provides = m.get("requires") or {}, m.get("provides") or []
        out = []
        if m.get("parameters"):
            if m.get("project_parameters"):
                out.append(f"`modules.{self.name}.<parameter>` - one entry per project, parameters below")
            else:
                out.append("`modules.<device>.<parameter>` - one entry per board device served by this module, "
                           "parameters below")
        if "spi_device" in requires and self.kind == "device_driver":
            out.append("`use.spi` - an instance is built when the project uses the SPI bus of its device")
        if self.kind == "device_driver" and "can_phy" in provides:
            out.append("`use.can` - the transceiver role is served for the CAN buses the project uses")
        names = sorted({p.get("names") for p in (m.get("parameters") or {}).values() if isinstance(p, dict)} - {None})
        if "can_bus" in names:
            out.append("`use.can` - parameters that name CAN buses accept only buses of `use.can`")
        return out


# ----------------------------------------------------------------------------------------------- collect


def _load_yaml(path: Path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _test_entries(tests_file: Path) -> list[ListEntry]:
    """Name, group, covered repository paths and named modules of every entry of tools/test/tests.yaml, in list
    order."""
    data = _load_yaml(tests_file) if tests_file.is_file() else None
    return [ListEntry(str(entry.get("name")), str(entry.get("group")),
                      [str(c).replace("\\", "/") for c in entry.get("covers") or []],
                      [str(m).replace("\\", "/").rstrip("/") for m in entry.get("modules") or []])
            for entry in (data or {}).get("tests") or []]


def _tests_of(mod: ModuleDoc, entries: list[ListEntry]) -> list[HostTest]:
    """The entries that cover a file in the module directory (those files relative to it) or name the module -
    by its name or its directory - in their field `modules`."""
    prefix = mod.path + "/"
    out = []
    for entry in entries:
        files = [c[len(prefix):] for c in entry.covers if c.startswith(prefix)]
        named = mod.name in entry.modules or mod.path in entry.modules
        if files or named:
            out.append(HostTest(entry.name, entry.group, files, named))
    return out


def _doc_file(directory: Path, name: str) -> Path | None:
    doc = directory / "doc"
    preferred = doc / f"{name}.md"
    if preferred.is_file():
        return preferred
    found = sorted(doc.glob("*.md")) if doc.is_dir() else []
    return found[0] if found else None


def _fill(mod: ModuleDoc, directory: Path, repo: Path, tests: list[ListEntry]) -> ModuleDoc:
    for manifest in (MANIFEST, PENDING):
        if (directory / manifest).is_file():
            data = _load_yaml(directory / manifest)
            mod.manifest = data if isinstance(data, dict) else {}
            mod.manifest_file = manifest
            break
    doc = _doc_file(directory, directory.name)
    mod.doc = doc.relative_to(repo).as_posix() if doc else None
    include = directory / "include"
    mod.headers = sorted(p.relative_to(include).as_posix() for p in include.glob("**/*.h")) \
        if include.is_dir() else []
    mod.tests = _tests_of(mod, tests)
    return mod


def _port_modules(repo: Path, tests: list[ListEntry]) -> list[ModuleDoc]:
    """Every directory with a manifest below a port directory of PORT_GLOBS, by port and then by module name."""
    mods = []
    for pattern, kind in PORT_GLOBS:
        for root in sorted((d for d in repo.glob(pattern) if d.is_dir()), key=lambda d: d.as_posix().lower()):
            dirs = {p.parent for name in (MANIFEST, PENDING) for p in root.rglob(name)}
            for directory in sorted(dirs, key=lambda d: (d.name.lower(), d.as_posix().lower())):
                mod = ModuleDoc(directory.name, PORT, port_root=root.relative_to(repo).as_posix(),
                                port_dir=directory.relative_to(repo).as_posix(), port_kind=kind)
                mods.append(_fill(mod, directory, repo, tests))
    return mods


def collect(libs: Path = LIBS, tests_file: Path = TESTS_FILE, repo: Path | None = None,
            ports: bool = True) -> list[ModuleDoc]:
    """Every directory in libs/bsw and libs/bsp, then every module with a manifest in a port (PORT_GLOBS below
    `repo`), with its manifest, documentation, headers and host tests."""
    repo = libs.parent if repo is None else repo
    tests = _test_entries(tests_file)
    mods = []
    for layer in LAYERS:
        base = libs / layer
        if not base.is_dir():
            continue
        for directory in sorted((d for d in base.iterdir() if d.is_dir()), key=lambda d: d.name.lower()):
            mods.append(_fill(ModuleDoc(directory.name, layer), directory, repo, tests))
    if ports:
        mods += _port_modules(repo, tests)
    return mods


# ----------------------------------------------------------------------------------------------- render


def short(text: str | None) -> str:
    """First clause of a manifest description for the overview table."""
    if not text:
        return f"_{NOT_STATED}_"
    for sep in ("; ", " - "):
        text = text.split(sep)[0]
    return text


def verification_text(mod: ModuleDoc) -> str:
    """Level and note for the module section: `hardware` - <verification_note>."""
    level = f"`{mod.verification}`" if mod.verification else f"_{NOT_STATED}_"
    return f"{level} - {render.prose(mod.verification_note)}" if mod.verification_note else level


def verification_cell(mod: ModuleDoc) -> str:
    """Level for the overview table; the note is too long for a cell, so the cell links to it."""
    if not mod.verification:
        return f"_{NOT_STATED}_"
    return f"{mod.verification} ([note](#{mod.anchor}))" if mod.verification_note else mod.verification


def verification_counts(mods: list[ModuleDoc]) -> list[tuple[str, int]]:
    """(level, number of modules) for every level that occurs, best level first, `not stated` last."""
    counts: dict[str, int] = {}
    for mod in mods:
        key = mod.verification or NOT_STATED
        counts[key] = counts.get(key, 0) + 1
    order = {level: i for i, level in enumerate(VERIFICATION_ORDER)}
    return sorted(counts.items(), key=lambda kv: (kv[0] == NOT_STATED, order.get(kv[0], len(order)), kv[0]))


def summary(mods: list[ModuleDoc]) -> str:
    """One or two sentences on manifests and stated verification, built from the data only."""
    no_manifest = [m for m in mods if m.manifest is None]
    pending = [m for m in mods if m.pending]
    parked = f"{len(pending)} of them parked (`{PENDING}`)" if pending else ""
    if not no_manifest:
        first = (f"All {len(mods)} modules have a manifest" if len(mods) != 1 else "The module has a manifest") + \
                (f", {parked}" if parked else "") + "."
    else:
        first = (f"{len(no_manifest)} of the {len(mods)} modules {'has' if len(no_manifest) == 1 else 'have'} no "
                 f"manifest" + (f", the others have one, {parked}" if parked else "") + ".")
    counts = verification_counts(mods)
    stated = [(level, n) for level, n in counts if level != NOT_STATED]
    missing = sum(n for level, n in counts if level == NOT_STATED)
    if not stated:
        second = "No manifest states its verification yet."
    else:
        second = "Verification stated: " + ", ".join(f"`{level}` {n}" for level, n in stated) + \
                 (f"; not stated: {missing}." if missing else "; every module states it.")
    return f"{first} {second}"


def manifest_state(mod: ModuleDoc) -> str:
    if mod.manifest_file is None:
        return "none"
    if mod.pending:
        return f"pending (`{PENDING}`)"
    return f"`{MANIFEST}`"


def _link(repo_path: str) -> str:
    return f"../../{repo_path}"


def _parameter_rows(parameters: dict) -> list[str]:
    header = ("Parameter", "Type", "Unit", "Default", "Allowed values", "Description")
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for name, spec in parameters.items():
        spec = spec if isinstance(spec, dict) else {}
        allowed = []
        if spec.get("min") is not None or spec.get("max") is not None:
            allowed.append(f"{spec.get('min', '')} .. {spec.get('max', '')}")
        if spec.get("pattern"):
            allowed.append(f"pattern `{spec['pattern']}`")
        if spec.get("names"):
            allowed.append(f"names: {spec['names']}")
        default = spec.get("default")
        cells = (f"`{name}`", str(spec.get("type", "")), str(spec.get("unit") or ""),
                 "required" if default is None else f"`{default}`", ", ".join(allowed),
                 render.prose(" ".join(str(spec["description"]).split())) if spec.get("description")
                 else render.MISSING_DESCRIPTION.replace("schema", "manifest"))
        lines.append("| " + " | ".join(render.cell(c) for c in cells) + " |")
    return lines


def _test_files_text(test: HostTest) -> str:
    """Covered files in the module directory; for an entry that names the module under `modules` also that."""
    files = ", ".join(f"`{f}`" for f in test.files)
    if not test.named:
        return files
    named = "named under `modules` (its test files lie outside the module directory)" if not files \
        else "also named under `modules`"
    return f"{files}; {named}" if files else named


def _tests_text(mod: ModuleDoc) -> str:
    return ", ".join(f"`{t.name}`" for t in mod.tests) if mod.tests else "none"


# DOC-76: modules of the power stage, the battery monitor and the multi-MCU link are not part of the first release
AFTER_R1 = ("gdTmc6200", "bccMc33771", "mcuLink")


def after_r1_section(mod: ModuleDoc) -> list[str]:
    return [f'<a id="{mod.anchor}"></a>', "", f"### {mod.name} (after R1)", "",
            render.prose(short(mod.description)) if mod.description else f"Purpose: _{NOT_STATED}_.", "",
            f"After R1: not part of the first release. Directory [`{mod.path}`]({_link(mod.path)}), manifest: "
            f"{manifest_state(mod)}. Keys, parameters and verification are listed once the module is released.", ""]


def section(mod: ModuleDoc) -> list[str]:
    if mod.name in AFTER_R1:
        return after_r1_section(mod)
    lines = [f'<a id="{mod.anchor}"></a>', "", f"### {mod.name}", ""]
    lines += [render.prose(mod.description) if mod.description else
              f"Purpose: _{NOT_STATED}_ ({'no manifest' if mod.manifest is None else 'the manifest has no description'}).",
              ""]
    if mod.pending:
        lines += [f"The manifest is parked as `{PENDING}`: `tools/nxconfig` and `tools/bswgen` do not load it, so "
                  "no project can use the module yet. The values below are what the parked manifest says.", ""]
    lines += [
        f"- **Directory:** [`{mod.path}`]({_link(mod.path)}), manifest: {manifest_state(mod)}, "
        f"kind: {f'`{mod.kind}`' if mod.kind else f'_{NOT_STATED}_'}",
    ]
    if mod.layer == PORT:
        lines.append(f"- **Port:** {mod.port_kind} [`{mod.port_root}`]({_link(mod.port_root)}) - " +
                     ("loaded by `tools/nxconfig` for the projects whose derivative belongs to this family"
                      if mod.port_kind == "family port" else
                      "loaded by `tools/nxconfig` for the projects on this board"))
    lines += ["- **Verification:** " + verification_text(mod)]
    if mod.headers:
        lines.append("- **Public headers:** " + ", ".join(f"`{h}`" for h in mod.headers))
    provides, requires = mod.get("provides") or [], mod.get("requires") or {}
    if provides:
        lines.append("- **Provides roles:** " + ", ".join(f"`{p}`" for p in provides))
    if requires:
        lines.append("- **Requires:** " + ", ".join(f"`{k}` × {v}" for k, v in requires.items()))
    extra = []
    lifecycle = mod.get("lifecycle")
    if isinstance(lifecycle, dict):
        extra.append(f"lifecycle level {lifecycle.get('level')} in task `{lifecycle.get('task')}`")
    if mod.get("console"):
        console = mod.get("console")
        extra.append("console command group per instance (parameter `console`)" if console == "instance"
                     else f"console command group `{console}`")
    if mod.get("cmake_target"):
        extra.append(f"CMake target `{mod.get('cmake_target')}`")
    if extra:
        lines.append("- **Integration:** " + ", ".join(extra))
    board, project = mod.board_keys(), mod.project_keys()
    if mod.manifest is not None:
        if board:
            lines.append("- **Board configuration (`board.yaml`):**")
            lines += ["    - " + b for b in board]
        if project:
            lines.append("- **Project configuration (`project.yaml`):**")
            lines += ["    - " + p for p in project]
    else:
        lines.append("- **Configuration:** not derivable (no manifest)")
    lines.append("")
    constraints = mod.get("constraints") or []
    parameters = mod.get("parameters") or {}
    if parameters:
        lines += _parameter_rows(parameters)
        lines.append("")
    if constraints:
        lines.append("Rules between the parameters (checked by `tools/nxconfig`): " +
                     ", ".join(f"`{c}`" for c in constraints) + ".")
        lines.append("")
    return lines


def render_catalogue(mods: list[ModuleDoc]) -> str:
    lines = ["<!-- SPDX-License-Identifier: Apache-2.0 -->", GENERATED_NOTE, "", "# Modules", ""]
    ports = [m for m in mods if m.layer == PORT]
    port_text = ""
    if ports:
        port_text = (" and every module with a manifest in a port (family port templates `platforms/<family>/port`, "
                     "board ports `ecu/platforms/<board>`)")
    lines += [
        "Every directory in `libs/bsw` (device drivers, services, libraries)" + (", " if ports else " and ") +
        f"`libs/bsp` (contracts and MCU drivers){port_text}, with what it is for, which configuration keys it reads, which host tests cover it "
        "and how far it is verified. The page is **generated** from the module manifests (`module.yaml`), the module "
        "documentation under `doc/` and the test list [`tools/test/tests.yaml`](../../tools/test/tests.yaml); a "
        "test fails as soon as page and sources disagree. How drivers are cut into modules: "
        "[driver granularity](../architecture/treiber-granularitaet.md) (German). What the configuration keys mean: "
        "[board description](board.md) and [project description](project.md).",
        "",
        "- **Purpose** - the `description` of the manifest. _not stated_ means there is no manifest or it has no "
        "description.",
        "- **Manifest** - `module.yaml` is read by `tools/nxconfig` and `tools/bswgen`; a parked "
        f"`{PENDING}` is not, so such a module cannot be used by a project yet.",
        "- **Host tests** - entries of `tools/test/tests.yaml` that list a file in the module directory under "
        "`covers` or name the module under `modules` (tests that lie elsewhere, e.g. in a generator's test "
        "directory; `tools/test` refuses a name without a manifest); run one with "
        "`.venv/Scripts/python tools/test -k <name>`.",
        f"- **Verification** - the manifest field `{VERIFICATION_FIELD}`: `none` (not yet), `mock` (host tests, "
        "register models, generator and build tests) or `hardware` (behaviour confirmed on a real board), "
        f"with the sentence `{NOTE_FIELD}` on what is confirmed on a board and what is not (linked as _note_ in "
        "the table, in full in the module section). Both are set by hand from the changelog; nothing here is "
        "inferred from the changelog or the module documentation, a module without the field reads "
        "_not stated_.",
        "",
        summary(mods) + " What is missing per module: [Gaps](#gaps).",
        "",
        "| Module | Layer | Kind | Purpose | Manifest | Host tests | Verification | Documentation |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for mod in mods:
        doc = f"[{Path(mod.doc).name}]({_link(mod.doc)})" if mod.doc else "none"
        cells = (f"[{mod.name}](#{mod.anchor})", mod.root, f"`{mod.kind}`" if mod.kind else f"_{NOT_STATED}_",
                 render.prose(short(mod.description)), manifest_state(mod), _tests_text(mod),
                 verification_cell(mod), doc)
        lines.append("| " + " | ".join(render.cell(c) for c in cells) + " |")
    lines.append("")
    for layer, title in (("bsw", "Device drivers and services (`libs/bsw`)"),
                         ("bsp", "Contracts and MCU drivers (`libs/bsp`)"),
                         (PORT, "Port modules (`platforms/<family>/port`, `ecu/platforms/<board>`)")):
        members = [m for m in mods if m.layer == layer]
        if not members:
            continue
        lines += [f"## {title}", ""]
        if layer == PORT:
            lines += ["Modules that belong to one MCU family or one board and therefore live in its port. "
                      "`tools/nxconfig` reads their manifests only for a project whose derivative is of that family "
                      "or which runs on that board (`port_module_dirs` in "
                      "[`tools/nxconfig/config.py`](../../tools/nxconfig/config.py)); a second family brings its own "
                      "module for the same parameters.", ""]
        for mod in members:
            lines += section(mod)
    lines += render_gaps(mods)
    lines += ["Back to the [reference overview](README.md).", ""]
    return "\n".join(lines)


# what gaps() reports -> heading of its list in the section "Gaps"
GAP_TITLES = {
    "no module.yaml (purpose, kind, configuration unknown)": "No manifest (purpose, kind and configuration unknown)",
    f"manifest parked as {PENDING}": f"Manifest parked as `{PENDING}`",
    "manifest without description": "Manifest without `description`",
    f"verification not stated (manifest field {VERIFICATION_FIELD})":
        f"Verification not stated (manifest field `{VERIFICATION_FIELD}`)",
    "no documentation under doc/": "No module documentation under `doc/`",
    "no host test in tools/test/tests.yaml": "No host test in `tools/test/tests.yaml` (no covered file in the module "
                                             "directory, module not named under `modules`)",
}


def _module_gaps(mod: ModuleDoc) -> list[str]:
    out = []
    if mod.manifest is None:
        out.append("no module.yaml (purpose, kind, configuration unknown)")
    else:
        if mod.pending:
            out.append(f"manifest parked as {PENDING}")
        if not mod.description:
            out.append("manifest without description")
    if not mod.verification:
        out.append(f"verification not stated (manifest field {VERIFICATION_FIELD})")
    if not mod.doc:
        out.append("no documentation under doc/")
    if not mod.tests:
        out.append("no host test in tools/test/tests.yaml")
    return out


def render_gaps(mods: list[ModuleDoc]) -> list[str]:
    """Section "Gaps": per kind of gap the modules that have it, in the order of GAP_TITLES and of the page."""
    lines = ['<a id="gaps"></a>', "", "## Gaps", "",
             "What the sources above do not say yet, per kind of gap (the same list as `tools/docgen --gaps`). A gap "
             "is closed in its source - the manifest, a `doc/` page in the module directory or an entry in "
             "`tools/test/tests.yaml` - and disappears here with the next run.", ""]
    by_gap: dict[str, list[ModuleDoc]] = {}
    for mod in mods:
        for what in _module_gaps(mod):
            by_gap.setdefault(what, []).append(mod)
    if not by_gap:
        return lines + ["None.", ""]
    for what in sorted(by_gap, key=lambda w: list(GAP_TITLES).index(w) if w in GAP_TITLES else len(GAP_TITLES)):
        members = by_gap[what]
        lines.append(f"- **{GAP_TITLES.get(what, what)}** ({len(members)}): " +
                     ", ".join(f"[{m.name}](#{m.anchor})" for m in members))
    return lines + [""]


def gaps(mods: list[ModuleDoc]) -> list[tuple[str, str]]:
    """(module path, what the page cannot say) for every gap, in page order."""
    return [(mod.path, what) for mod in mods for what in _module_gaps(mod)]
