"""Sensor characteristics of ADC channels: signed physical values in fixed units, integer only (IO-18).

Decisions of the user 2026-09-16 (doc/architecture/README.md section 4, "Sensor characteristics on ADC channels"):

  board    adc[].sensor          circuit in front of the pin, delivers the quantity at the connector
                                 linear | shunt_amplifier | divider | pullup | highside_is
           rails[]               supply rails the circuits refer to (pull-up supply, amplifier reference)
  project  adc_loads.<CHANNEL>   load connected to the channel: ntc_beta | table

Runtime model (generated by tools/bswgen as bsp/adc/analogSensorConfiguration.h, no floating point):

  x      = min(raw, calc_high)                                   raw code of the converter
  board  = round((a * x + b) / (c * x + d))                      int64, c * x + d > 0 for every x <= calc_high
  value  = board                          without a load
         = interpolate(points, board)     with a load (points ascending in the board value, ends held)
  quality OK for ok_low <= raw <= ok_high and a board value inside the points, otherwise RANGE

round() is half away from zero. Pin voltage U = raw * V / M (V = board.adc_reference_mv, M = 2^bits - 1):

  scale (no sensor)  U * factor + offset_mv                      mV, the formula of adc.mv without the limit at 0
  linear             U * gain_num / gain_den + offset             unit of the entry
  divider            U * (r_top + r_bottom) / r_bottom            mV
  shunt_amplifier    (U - U_ref) * 10^6 * gain_den / (gain * R_shunt[uOhm])     mA
  pullup             R_pu * U / (U_supply - U_diode - U)           ohm, computable while the denominator is > 0
  highside_is        k_ILIS * U / R_IS                             mA

Quality RANGE (QLF_ERROR_RANGE of the RTE) marks the ends of the converter (raw 0 and full scale, decision 5), the
output range of an amplifier (output_min_mv/output_max_mv), the open input of a pull-up and a board value outside
the points of a load. Everything nxconfig reports comes with the YAML path: int64 intermediate values, int32 results
over every raw code, points of a table or an NTC that do not ascend, the interpolation error of an NTC table.
"""

import math
from dataclasses import dataclass
from fractions import Fraction

from .config import Config, Reporter

INT32_MIN, INT32_MAX = -(1 << 31), (1 << 31) - 1
INT64_MAX = (1 << 63) - 1
SEGMENT_PRODUCT_MAX = 1 << 62               # |dx * dy| of one table segment, headroom for the rounding
KELVIN_DDEGC = 2731.5                       # 0 degC in 0.1 K

# Quality codes of the generated conversion; equal to QLF_OK and QLF_ERROR_RANGE of the RTE (Rte_Qlf.h,
# doc/architecture/signal-qualifier.md), test_rtegen.py compares them.
QUALITY_OK = 1
QUALITY_RANGE = 32

BOARD_UNITS = {"divider": "mV", "shunt_amplifier": "mA", "pullup": "ohm", "highside_is": "mA", "scale": "mV"}


@dataclass(frozen=True)
class SensorPlan:
    """Integer conversion of one used board ADC channel."""

    name: str
    kind: str                                       # scale (no sensor block) or the sensor kind
    unit: str                                       # unit of adc.phys (the load's unit with a load)
    board_unit: str
    load: str | None                                # ntc_beta, table or None
    max_raw: int
    a: int
    b: int
    c: int
    d: int
    calc_high: int                                  # highest raw code the rational function is computed for
    ok_low: int
    ok_high: int
    points: tuple[tuple[int, int], ...]             # load table (board value, value), empty without a load
    value_min: int                                  # adc.phys over every raw code
    value_max: int
    formula: str                                    # for the generated comment
    confirmed: bool                                 # source given and not verify (board sensor and load)
    max_error: int | None                           # NTC: largest deviation of the table from the model (0.1 degC)


def div_round(num: int, den: int) -> int:
    """Integer division rounding half away from zero, den > 0 (the C function nxAdcSensorDivRound)."""
    return (num + den // 2) // den if num >= 0 else -((-num + den // 2) // den)


def interpolate(points, x: int) -> tuple[int, bool]:
    """(value, inside) of a load table (the C function nxAdcSensorTable)."""
    if x <= points[0][0]:
        return points[0][1], x == points[0][0]
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if x <= x1:
            return y0 + div_round((x - x0) * (y1 - y0), x1 - x0), True
    return points[-1][1], False


def board_value(plan: SensorPlan, raw: int) -> int:
    x = min(raw, plan.calc_high)
    return div_round(plan.a * x + plan.b, plan.c * x + plan.d)


def evaluate(plan: SensorPlan, raw: int) -> tuple[int, int]:
    """Python reference of the generated conversion: (adc.phys, quality code) for a raw code 0..max_raw."""
    value = board_value(plan, raw)
    ok = plan.ok_low <= raw <= plan.ok_high
    if plan.points:
        value, inside = interpolate(plan.points, value)
        ok = ok and inside
    return value, QUALITY_OK if ok else QUALITY_RANGE


def _reduce(a: int, b: int, c: int, d: int) -> tuple[int, int, int, int]:
    g = math.gcd(math.gcd(a, b), math.gcd(c, d))
    return (a // g, b // g, c // g, d // g) if g > 1 else (a, b, c, d)


def _frac(value) -> Fraction:
    return Fraction(str(value))


class _Channel:
    """Derives the plan of one board channel; reports with the board path adc[i]."""

    def __init__(self, cfg: Config, rep: Reporter, index: int, ch):
        self.cfg, self.rep, self.index, self.ch = cfg, rep, index, ch
        self.base = ("adc", index)
        self.vref = cfg.board.board.adc_reference_mv
        inst = cfg.derivative.instances.get(ch.instance)
        self.max_raw = (1 << inst.resolution_bits) - 1 if inst is not None and inst.resolution_bits else None

    def error(self, path, text):
        self.rep.error("board", self.base + tuple(path), f"ADC {self.ch.name}: {text}")

    def rail(self, where: tuple, ref) -> Fraction | None:
        if ref.mv is not None:
            return Fraction(ref.mv)
        rails = {r.name: r for r in self.cfg.board.rails}
        rail = rails.get(ref.rail)
        if rail is None:
            self.error(where + ("rail",), f"unknown rail {ref.rail} (board rails: "
                       f"{', '.join(rails) if rails else 'none'})")
            return None
        return Fraction(rail.mv * ref.ratio_permille, 1000)

    def rail_confirmed(self, ref) -> bool:
        if ref.mv is not None:
            return True
        rail = next((r for r in self.cfg.board.rails if r.name == ref.rail), None)
        return rail is not None and rail.source is not None and not rail.verify

    def coefficients(self):
        """(kind, unit, a, b, c, d, ok_low, ok_high, calc_high, formula, confirmed) or None after an error."""
        ch, v, m = self.ch, self.vref, self.max_raw
        s = ch.sensor
        ok_low, ok_high, calc_high = 1, m - 1, m
        if s is None:
            sc = ch.scale
            if sc.divider is not None:
                factor = (_frac(sc.divider.r_top) + _frac(sc.divider.r_bottom)) / _frac(sc.divider.r_bottom)
            else:
                factor = _frac(sc.factor if sc.factor is not None else 1)
            p, q = factor.numerator, factor.denominator
            a, b, c, d = v * p, sc.offset_mv * m * q, 0, m * q
            formula = f"U * {factor} + {sc.offset_mv} mV (board scale)"
            return "scale", "mV", a, b, c, d, ok_low, ok_high, calc_high, formula, not sc.verify
        if (ch.scale.divider is not None or ch.scale.offset_mv != 0
                or (ch.scale.factor is not None and _frac(ch.scale.factor) != 1)):
            self.error(("scale",), "scale and sensor both describe the circuit; with a sensor the scale stays at "
                       "factor 1 (adc.mv = pin voltage)")
            return None
        confirmed = s.source is not None and not s.verify
        if s.kind == "linear":
            a, b, c, d = v * s.gain_num, s.offset * m * s.gain_den, 0, m * s.gain_den
            formula = f"U * {s.gain_num} / {s.gain_den} + {s.offset} {s.unit}"
            unit = s.unit
        elif s.kind == "divider":
            a, b, c, d = v * (s.r_top_ohm + s.r_bottom_ohm), 0, 0, m * s.r_bottom_ohm
            formula = f"U * ({s.r_top_ohm} + {s.r_bottom_ohm}) / {s.r_bottom_ohm}"
            unit = "mV"
        elif s.kind == "shunt_amplifier":
            ref = self.rail(("sensor", "reference"), s.reference)
            if ref is None:
                return None
            confirmed = confirmed and self.rail_confirmed(s.reference)
            p, q = ref.numerator, ref.denominator
            scale = 1000000 * s.gain_den
            a, b, c, d = v * q * scale, -p * m * scale, 0, m * q * s.gain * s.shunt_uohm
            gain = f"{s.gain}" if s.gain_den == 1 else f"{s.gain}/{s.gain_den}"
            formula = f"(U - {float(ref):g} mV) / ({gain} V/V * {s.shunt_uohm} uOhm)"
            unit = "mA"
            if s.output_min_mv is not None:
                ok_low = max(ok_low, -(-s.output_min_mv * m // v))
            if s.output_max_mv is not None:
                ok_high = min(ok_high, s.output_max_mv * m // v)
            if (s.output_min_mv is not None and s.output_max_mv is not None
                    and s.output_min_mv >= s.output_max_mv):
                self.error(("sensor", "output_max_mv"), f"output_max_mv {s.output_max_mv} must be above "
                           f"output_min_mv {s.output_min_mv}")
                return None
        elif s.kind == "pullup":
            supply = self.rail(("sensor", "supply"), s.supply)
            if supply is None:
                return None
            confirmed = confirmed and self.rail_confirmed(s.supply)
            top = supply - s.diode_mv
            if top <= 0:
                self.error(("sensor", "diode_mv"), f"diode_mv {s.diode_mv} is not below the supply {float(supply):g} mV")
                return None
            p, q = top.numerator, top.denominator
            a, b, c, d = s.pullup_ohm * v * q, 0, -v * q, p * m
            calc_high = min(m, (d - 1) // (-c))    # denominator c * x + d > 0
            ok_high = min(ok_high, calc_high)
            diode = f" - {s.diode_mv} mV" if s.diode_mv else ""
            formula = f"{s.pullup_ohm} * U / ({float(supply):g} mV{diode} - U)"
            unit = "ohm"
        else:                                       # highside_is
            if not self.highside_device(s):
                return None
            a, b, c, d = s.k_ilis * v, 0, 0, m * s.r_is_ohm
            formula = f"{s.k_ilis} * U / {s.r_is_ohm} ohm"
            unit = "mA"
        return s.kind, unit, a, b, c, d, ok_low, ok_high, calc_high, formula, confirmed

    def highside_device(self, s) -> bool:
        device = next((dev for dev in self.cfg.board.devices if dev.name == s.device), None)
        if device is None:
            self.error(("sensor", "device"), f"unknown device {s.device}")
            return False
        wired = [key for key, target in device.connect.items() if target == self.ch.name]
        if not wired:
            self.error(("sensor", "device"), f"device {s.device} is not wired to this channel "
                       f"(devices[{s.device}].connect names no {self.ch.name})")
            return False
        return True

    def plan(self) -> SensorPlan | None:
        ch = self.ch
        if not ch.fitted and ch.sensor is not None:
            self.error(("sensor",), "the channel is marked fitted: false; a circuit that is not fitted has no sensor")
            return None
        if self.vref is None or self.max_raw is None:
            return None                             # reported by the board/project checks
        result = self.coefficients()
        if result is None:
            return None
        kind, unit, a, b, c, d, ok_low, ok_high, calc_high, formula, confirmed = result
        where = ("sensor",) if ch.sensor is not None else ("scale",)
        if calc_high < 0:
            self.error(where, "no ADC code gives a value (the denominator is never positive)")
            return None
        if ok_low > ok_high:
            self.error(where, f"no ADC code gives a valid value (valid raw range {ok_low}..{ok_high})")
            return None
        a, b, c, d = _reduce(a, b, c, d)
        # Without a sensor block the channel keeps its adc.mv scaling (uint32, checked by the generator); a scale
        # beyond int32 only means that there is no adc.phys for it - a warning, not an error.
        report = self.error if kind != "scale" else (
            lambda path, text: self.rep.warning("board", self.base + tuple(path),
                                                f"ADC {ch.name}: {text}; adc.phys.{ch.name} is not available"))
        values = []
        for raw in range(calc_high + 1):
            num, den = a * raw + b, c * raw + d
            if (max(abs(a * raw), abs(c * raw), abs(b), abs(d)) > INT64_MAX or abs(num) + den // 2 > INT64_MAX
                    or not 0 < den <= INT64_MAX):
                report(where, f"the integer conversion overflows int64 at raw {raw} (numerator {num}, "
                       f"denominator {den}); the values are too precise or too large")
                return None
            values.append(div_round(num, den))
        low, high = min(values), max(values)
        if low < INT32_MIN or high > INT32_MAX:
            report(where, f"the value range {low}..{high} {unit} does not fit int32 (adc.phys)")
            return None
        return SensorPlan(ch.name, kind, unit, unit, None, self.max_raw, a, b, c, d, calc_high, ok_low, ok_high, (),
                          low, high, formula, confirmed, None)


def _ntc_points(load, name: str, rep: Reporter) -> tuple[tuple[int, int], ...] | None:
    path = ("adc_loads", name)
    if load.t_min_ddegc >= load.t_max_ddegc:
        rep.error("project", path + ("t_max_ddegc",), f"adc load {name}: t_max_ddegc {load.t_max_ddegc} must be above "
                  f"t_min_ddegc {load.t_min_ddegc}")
        return None
    temps = list(range(load.t_min_ddegc, load.t_max_ddegc, load.step_ddegc)) + [load.t_max_ddegc]
    if len(temps) > 255:
        rep.error("project", path + ("step_ddegc",), f"adc load {name}: {len(temps)} points from t_min to t_max, at "
                  f"most 255 (larger step_ddegc)")
        return None
    t_n = (load.t_nominal_ddegc + KELVIN_DDEGC) / 10
    points = []
    for t in temps:
        exponent = load.beta_k * (1 / ((t + KELVIN_DDEGC) / 10) - 1 / t_n)
        r = load.r_nominal_ohm * math.exp(min(exponent, 50.0))     # exp(50) * 1 ohm is beyond int32 anyway
        if round(r) > INT32_MAX:
            rep.error("project", path + ("t_min_ddegc",), f"adc load {name}: {round(r)} ohm at {t / 10:g} degC does "
                      f"not fit int32 (higher t_min_ddegc)")
            return None
        points.append((round(r), t))
    points.reverse()                                # ascending resistance
    for (r0, t0), (r1, t1) in zip(points, points[1:]):
        if r1 <= r0:
            rep.error("project", path + ("step_ddegc",), f"adc load {name}: {t1 / 10:g} and {t0 / 10:g} degC give "
                      f"the same resistance {r0} ohm after rounding (larger step_ddegc or t_max_ddegc lower)")
            return None
    return tuple(points)


def _ntc_temperature(load, ohm: float) -> float:
    t_n = (load.t_nominal_ddegc + KELVIN_DDEGC) / 10
    return (1 / (1 / t_n + math.log(ohm / load.r_nominal_ohm) / load.beta_k)) * 10 - KELVIN_DDEGC


def _with_load(cfg: Config, rep: Reporter, plan: SensorPlan, load) -> SensorPlan | None:
    name, path = plan.name, ("adc_loads", plan.name)
    max_error = None
    if load.kind == "ntc_beta":
        if plan.board_unit != "ohm":
            rep.error("project", path + ("kind",), f"adc load {name}: an NTC needs a resistance from the board "
                      f"(sensor kind pullup, unit ohm), the channel delivers {plan.board_unit} ({plan.kind})")
            return None
        points = _ntc_points(load, name, rep)
        if points is None:
            return None
        unit, formula = "ddegC", (f"NTC R_n {load.r_nominal_ohm} ohm at {load.t_nominal_ddegc / 10:g} degC, "
                                  f"B {load.beta_k} K, {len(points)} points {load.t_min_ddegc / 10:g}.."
                                  f"{load.t_max_ddegc / 10:g} degC")
    else:
        points = tuple((x, y) for x, y in load.points)
        for k, ((x0, _), (x1, _)) in enumerate(zip(points, points[1:])):
            if x1 <= x0:
                rep.error("project", path + ("points", k + 1, 0), f"adc load {name}: board values of the points must "
                          f"ascend ({x0} then {x1})")
                return None
        unit, formula = load.unit, f"table of {len(points)} points ({plan.board_unit} -> {load.unit})"
    for k, ((x0, y0), (x1, y1)) in enumerate(zip(points, points[1:])):
        if (x1 - x0) * abs(y1 - y0) >= SEGMENT_PRODUCT_MAX:
            rep.error("project", path + ("points" if load.kind == "table" else "step_ddegc",),
                      f"adc load {name}: segment {k} ({x0}..{x1}) overflows the int64 interpolation")
            return None

    staged = SensorPlan(**{**plan.__dict__, "unit": unit, "load": load.kind, "points": points,
                           "formula": f"{plan.formula}; {formula}",
                           "confirmed": plan.confirmed and load.source is not None and not load.verify})
    values = [evaluate(staged, raw)[0] for raw in range(plan.max_raw + 1)]
    if load.kind == "ntc_beta":
        # deviation of the integer chain (board rounding + table) from the model over the valid codes in the table
        errors = []
        for raw in range(plan.ok_low, plan.ok_high + 1):
            x = min(raw, plan.calc_high)
            exact = Fraction(plan.a * x + plan.b, plan.c * x + plan.d)
            if points[0][0] <= exact <= points[-1][0] and exact > 0:
                errors.append(abs(evaluate(staged, raw)[0] - _ntc_temperature(load, float(exact))))
        max_error = math.ceil(max(errors)) if errors else 0
        if max_error > load.max_error_ddegc:
            rep.warning("project", path + ("step_ddegc",), f"adc load {name}: the table deviates up to "
                        f"{max_error / 10:g} degC from the NTC model (max_error_ddegc {load.max_error_ddegc}): "
                        f"smaller step_ddegc")
    return SensorPlan(**{**staged.__dict__, "value_min": min(values), "value_max": max(values),
                         "max_error": max_error})


def check(cfg: Config, rep: Reporter) -> dict[str, SensorPlan]:
    """Plans of the used board channels by name; channels with errors are left out (the messages say why)."""
    board_adc = cfg.board.adc
    selection = cfg.project.use.adc
    if selection != "all":
        for name in selection:
            index = next((i for i, ch in enumerate(board_adc) if ch.name == name), None)
            if index is not None and not board_adc[index].fitted:
                rep.warning("project", ("use", "adc"), f"ADC channel {name} is used, but board adc[{index}] marks its "
                            f"circuit as not fitted (fitted: false): the pin reads no quantity")
    used = {ch.name for ch in cfg.selected("adc")}
    plans = {}
    for i, ch in enumerate(board_adc):
        plan = _Channel(cfg, rep, i, ch).plan()
        if plan is not None and ch.name in used and ch.fitted:
            plans[ch.name] = plan

    names = {ch.name: ch for ch in board_adc}
    for name, load in cfg.project.adc_loads.items():
        path = ("adc_loads", name)
        ch = names.get(name)
        if ch is None:
            rep.error("project", path, f"adc load {name}: no board ADC channel {name}")
        elif name not in used:
            rep.error("project", path, f"adc load {name}: channel {name} is not used by the project (use.adc)")
        elif not ch.fitted:
            rep.error("project", path, f"adc load {name}: board marks channel {name} as not fitted (fitted: false)")
        elif ch.sensor is None:
            rep.error("project", path, f"adc load {name}: board channel {name} has no sensor block; a load needs the "
                      f"circuit in front of the pin (e.g. pullup for an NTC)")
        elif name in plans:
            staged = _with_load(cfg, rep, plans[name], load)
            if staged is None:
                del plans[name]
            else:
                plans[name] = staged
    return plans
