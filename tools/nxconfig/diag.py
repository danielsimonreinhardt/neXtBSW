"""Diagnostic addresses of a project (COM-11): UDS on ISO-TP for the bootloader and the application.

Project (`diagnostics`) + memory layout (memory.py) + the diagnostic bus of the ECU description
(rte.yaml uds.bus, ARCH-07) -> one DiagPlan. tools/bswgen/blgen.py writes it as
<build>/generated/board/bootloader/bl_diag.h, which bootloader/include/bl_config.h includes and
tools/canflash reads, so bootloader, application UDS stack (ecu/uds) and tester use one source.

Family and board neutral, no Qt; every finding carries file, YAML path and line. Checked here:
- CAN ids inside the 11-bit range and different from each other,
- no collision with the CAN messages of the project's DBC on the same bus,
- the area the application searches for the bootloader version inside the bootloader's flash,
- ISO-TP values the protocol can encode and that keep a download usable (STmin, block size, timeouts),
- XCP on CAN (project `xcp`, TOOL-26): bus of the project, 11/29-bit range, no collision with the diagnostic ids
  and the DBC messages on the same bus. The application runs these ids at the same time on one bus, so a
  collision would route XCP commands into the UDS stack (or the other way round) and is an error.

Not a project value: the data identifiers and routine identifiers of the UDS services. They are protocol
constants that bootloader (bootloader/src/core/uds.c), application (ecu/uds, generated by tools/diaggen) and
tools/canflash must agree on, not a property of a board or an ECU software.
"""

import re
from dataclasses import dataclass
from pathlib import Path

from .config import Config, Reporter, read_rte

CAN_ID_MAX_11BIT = 0x7FF
CAN_ID_MAX_29BIT = 0x1FFFFFFF

# Flash the application must not search for the bootloader version string, in bytes from the start of the code
# flash. s32k1xx puts the flash configuration field at 0x400..0x40F, right behind the vector table of the
# bootloader; reading it is harmless but it is not code and never carries the string. A family that is not
# listed is searched from the first byte of the bootloader area; a project can always name the address itself
# (diagnostics.bootloader.scan_start).
FAMILY_SCAN_OFFSET = {"s32k1xx": 0x410}

# STmin is encoded in one byte of the flow control frame: 0x00..0x7F are milliseconds, 0xF1..0xF9 are
# 100..900 us (ISO 15765-2). Only whole milliseconds are configurable here.
STMIN_MS_MAX = 0x7F
# Largest UDS block of the bootloader (bl_config.h BL_MAX_BLOCK_LENGTH): used to judge STmin
DOWNLOAD_BLOCK_BYTES = 1026
CONSECUTIVE_FRAME_BYTES = 7
# A separation time that makes one download block take longer than this is reported (the tester's P2* and the
# download of a whole application would grow into minutes)
DOWNLOAD_BLOCK_WARN_MS = 1000

# CAN id of the updater's status frames (bootloader/updater/include/upd_config.h UPD_STATUS_CAN_ID). Not a
# project value yet; until it is one, a project that uses it for UDS gets a warning here (COM-11 follow-up).
UPDATER_STATUS_CAN_ID = 0x7EE

# BL-03: security access methods and their number in the bootloader (bootloader/include/bl_config.h
# BL_SECURITY_METHOD_*; tools/canflash reads the number from DID 0xF1A1). New methods (e.g. ed25519) get the next one.
SECURITY_METHOD_IDS = {"hmac-sha256": 1}

DBC_MESSAGE = re.compile(r"^\s*BO_\s+(\d+)\s+([A-Za-z_][\w]*)\s*:", re.M)
DBC_EXTENDED_FLAG = 1 << 31


@dataclass(frozen=True)
class DiagPlan:
    """Diagnostic addresses of a checked project; all addresses in bytes, `scan_end` exclusive."""

    bus: str | None                 # board CAN bus the application answers on (rte.yaml uds.bus), None: unknown
    request_id: int                 # physically addressed request
    functional_id: int
    response_id: int
    tester_address: int
    ecu_address: int
    padding: int
    block_size: int
    stmin_ms: int
    n_cr_ms: int
    n_bs_ms: int
    version_prefix: str             # BL_VERSION_STRING without the version number
    scan_start: int                 # first address the application searches for the version string
    scan_end: int                   # end of the search area (exclusive): start of the application
    scan_start_from_project: bool   # False: derived from the family (FAMILY_SCAN_OFFSET)
    # BL-03: security access of the bootloader (diagnostics.bootloader.security)
    security_method: str = "hmac-sha256"
    key_name: str = ""              # master key in the key store of the workstation (tools/canflash/blkeys.py)
    allow_test_key: bool = False    # the insecure test key of the repository may be used (test profiles)
    uid_address: int | None = None  # chip UID of the derivative (mcudb uid), None: unknown
    uid_size: int = 0

    @property
    def security_method_id(self) -> int:
        """BL_SECURITY_METHOD: number of the method in the bootloader (bl_config.h BL_SECURITY_METHOD_*)."""
        return SECURITY_METHOD_IDS[self.security_method]

    @property
    def version_string_prefix(self) -> str:
        """What the application looks for and the updater compares: prefix and the separating space."""
        return f"{self.version_prefix} "


def _hex(value: int) -> str:
    return f"0x{value:X}"


def scan_offset(family: str) -> int:
    """Bytes at the start of the code flash the application skips when searching for the version string."""
    return FAMILY_SCAN_OFFSET.get(family, 0)


def dbc_messages(text: str) -> dict[int, str]:
    """CAN id -> message name of a DBC text; extended ids keep the flag of the DBC (bit 31)."""
    return {int(number): name for number, name in DBC_MESSAGE.findall(text)}


def _ecu_buses(cfg: Config) -> tuple[str | None, str | None, str | None]:
    """(diagnostic bus, bus of the CAN signals, DBC path as the description spells it - relative to the rte.yaml
    since RTE-22) of the ECU description (rte.yaml, ARCH-07), resolved like tools/rtegen does (uds.bus, else
    can.bus, else the first used bus).

    ARCH-34: the schema model the configuration was loaded with (Config.rte); a Config built without check() reads
    the file itself. Schema findings are reported by check() at the rte level, so an unreadable or invalid file
    gives all values None here.
    """
    rte = cfg.rte_file
    if rte is None or not rte.is_file():
        return None, None, None
    ecu = cfg.rte if cfg.rte is not None else read_rte(rte)[0]
    if ecu is None:
        return None, None, None
    used = [b.name for b in cfg.selected("can")]
    signal_bus = (ecu.can.bus if ecu.can is not None else None) or (used[0] if used else None)
    bus = (ecu.uds.bus if ecu.uds is not None else None) or signal_bus
    dbc = ecu.can.dbc if ecu.can is not None else None
    return bus, signal_bus, dbc


def _ecu_can(cfg: Config) -> tuple[str | None, str | None]:
    """(diagnostic bus, DBC path if the DBC is on the diagnostic bus) of the ECU description."""
    bus, signal_bus, dbc = _ecu_buses(cfg)
    return bus, (dbc if dbc and bus == signal_bus else None)


def _dbc_base(cfg: Config) -> Path:
    """Folder `can.dbc` of the ECU description is relative to (RTE-22): the rte.yaml's own folder.

    Format 1 of the description had it relative to the repository; such a file is refused by the schema with the
    migration command (migrate.finding), so this is the only base left for a file that loads at all.
    """
    rte = cfg.rte_file
    return rte.parent if rte is not None else cfg.running_tree


def _read_dbc(dbc: str | None, base: Path) -> dict[int, str]:
    """CAN id (bit 31: extended) -> message name of the project's DBC; empty if there is none or it is unreadable."""
    if dbc is None:
        return {}
    file = base / dbc                               # can.dbc is relative to the rte.yaml (RTE-22)
    if not file.is_file():
        return {}                                   # rtegen reports a missing DBC
    try:
        return dbc_messages(file.read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return {}


def _check_ids(rep: Reporter, use) -> None:
    ids = {"request_id": use.request_id, "functional_id": use.functional_id, "response_id": use.response_id}
    for key, value in ids.items():
        if value > CAN_ID_MAX_11BIT:
            rep.error("project", ("diagnostics", key), f"CAN id {_hex(value)} is outside the 11-bit range "
                      f"(0x000..{_hex(CAN_ID_MAX_11BIT)}); DoCAN normal addressing with 29-bit ids is not "
                      "supported by bootloader and application (bl_diag.h, ecu/uds)")
        elif value == UPDATER_STATUS_CAN_ID:
            rep.warning("project", ("diagnostics", key), f"CAN id {_hex(value)} is the id of the updater's "
                        "status frames (bootloader/updater/include/upd_config.h UPD_STATUS_CAN_ID): during a "
                        "bootloader update the status frames would look like diagnostic frames")
    for key, other in (("response_id", "request_id"), ("functional_id", "request_id"),
                       ("functional_id", "response_id")):
        if ids[key] == ids[other]:
            rep.error("project", ("diagnostics", key), f"{key} {_hex(ids[key])} is also {other}: request, "
                      "functional request and response need three different CAN ids")


def _check_dbc(rep: Reporter, use, bus: str | None, dbc: str | None, base: Path) -> None:
    """CAN ids of the project's DBC against the diagnostic ids (same bus only)."""
    messages = _read_dbc(dbc, base)
    for key, value in (("request_id", use.request_id), ("functional_id", use.functional_id),
                       ("response_id", use.response_id)):
        for number, name in messages.items():
            if number & DBC_EXTENDED_FLAG:          # extended id, no collision with an 11-bit diagnostic id
                continue
            if number == value:
                rep.error("project", ("diagnostics", key), f"{key} {_hex(value)} is also the CAN id of message "
                          f"{name} of {dbc}" + (f" on bus {bus}" if bus else "")
                          + ": the diagnostic frames and the application's messages would overwrite each other")


def _xcp_id(value: int) -> str:
    """CAN id in the notation of project.yaml, with the 29-bit value if bit 31 marks an extended id."""
    if value & DBC_EXTENDED_FLAG:
        return f"{_hex(value)} (29-bit {_hex(value & CAN_ID_MAX_29BIT)})"
    return _hex(value)


def check_xcp(cfg: Config, rep: Reporter, uds_bus: str | None, signal_bus: str | None, dbc: str | None) \
        -> str | None:
    """XCP on CAN of the project (TOOL-26): the bus XCP runs on, None without `xcp` or after an error.

    Identifiers use the encoding of the DBC and of ::can::CanId: bit 31 set marks a 29-bit identifier. Collisions
    count on the XCP bus only; the bootloader does not run together with the application and is not compared.
    tools/rtegen resolves the bus the same way (xcp.bus, else the diagnostic bus) and adds master_id to the
    hardware receive filter of that bus.
    """
    use = cfg.project.xcp
    if use is None:
        return None
    errors = len(rep.messages)
    ids = {"master_id": use.master_id, "slave_id": use.slave_id}
    for key, value in ids.items():
        raw = value & ~DBC_EXTENDED_FLAG
        if value & DBC_EXTENDED_FLAG:
            if raw > CAN_ID_MAX_29BIT:
                rep.error("project", ("xcp", key), f"CAN id {_hex(value)} is outside the 29-bit range "
                          f"(bit 31 marks a 29-bit id, then 0x0..{_hex(CAN_ID_MAX_29BIT)})")
        elif raw > CAN_ID_MAX_11BIT:
            rep.error("project", ("xcp", key), f"CAN id {_hex(value)} is outside the 11-bit range "
                      f"(0x000..{_hex(CAN_ID_MAX_11BIT)}); a 29-bit id has bit 31 set "
                      f"({_hex(value | DBC_EXTENDED_FLAG)})")
    if use.master_id == use.slave_id:
        rep.error("project", ("xcp", "slave_id"), f"slave_id {_xcp_id(use.slave_id)} is also master_id: command "
                  "and response of XCP need two different CAN ids")
    used = [b.name for b in cfg.selected("can")]
    # without an ECU description rtegen is given one from elsewhere; with no uds:/can: section it picks the
    # first bus of the project, so the diagnostic bus is that one here as well
    uds_bus = uds_bus or (used[0] if used else None)
    signal_bus = signal_bus or (used[0] if used else None)
    if use.bus is not None:
        bus = use.bus
        if bus not in used:
            rep.error("project", ("xcp", "bus"), f"bus {bus} is not a CAN bus of the project "
                      f"(use.can: {', '.join(used) if used else 'none'})")
    else:
        bus = uds_bus
        if bus is None:
            rep.error("project", ("xcp",), "no bus for XCP: xcp.bus is not set and the project uses no CAN bus "
                      "(use.can) that could be its diagnostic bus")
    if any(m.severity == "error" for m in rep.messages[errors:]):
        return None
    taken: list[tuple[int, str]] = []
    diag = cfg.project.diagnostics
    if diag is not None and bus == uds_bus:
        taken += [(diag.request_id, "diagnostics.request_id"), (diag.functional_id, "diagnostics.functional_id"),
                  (diag.response_id, "diagnostics.response_id")]
    if bus == signal_bus:
        taken += [(number, f"the CAN id of message {name} of {dbc}")
                  for number, name in _read_dbc(dbc, _dbc_base(cfg)).items()]
    for key, value in ids.items():
        for number, what in taken:
            if number == value:
                rep.error("project", ("xcp", key), f"{key} {_xcp_id(value)} is also {what} on bus {bus}: XCP and "
                          "the application would take each other's frames")
    return None if any(m.severity == "error" for m in rep.messages[errors:]) else bus


def _check_isotp(rep: Reporter, use) -> None:
    tp = use.isotp
    if tp.stmin_ms > STMIN_MS_MAX:
        rep.error("project", ("diagnostics", "isotp", "stmin_ms"), f"STmin {tp.stmin_ms} ms cannot be encoded in "
                  f"the flow control frame (ISO 15765-2: 0..{STMIN_MS_MAX} ms)")
    elif tp.stmin_ms > 0:
        frames = -(-(DOWNLOAD_BLOCK_BYTES - 6) // CONSECUTIVE_FRAME_BYTES)
        block_ms = frames * tp.stmin_ms
        if block_ms > DOWNLOAD_BLOCK_WARN_MS:
            rep.warning("project", ("diagnostics", "isotp", "stmin_ms"), f"STmin {tp.stmin_ms} ms lets one "
                        f"download block of {DOWNLOAD_BLOCK_BYTES} bytes take at least {block_ms} ms "
                        f"({frames} consecutive frames): flashing becomes very slow")
    if tp.stmin_ms >= tp.n_cr_ms:
        rep.error("project", ("diagnostics", "isotp", "n_cr_ms"), f"N_Cr {tp.n_cr_ms} ms is not longer than "
                  f"STmin {tp.stmin_ms} ms: the receiver would time out while the sender keeps its separation "
                  "time")
    if tp.block_size and tp.n_bs_ms <= tp.stmin_ms:
        rep.error("project", ("diagnostics", "isotp", "n_bs_ms"), f"N_Bs {tp.n_bs_ms} ms is not longer than "
                  f"STmin {tp.stmin_ms} ms: the sender would time out waiting for the next flow control frame")


def _scan_area(cfg: Config, rep: Reporter, use) -> tuple[int, int] | None:
    """(start, end) of the area the application searches for the bootloader version string."""
    layout = cfg.memory
    if layout is None:
        return None
    default = layout.flash_start + scan_offset(cfg.derivative.derivative.family)
    start = use.bootloader.scan_start if use.bootloader.scan_start is not None else default
    end = layout.app_start
    if not layout.flash_start <= start < end:
        rep.error("project", ("diagnostics", "bootloader", "scan_start"), f"search area {_hex(start)} is outside "
                  f"the bootloader area {_hex(layout.flash_start)}..{_hex(end - 1)} of {layout.flash_region} "
                  "(the application reads this flash to find the bootloader version)")
        return None
    return start, end


def _check_security(cfg: Config, rep: Reporter, use) -> tuple[str, int | None, int]:
    """Key name of the security access (BL-03) and the UID of the derivative the device key is derived from."""
    from .model import INSECURE_TEST_KEY_NAME

    security = use.bootloader.security
    key = security.key or cfg.board.board.name
    if key == INSECURE_TEST_KEY_NAME and not security.allow_insecure_test_key:
        rep.error("project", ("diagnostics", "bootloader", "security", "key"), f"key {key} is the insecure test key "
                  "of the repository (tools/canflash/keys): anybody can compute the device keys of a device "
                  "provisioned with it. Name the project's own master key, or allow the test key for a test "
                  "profile with diagnostics.bootloader.security.allow_insecure_test_key: true")
    uid = cfg.derivative.uid
    if uid is None and cfg.project.memory is not None:
        rep.error("derivative", ("uid",), f"{cfg.derivative.derivative.name} has no chip UID (uid: address, size): "
                  "the bootloader reports it (DID 0xF18C) and the tester derives the device key of the security "
                  "access from it (BL-03)")
        return key, None, 0
    return key, (uid.address if uid else None), (uid.size if uid else 0)


def check(cfg: Config, rep: Reporter) -> DiagPlan | None:
    """DiagPlan of a project, None without a `diagnostics` section or after errors. Checks `xcp` too."""
    uds_bus, signal_bus, dbc_file = _ecu_buses(cfg)
    check_xcp(cfg, rep, uds_bus, signal_bus, dbc_file)
    use = cfg.project.diagnostics
    if use is None:
        if cfg.project.memory is not None:
            rep.error("project", ("memory",), "the memory partitioning generates bl_config.h for bootloader, "
                      "application and canflash, so the diagnostic addresses are needed too (section "
                      "diagnostics: request_id, response_id, ...)")
        return None
    errors = len(rep.messages)
    bus, dbc = _ecu_can(cfg)
    _check_ids(rep, use)
    _check_dbc(rep, use, bus, dbc, _dbc_base(cfg))
    _check_isotp(rep, use)
    area = _scan_area(cfg, rep, use)
    key, uid_address, uid_size = _check_security(cfg, rep, use)
    if bus is not None and cfg.project.bootloader is not None and cfg.project.bootloader.can != bus:
        rep.warning("project", ("bootloader", "can"), f"the bootloader answers on {cfg.project.bootloader.can}, "
                    f"the application on {bus} (rte.yaml uds.bus): a tester that switches into the bootloader "
                    "with 10 02 has to change the bus")
    if any(m.severity == "error" for m in rep.messages[errors:]) or area is None:
        return None
    tp = use.isotp
    return DiagPlan(bus, use.request_id, use.functional_id, use.response_id, use.tester_address, use.ecu_address,
                    tp.padding, tp.block_size, tp.stmin_ms, tp.n_cr_ms, tp.n_bs_ms,
                    use.bootloader.version_prefix, area[0], area[1],
                    use.bootloader.scan_start is not None, use.bootloader.security.method, key,
                    use.bootloader.security.allow_insecure_test_key, uid_address, uid_size)
