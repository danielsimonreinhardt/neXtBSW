"""Generated module integration of a project (doc/architecture/README.md, section 5).

Each reusable module in libs/bsw/<module> describes itself in module.yaml: kind, the board parts it serves,
required contracts, provided roles, connections to board entries, project parameters, lifecycle and CMake target.
Loading the manifests and all checks (module assignment of the board devices, connections, parameters against the
module's schema, CAN transceiver roles) belong to tools/nxconfig (config.load_modules, checks.integrate), so the
Studio reports them without a generator run. This file only renders the checked result:

- integration/moduleConfiguration.h   instances per module, CAN bus roles, used board signals
- integration/<module>Configuration.h  per instance of a module with connect/parameters: connections, parameter
                                        values, part, console label and an X-macro list of the instances
- integration/modules.cmake            NX_MODULES, NX_MODULE_TARGETS, NX_USE_SPI/DIO/ADC/I2C
- integration/moduleBinding.h          ARCH-52: the per-instance integration of every module with a `binding` (trait)
- integration/moduleBindingConfiguration.h  ARCH-52: what that integration needs from the family binders (counts)

Generated is wiring information only, no logic. Family independent, no Qt.
"""

import re

import nxconfig
from nxconfig import checks as nxchecks
from nxconfig.config import MANIFEST, MODULE_DIRS, ModuleSet, Reporter, load_modules  # noqa: F401 (re-exported)
from nxconfig.model import Manifest  # noqa: F401 (re-exported)

PASSIVE = nxchecks.PASSIVE
Integration = nxchecks.Integration


def load_manifests(dirs=MODULE_DIRS) -> ModuleSet:
    """Reads <dir>/<module>/module.yaml of every directory in `dirs`. Never raises for manifest problems."""
    return load_modules(dirs)


def integrate(config: "nxconfig.Config", modules: ModuleSet) -> Integration:
    """Module integration of a loaded project with another set of manifests (tests); messages are returned.

    nxconfig.check() already runs this with the manifests of MODULE_DIRS and keeps the result in
    config.integration.
    """
    return nxchecks.integrate(config, Reporter(sources=dict(config.sources)), modules)


def render_cmake(integration: Integration, modules: ModuleSet, source: str) -> str:
    """CMake include: modules with at least one instance and their targets (for conditional sources/links).

    PLAT-25: plus the board signals the project uses, by kind - the same information as the C macros
    NX_USE_<KIND>_<NAME> of moduleConfiguration.h. Without them a driver of a **signal kind** could only be
    bound to a device module: a board with SPI but without an SBC could not link the family SPI driver
    (platforms/<family>/bsp/bspLpspi) from the configuration. The lists are empty if the project uses nothing
    of that kind, so `if (NX_USE_SPI)` is the switch "this project uses SPI at all" and
    `if ("MEM_SPI" IN_LIST NX_USE_SPI)` picks a single bus.
    """
    used = sorted({d.module for d in integration.devices} | {b.module for b in integration.can}, key=str.upper)
    targets = [modules.manifests[m].cmake_target for m in used
               if m in modules.manifests and modules.manifests[m].cmake_target]
    lines = [
        f"# Generated by tools/bswgen from {source} - do not edit.",
        "",
        f"set(NX_MODULES {' '.join(used)})",
        f"set(NX_MODULE_TARGETS {' '.join(targets)})",
        "",
        "# Board signals used by the project, by kind (NX_USE_<KIND>_<NAME> in integration/moduleConfiguration.h)",
    ]
    for kind, names in (("SPI", integration.spi), ("DIO", integration.dio), ("ADC", integration.adc),
                        ("I2C", integration.i2c)):
        lines.append(f"set(NX_USE_{kind} {' '.join(names)})")
    # ARCH-52: the modules whose integration is generated (integration/moduleBinding.h), with their CMake targets and
    # directories: the build can add and link them without a line per driver (empty without a bound module)
    bound = sorted({d.module for d in bound_devices(integration, modules)}, key=str.upper)
    lines += ["",
              "# Modules with a binding (integration/moduleBinding.h): CMake targets and module directories",
              f"set(NX_BINDING_TARGETS {' '.join(t for t in (modules.manifests[m].cmake_target for m in bound) if t)})",
              f"set(NX_BINDING_MODULE_DIRS {' '.join(_module_dir(modules, m) for m in bound)})"]
    return "\n".join(lines) + "\n"


def _module_dir(modules: ModuleSet, module: str) -> str:
    """Directory of a module (where its module.yaml lies), as CMake path; quoted if it contains a blank."""
    path = modules.files[module].parent.resolve().as_posix()
    return f'"{path}"' if " " in path else path


def macro(*parts: str) -> str:
    return "_".join(p.upper() for p in parts)


def identifier(name: str) -> str:
    """C identifier of a board entry in the generated board headers (bswgen.identifier uses this)."""
    ident = re.sub(r"\W", "_", name.upper())
    return f"SIG_{ident}" if ident[0].isdigit() else ident


def render_header(integration: Integration, modules: ModuleSet, source: str) -> str:
    lines = [
        f"// Generated by tools/bswgen from {source} - do not edit.",
        "// Module integration: board devices matched to libs/bsw/*/module.yaml (module or part), used by this project.",
        "",
        "#pragma once",
        "",
        "// Instances per device driver module (0: module known, no device of the project uses it)",
    ]
    drivers = [n for n, m in modules.manifests.items() if m.kind == "device_driver"]
    for name in sorted(drivers, key=str.upper):
        lines.append(f"#define {macro('NX_MODULE', name, 'COUNT')} {integration.module_count(name)}")
    # ARCH-52: lifecycle of every device driver as its manifest declares it. The generated binding registers its
    # instances there; a hand-written integration checks its registration against it (static_assert), so a manifest
    # change is not silently ignored any more.
    lines += ["", "// Lifecycle level and task per device driver module (module.yaml lifecycle)"]
    for name in sorted(drivers, key=str.upper):
        lifecycle = modules.manifests[name].lifecycle
        if lifecycle is not None:
            lines += [f"#define {macro('NX_MODULE', name, 'LIFECYCLE_LEVEL')} {lifecycle.level}U",
                      f"#define {macro('NX_MODULE', name, 'LIFECYCLE_TASK')} TASK_{lifecycle.task.upper()}"]
    lines += ["", "// Devices with a module"]
    for d in integration.devices:
        wiring = ", ".join([f"spi {n}" for n in d.spi] + [f"can_phy {n}" for n in d.can_phy]
                           + [f"{k} {v}" for k, v in d.connect.items()])
        lines.append(f"// {d.name}: {d.part} -> {d.module}" + (f" ({wiring})" if wiring else ""))
        lines.append(f"#define {macro('NX_DEVICE', d.name, 'MODULE', d.module)} 1")
    lines += ["", "// CAN buses used by the project: index in board order, transceiver device and role provider",
              f"#define NX_CAN_BUS_COUNT {len(integration.can)}"]
    for bus in integration.can:
        lines.append(f"#define {macro('NX_CAN', bus.name, 'INDEX')} {bus.index}")
        if bus.phy:
            lines.append(f"#define {macro('NX_CAN', bus.name, 'PHY', bus.phy)} 1")
        lines.append(f"#define {macro('NX_CAN', bus.name, 'PHY_MODULE', bus.module)} 1")
    lines += ["", "// Role can_phy per module: X(<bus>, <index>) of the buses it serves (ARCH-07). The integration",
              "// wires one of these lists per module it knows; the counts prove that no bus is left without a"
              " transceiver."]
    for module in sorted(can_phy_modules(modules, integration), key=str.upper):
        buses = [b for b in integration.can if b.module == module]
        entries = "".join(f" X({identifier(b.name)}, {b.index})" for b in buses)
        lines.append(f"#define {macro('NX_CAN_PHY_BUSES', module)}(X){entries}")
        lines.append(f"#define {macro('NX_CAN_PHY_COUNT', module)} {len(buses)}")
    lines += ["", "// Board signals used by the project"]
    for kind, names in (("SPI", integration.spi), ("DIO", integration.dio), ("ADC", integration.adc),
                        ("I2C", integration.i2c)):
        lines += [f"#define {macro('NX_USE', kind, n)} 1" for n in names]
    return "\n".join(lines) + "\n"


def can_phy_modules(modules: ModuleSet, integration: Integration) -> set[str]:
    """Modules that can serve the role can_phy of a CAN bus, plus the ones a bus of this project uses."""
    known = {n for n, m in modules.manifests.items() if "can_phy" in m.provides}
    return known | {b.module for b in integration.can}


def instance_modules(modules: ModuleSet) -> list[str]:
    """Modules that get an integration/<module>Configuration.h: device drivers with connections, parameters or an
    SPI bus (ARCH-40: the SBC has neither connections nor parameters, its port code takes the bus from here)."""
    return sorted((n for n, m in modules.manifests.items()
                   if m.kind == "device_driver" and (m.connect or m.parameters or m.requires.get("spi_device"))),
                  key=str.upper)


def header_name(module: str) -> str:
    return f"integration/{module}Configuration.h"


def _c_value(spec, value) -> str:
    if spec.type == "bool":
        return "1" if value else "0"
    if spec.type == "str":
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return f"{value}U" if spec.min >= 0 else f"({value})"


def _c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_module_header(integration: Integration, modules: ModuleSet, module: str, source: str) -> str:
    """Connections and parameters of every instance of `module` (board order), as macros per device:

    NX_MODULE_<MODULE>_INSTANCES(X)   X(<device>) for each instance, empty without instances
    NX_DEVICE_<DEVICE>_PART           board part number (string)
    NX_DEVICE_<DEVICE>_IO_<CONN>      board entry name of a connection (identifier, e.g. an output or ADC channel)
    NX_DEVICE_<DEVICE>_IO_<CONN>_WIRED  ARCH-52, optional connections only: 1 if the board wires it (then also
                                      _IO_<CONN>), 0 if it leaves it open
    NX_DEVICE_<DEVICE>_PARAM_<PARAM>  parameter value: int with U suffix if unsigned, bool 0/1, string literal
    NX_DEVICE_<DEVICE>_LABEL          console command group in upper case (modules with console: instance)

    IO-25, modules that require spi_device (board spi[] with device: <device>, used by the project):
    NX_DEVICE_<DEVICE>_SPI_COUNT      used SPI buses of the device
    NX_DEVICE_<DEVICE>_SPI_BUS        board name of the bus (only with exactly one bus, also _INSTANCE and _PCS)
    NX_DEVICE_<DEVICE>_SPI_INSTANCE   peripheral instance of the board (e.g. LPSPI0; the family port forms its
                                      register block and clock macro from it)
    NX_DEVICE_<DEVICE>_SPI_PCS        chip select index

    IO-25, modules that provide gate_driver (board pwm[].gate_driver, group used by the project):
    NX_DEVICE_<DEVICE>_PWM_GROUP      PWM group whose channels drive the device (only if there is one)
    NX_DEVICE_<DEVICE>_PWM_COMPLEMENTARY  1: separate high and low side signals per pair, 0: no used group
    """
    manifest = modules.manifests[module]
    instances = integration.instances(module)
    lines = [
        f"// Generated by tools/bswgen from {source} - do not edit.",
        f"// Instances of module {module} (libs/bsw/{module}/module.yaml): connections from board.yaml devices[].connect,",
        "// parameters from project.yaml modules.<device> (defaults of the module filled in).",
        "",
        "#pragma once",
        "",
        f"#define {macro('NX_MODULE', module, 'INSTANCES')}(X)" + "".join(f" X({d.name})" for d in instances),
    ]
    for d in instances:
        lines += ["", f"// {d.name}: {d.part}" + (" - parameter values marked verify: not confirmed" if d.verify else ""),
                  f"#define {macro('NX_DEVICE', d.name, 'PART')} {_c_string(d.part)}"]
        for key, spec in manifest.connect.items():
            if key in d.connect:
                lines.append(f"#define {macro('NX_DEVICE', d.name, 'IO', key)} {identifier(d.connect[key])}")
            if spec.optional:
                # ARCH-52: an optional connection the board may leave open; its IO macro exists only when wired
                lines.append(f"#define {macro('NX_DEVICE', d.name, 'IO', key, 'WIRED')} {1 if key in d.connect else 0}")
        if manifest.requires.get("spi_device"):
            lines.append(f"#define {macro('NX_DEVICE', d.name, 'SPI_COUNT')} {len(d.spi_buses)}")
            if len(d.spi_buses) == 1:
                bus, instance, pcs = d.spi_buses[0]
                lines += [f"#define {macro('NX_DEVICE', d.name, 'SPI_BUS')} {identifier(bus)}",
                          f"#define {macro('NX_DEVICE', d.name, 'SPI_INSTANCE')} {identifier(instance)}",
                          f"#define {macro('NX_DEVICE', d.name, 'SPI_PCS')} {pcs}U"]
        if "gate_driver" in manifest.provides:
            if d.pwm:
                lines.append(f"#define {macro('NX_DEVICE', d.name, 'PWM_GROUP')} {identifier(d.pwm)}")
            lines.append(f"#define {macro('NX_DEVICE', d.name, 'PWM_COMPLEMENTARY')} "
                         f"{1 if d.pwm_mode == 'complementary' else 0}")
        for pname, spec in manifest.parameters.items():
            unit = f" // {spec.unit}" if spec.unit else ""
            lines.append(f"#define {macro('NX_DEVICE', d.name, 'PARAM', pname)} "
                         f"{_c_value(spec, d.parameters[pname])}{unit}")
            # IO-33: a fixed choice as 1/0 per value, so the port can use it in a constant expression
            for choice in _choices(spec):
                lines.append(f"#define {macro('NX_DEVICE', d.name, 'PARAM', pname, 'IS', choice)} "
                             f"{1 if d.parameters[pname] == choice else 0}")
        lines += _pin_lines(manifest, d)
        if manifest.console == "instance":
            label = d.parameters[nxchecks.CONSOLE_PARAMETER].upper()
            lines.append(f"#define {macro('NX_DEVICE', d.name, 'LABEL')} {_c_string(label)}")
        if d.can_wakeup_frame is not None:
            lines += _can_wakeup_frame_lines(d)
    return "\n".join(lines) + "\n"


def _pin_lines(manifest, d) -> list[str]:
    """IO-33: wiring of the part's own pins (board.yaml devices[].pins, module.yaml pins), per pin and use:

    NX_DEVICE_<DEVICE>_PIN_<PIN>_IS_<USE>  1 if the board wires the pin that way, else 0; all 0 for a pin the board
                                           does not describe (the driver leaves it as found)
    """
    if not manifest.pins:
        return []
    lines = ["// Pins of the part (board.yaml devices[].pins): 1 = wired this way, all 0 = not described"]
    for pin, spec in manifest.pins.items():
        wired = d.pins.get(pin)
        lines += [f"#define {macro('NX_DEVICE', d.name, 'PIN', pin, 'IS', use)} {1 if wired == use else 0}"
                  for use in spec.uses]
    return lines


def _c_bool(value: bool) -> str:
    return "true" if value else "false"


def _can_wakeup_frame_lines(d) -> list[str]:
    """COM-21: selective CAN wake-up of a system basis chip (project.yaml modules.<device>.can_wakeup_frame).

    NX_SBC_CAN_WAKEUP_FRAME       1 (only generated with a wake-up frame; one SBC per project, ARCH-44)
    NX_SBC_CAN_WAKEUP_FRAME_INIT  initializer of sbc::CanWakeupFrame in field order: bitrate, id, idCompareMask,
                                  extendedId, evaluateData, dlc, dataMask[8], fdPassive
    The port (SbcSystem) builds SBC_CAN_WAKEUP_FRAME from it; this header stays free of driver includes.
    """
    f = d.can_wakeup_frame
    data = [*f.data_mask, *([0] * (8 - len(f.data_mask)))]
    what = (f"id 0x{f.id:X}{' (29 bit)' if f.extended else ''} mask 0x{f.compare_mask:X}, "
            + (f"dlc {f.dlc}" if f.dlc is not None else "identifier only")
            + (", CAN FD passive" if f.fd_passive else ""))
    return [
        f"// Selective CAN wake-up (partial networking): {what}; bit rate of CAN bus {f.bus} (can.{f.bus}.bitrate)",
        "#define NX_SBC_CAN_WAKEUP_FRAME 1",
        f"#define NX_SBC_CAN_WAKEUP_FRAME_INIT {{{f.bitrate}UL, 0x{f.id:X}UL, 0x{f.compare_mask:X}UL, {_c_bool(f.extended)}, "
        f"{_c_bool(f.dlc is not None)}, {f.dlc or 0}U, {{{', '.join(f'0x{x:02X}U' for x in data)}}}, {_c_bool(f.fd_passive)}}}",
    ]


def parameter_modules(integration: Integration, modules: ModuleSet) -> list[str]:
    """Modules without a board device whose parameters the project sets (module.yaml project_parameters)."""
    return sorted((n for n in integration.modules if n in modules.manifests), key=str.upper)


def render_parameter_header(integration: Integration, modules: ModuleSet, module: str, source: str) -> str:
    """Parameters of a module without a board device (IO-19), as macros of the module:

    NX_MODULE_<MODULE>_PARAM_<PARAM>  parameter value: int with U suffix if unsigned, bool 0/1, string literal
    NX_MODULE_<MODULE>_PARAM_<PARAM>_IS_<VALUE>  1/0 per allowed value of a str parameter with a fixed choice
                                      (pattern "a|b|..."), so the code can use #if instead of string comparison
    NX_MODULE_<MODULE>_DERIVED_<NAME> value tools/nxconfig derives from the parameters (ModuleUse.derived, e.g. the
                                      watchdog service cycles of safeLifecycle, SYS-25), with the rule as comment
    """
    manifest = modules.manifests[module]
    use = integration.modules[module]
    lines = [
        f"// Generated by tools/bswgen from {source} - do not edit.",
        f"// Parameters of module {module} ({MANIFEST} of the module): values from project.yaml modules.{module},",
        "// defaults of the module filled in."
        + (" Parameter values marked verify: not confirmed." if use.verify else ""),
        "",
        "#pragma once",
        "",
    ]
    for pname, spec in manifest.parameters.items():
        value = use.parameters[pname]
        unit = f" // {spec.unit}" if spec.unit else ""
        lines.append(f"#define {macro('NX_MODULE', module, 'PARAM', pname)} {_c_value(spec, value)}{unit}")
        for choice in _choices(spec):
            lines.append(f"#define {macro('NX_MODULE', module, 'PARAM', pname, 'IS', choice)} "
                         f"{1 if value == choice else 0}")
    if use.derived:
        lines += ["", "// Derived by tools/nxconfig from the parameters above, the derivative (mcudb) or the modules "
                      "they depend on - not a value of the project."]
        for name, (value, how) in use.derived.items():
            lines += [f"// {how}", f"#define {macro('NX_MODULE', module, 'DERIVED', name)} {value}U"]
    return "\n".join(lines) + "\n"


def _choices(spec) -> list[str]:
    """Fixed choice of a str parameter: pattern "a|b|c" of plain words, otherwise no choice."""
    if spec.type != "str" or not spec.pattern:
        return []
    parts = spec.pattern.split("|")
    return parts if all(re.fullmatch(r"[a-z][a-z0-9_]*", p) for p in parts) and len(parts) > 1 else []


def parameter_header_name(module: str) -> str:
    return f"integration/{module}Configuration.h"


def render_all(integration: Integration, modules: ModuleSet, source: str) -> dict[str, str]:
    """All generated integration files, relative to the output directory."""
    files = {
        "integration/moduleConfiguration.h": render_header(integration, modules, source),
        "integration/modules.cmake": render_cmake(integration, modules, source),
        BINDING_CONFIGURATION: render_binding_configuration(integration, modules, source),
        BINDING_HEADER: render_binding_header(integration, modules, source),
    }
    for module in instance_modules(modules):
        files[header_name(module)] = render_module_header(integration, modules, module, source)
    for module in parameter_modules(integration, modules):
        files[parameter_header_name(module)] = render_parameter_header(integration, modules, module, source)
    return files


# ----------------------------------------------------------------------------------------------- binding (ARCH-52)
# The per-instance integration of the device drivers with a `binding` entry (decision arch52-vorschlag, mixture:
# doc/architecture/treiber-anbindung-analyse.md section 9). Family neutral: every construct that depends on the
# family goes through a binder of the family integration (ModuleBinders.h, one per connection kind and contract);
# every construct that depends on the driver goes through the module's trait. The file is included by exactly one
# translation unit (the family integration, Integration.cpp), because it defines the objects of the instances.
#
# Contract of a trait T (header binding.include of the module, C++17; the module's own host test compiles it):
#   using System = ...;                          lifecycle component of one instance (ILifecycleComponent)
#   template <class I> static constexpr C config();       configuration from the generated description I
#   static constexpr bool valid(C const&);                validity of that configuration (static_assert below)
#   template <class I, class B> class Parts;              what one instance needs besides the configuration (pin
#                                                         adapters on the family binders B, the SPI device); built
#                                                         with a ::bsp::spi::ISpiDevice& if the module requires
#                                                         spi_device, default constructible otherwise
#   template <class I, class B> static System& create(::etl::typed_storage<System>&, ::async::ContextType,
#                                                     Parts<I, B>&);
#   struct SafeOff_<connection> per safe_off connection:  System, off(System&), enables(System const&),
#                                                         setLock(System&, SafeOffLock), updateLock(System&)
#   static void rte(System const*, <rte.reading>&);       with rte (access reading): one consistent snapshot, called
#                                                         from any task; nullptr before the system is created
#   SPI_FRAME_BITS, SPI_CPOL, SPI_CPHA, SPI_MAX_HZ, SPI_TIMEOUT_US   with requires spi_device: the device facts the
#                                                         family's SPI binder sets its master up with
#
# Generated description I of one instance (struct named after the device):
#   NAME, PART, COMPONENT (lifecycle component name = console group), LABEL; PWM_BOUND (a used PWM group drives the
#   device, board pwm[].gate_driver); Param::<PARAM> per parameter (typed); Connect::<CONN> (binder value) and
#   Connect::<CONN>_WIRED per connection (an optional one may be unwired: no value then).

BINDING_HEADER = "integration/moduleBinding.h"
BINDING_CONFIGURATION = "integration/moduleBindingConfiguration.h"
BINDER_KINDS = {"digital_output": "NX_BINDER_DIGITAL_OUTPUT", "digital_input": "NX_BINDER_DIGITAL_INPUT",
                "analog_input": "NX_BINDER_ANALOG_INPUT"}


def bound_devices(integration: Integration, modules: ModuleSet) -> list:
    """Used devices whose module has a binding, in board order."""
    return [d for d in integration.devices
            if d.module in modules.manifests and modules.manifests[d.module].binding is not None]


def _param_member(device: str, pname: str, spec) -> str:
    value = macro("NX_DEVICE", device, "PARAM", pname)
    name = pname.upper()
    if spec.type == "str":
        return f"static constexpr char const {name}[] = {value};"
    if spec.type == "bool":
        return f"static constexpr bool {name} = ({value} != 0);"
    ctype = "uint32_t" if spec.min is not None and spec.min >= 0 else "int32_t"
    return f"static constexpr {ctype} {name} = {value};"


def _component_name(manifest, d) -> str:
    if manifest.console == "instance":
        return macro("NX_DEVICE", d.name, "PARAM", nxchecks.CONSOLE_PARAMETER)
    if manifest.console:
        return _c_string(manifest.console)
    return _c_string(d.name.lower())


def _binding_counts(integration: Integration, modules: ModuleSet):
    devices = bound_devices(integration, modules)
    manifests = modules.manifests
    safe_off = [(d, key) for d in devices for key, spec in manifests[d.module].connect.items() if spec.safe_off]
    spi = [d for d in devices if manifests[d.module].requires.get("spi_device")]
    analog = [(d, key) for d in devices for key, spec in manifests[d.module].connect.items()
              if spec.kind == "analog_input" and key in d.connect]
    return devices, safe_off, spi, analog


def render_binding_configuration(integration: Integration, modules: ModuleSet, source: str) -> str:
    """integration/moduleBindingConfiguration.h: what the generated binding needs from the family (ARCH-52).

    NX_BINDING_INSTANCE_COUNT         instances of modules with a binding
    NX_BINDING_SAFE_OFF_COUNT         their safe_off adapters (the family's debug halt guard and safe state hold)
    NX_BINDING_SPI_DEVICE_COUNT       their SPI devices (contract spi_device), NX_BINDING_ANALOG_INPUT_COUNT their
                                      wired analog inputs: the family binders include those drivers only if used
    """
    devices, safe_off, spi, analog = _binding_counts(integration, modules)
    return "\n".join([
        f"// Generated by tools/bswgen from {source} - do not edit.",
        "// ARCH-52: what the generated module binding (integration/moduleBinding.h) needs from the family binders.",
        "",
        "#pragma once",
        "",
        f"#define NX_BINDING_INSTANCE_COUNT {len(devices)}",
        f"#define NX_BINDING_SAFE_OFF_COUNT {len(safe_off)}",
        f"#define NX_BINDING_SPI_DEVICE_COUNT {len(spi)}",
        f"#define NX_BINDING_ANALOG_INPUT_COUNT {len(analog)}",
    ]) + "\n"


def render_binding_header(integration: Integration, modules: ModuleSet, source: str) -> str:
    """integration/moduleBinding.h: the integration of every instance of a module with `binding` (contract above).

    The including translation unit includes the family binders (ModuleBinders.h: FamilyBinders and the NX_BINDER_*
    macros) and the framework (ModuleBinding.h: SafeOffOutput, safeOffLock) first; they live in the family
    integration directory, which is no include path of the generated files.

    NX_BINDING_SAFE_OFF_OUTPUT_REFS   `&adapter,` per safe_off connection of a bound instance (IPowerStageOutput)
    ::integration::binding::addComponents(manager, level)  lifecycle registration in the declared level and task
    ::integration::rte::<read>_<Instance>(reading)          RTE readers of the modules with rte (access reading)
    """
    devices, safe_off, _, _ = _binding_counts(integration, modules)
    manifests = modules.manifests
    lines = [
        f"// Generated by tools/bswgen from {source} - do not edit.",
        "// ARCH-52: integration of every instance of a device driver module with a binding (module.yaml binding:",
        "// trait of the module; connect, requires, lifecycle, console and rte of the manifest). Family neutral: family",
        "// constructs come from the binders of the family integration (ModuleBinders.h). Included by exactly one",
        "// translation unit, the family integration: it defines the objects of the instances.",
        "",
        "#pragma once",
        "",
        '#include "integration/moduleBindingConfiguration.h"',
        "",
        "#include <lifecycle/LifecycleManager.h>",
        "",
        "#include <cstdint>",
        "",
        "#ifndef NX_BINDER_DIGITAL_OUTPUT",
        '#error "include the family binders (ModuleBinders.h) and ModuleBinding.h before integration/moduleBinding.h"',
        "#endif",
        "",
        "#define NX_BINDING_SAFE_OFF_OUTPUT_REFS"
        + "".join(f" &::integration::binding::{macro(d.name, 'SAFE_OFF', key)}," for d, key in safe_off),
    ]
    if not devices:
        lines += [
            "",
            "namespace integration",
            "{",
            "namespace binding",
            "{",
            "// No module of this project has a binding: nothing to register.",
            "inline void addComponents(::lifecycle::LifecycleManager& /* lifecycleManager */, uint8_t const /* level */)",
            "{}",
            "} // namespace binding",
            "} // namespace integration",
        ]
        return "\n".join(lines) + "\n"
    headers = sorted({header_name(d.module) for d in devices})
    traits = sorted({manifests[d.module].binding.include for d in devices})
    lines += ["", "// instances (tools/bswgen)"] + [f'#include "{h}"' for h in headers]
    lines += ["// traits of the modules (module.yaml binding.include)"] + [f'#include "{t}"' for t in traits]
    lines += ["", "#include <async/Config.h>", "#include <etl/alignment.h>", "",
              "namespace integration", "{", "namespace binding", "{"]
    for d in devices:
        m = manifests[d.module]
        trait = m.binding.trait
        ident = identifier(d.name)
        label = macro("NX_DEVICE", d.name, "LABEL") if m.console == "instance" else _c_string(d.name)
        lines += ["", f"// {d.name}: {d.part} -> {d.module} (lifecycle level {m.lifecycle.level}, task "
                      f"{m.lifecycle.task})" + (" - parameter values marked verify: not confirmed" if d.verify else ""),
                  f"struct {ident}", "{",
                  f"    static constexpr char const NAME[]      = {_c_string(d.name)};",
                  f"    static constexpr char const PART[]      = {macro('NX_DEVICE', d.name, 'PART')};",
                  f"    static constexpr char const COMPONENT[] = {_component_name(m, d)};",
                  f"    static constexpr char const LABEL[]     = {label};",
                  f"    static constexpr bool PWM_BOUND         = {_c_bool(d.pwm_mode == 'complementary')};",
                  "", "    struct Param", "    {"]
        lines += [f"        {_param_member(d.name, p, spec)}" for p, spec in m.parameters.items()]
        lines += ["    };", "", "    struct Connect", "    {"]
        for key, spec in m.connect.items():
            wired = key in d.connect
            if wired:
                lines.append(f"        static constexpr auto {key.upper()} = {BINDER_KINDS[spec.kind]}"
                             f"({identifier(d.connect[key])});")
            lines.append(f"        static constexpr bool {key.upper()}_WIRED = {_c_bool(wired)};")
        lines += ["    };", "};"]
        cfg = f"{trait}::config<{ident}>()"
        lines.append(f'static_assert({trait}::valid({cfg}), "{d.module} {d.name}: configuration invalid '
                     f'(project.yaml modules.{d.name})");')
        parts = f"{trait}::Parts<{ident}, ::integration::FamilyBinders>"
        if m.requires.get("spi_device"):
            lines += [f"::integration::FamilyBinders::SpiDevice<{trait}> {ident}_SPI{{NX_BINDER_SPI_BUS("
                      f"{macro('NX_DEVICE', d.name, 'SPI_INSTANCE')}, {macro('NX_DEVICE', d.name, 'SPI_PCS')})}};",
                      f"{parts} {ident}_PARTS{{{ident}_SPI}};"]
        else:
            lines.append(f"{parts} {ident}_PARTS{{}};")
        lines.append(f"::etl::typed_storage<{trait}::System> {ident}_SYSTEM;")
        for key, spec in m.connect.items():
            if spec.safe_off:
                lines.append(f"::integration::SafeOffOutput<{trait}::SafeOff_{key}> {macro(d.name, 'SAFE_OFF', key)};")
    lines += ["", "/** Lifecycle registration of the bound instances at `level`, in board order: each in the task of its",
              " * module (module.yaml lifecycle), named after its console group; the safe_off adapters are attached",
              " * with the lock of the safe state as soon as the system exists. */",
              "inline void addComponents(::lifecycle::LifecycleManager& lifecycleManager, uint8_t const level)", "{"]
    for level in sorted({manifests[d.module].lifecycle.level for d in devices}):
        lines += [f"    if (level == {level}U)", "    {"]
        for d in devices:
            m = manifests[d.module]
            if m.lifecycle.level != level:
                continue
            ident = identifier(d.name)
            lines += ["        lifecycleManager.addComponent(",
                      f"            {ident}::COMPONENT,",
                      f"            {m.binding.trait}::create({ident}_SYSTEM, TASK_{m.lifecycle.task.upper()}, "
                      f"{ident}_PARTS),",
                      "            level);"]
            for key, spec in m.connect.items():
                if spec.safe_off:
                    lines.append(f"        {macro(d.name, 'SAFE_OFF', key)}.attach(*{ident}_SYSTEM, "
                                 f"safeOffLock({ident}::PWM_BOUND));")
        lines += ["    }"]
    lines += ["}", "} // namespace binding", "} // namespace integration"]
    readers = [d for d in devices if manifests[d.module].rte is not None]
    if readers:
        lines += ["", "namespace integration", "{", "namespace rte", "{",
                  "// RTE-18 reader contract (module.yaml rte, access reading): one snapshot per call, from any task"]
        for d in readers:
            m = manifests[d.module]
            ident = identifier(d.name)
            lines += [f"void {m.rte.read}_{ident}({m.rte.reading}& reading)", "{",
                      f"    {m.binding.trait}::rte(",
                      f"        ::integration::binding::{ident}_SYSTEM.has_value() ? "
                      f"&*::integration::binding::{ident}_SYSTEM : nullptr,",
                      "        reading);", "}"]
        lines += ["} // namespace rte", "} // namespace integration"]
    return "\n".join(lines) + "\n"
