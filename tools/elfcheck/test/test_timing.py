def exp_derivative(project: Path) -> Path:
    p = yaml.safe_load(project.read_text(encoding="utf-8"))["project"]
    board = yaml.safe_load((project.parent / p["board"] / "board.yaml").read_text(encoding="utf-8"))["board"]
    return check.find_derivative_file(board["mcu"])


