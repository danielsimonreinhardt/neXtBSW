def build_c_swc_image(gen: Path, work: Path, mcpu: str, level_mon: Path = C_SWC / "LevelMonSwc") -> Path:
    """Compiles the generated RTE of test/c_swc with DemoSwc (Simulink) and LevelMonSwc (hand-written C, PLAT-102)."""
    include = [f"-I{gen}", f"-I{gen / 'tasks'}", f"-I{REPO / 'libs/bsw/autosarBase/include'}",
               f"-I{REPO / 'tools/rtegen/test/can_host/stubs'}", f"-I{DEMO_SWC / 'generated/src'}"]
    flags = [f"-mcpu={mcpu}", "-mthumb", "-g3", "-O1"]
    work.mkdir(parents=True, exist_ok=True)
    objects = []
    for src in (gen / "Rte.c", DEMO_SWC / "generated/src/DemoSwc.c", level_mon / "src/LevelMonSwc.c",
                gen / "RteConfig.cpp"):
        obj = work / f"c_swc_{src.stem}.o"
        cc, std = (ARM_GXX, ["-std=c++17", "-fno-exceptions", "-fno-rtti"]) if src.suffix == ".cpp" else \
            (ARM_GCC, ["-std=c99"])
        werror = [] if src.parent.parent.name == "generated" else ["-Werror"]     # Embedded Coder: no -Werror
        r = subprocess.run([cc, *flags, *std, "-Wall", *werror, *include, "-c", str(src), "-o", str(obj)],
                           capture_output=True, text=True)
        if r.returncode:
            raise AssertionError(f"{src.name} does not compile for {mcpu}:\n{r.stderr[-3000:]}")
        objects.append(str(obj))
    elf = work / "c_swc.elf"
    r = subprocess.run([ARM_GXX, *flags, "-nostdlib", "-nostartfiles", "-Wl,-e,0",
                        "-Wl,--unresolved-symbols=ignore-all", *objects, "-o", str(elf)],
                       capture_output=True, text=True)
    if r.returncode:
        raise AssertionError(f"link for {mcpu}:\n{r.stderr[-3000:]}")
    return elf


