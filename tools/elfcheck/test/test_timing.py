def load_ecu(ecu_file: Path) -> dict:
    """An ECU description for a mutant that is written somewhere else (RTE-22).

    Since format 2 the paths of an rte.yaml are relative to the file itself. A mutant written into a scratch folder
    would look for its components next to the copy, so the paths are pinned to the file they came from - the same
    thing rtegen.with_resolved_paths() does for callers that hand the mapping around.
    """
    ecu = yaml.safe_load(Path(ecu_file).read_text(encoding="utf-8"))
    base = Path(ecu_file).resolve().parent
    for entry in ecu.get("components") or []:
        if isinstance(entry, dict) and entry.get("path"):
            entry["path"] = str(base / str(entry["path"]))
    can = ecu.get("can")
    if isinstance(can, dict) and can.get("dbc"):
        can["dbc"] = str(base / str(can["dbc"]))
    return ecu
