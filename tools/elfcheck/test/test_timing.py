def reference_tables(folder: Path) -> tuple[dict[str, int], list[tuple], list[tuple]]:
    """Task contexts, rte::TASKS and rte::RUNNABLES rows as rtegen wrote them into the reviewed reference (PLAT-78)."""
    config = (folder / "tasks" / "async" / "Config.h").read_text(encoding="utf-8")
    contexts, number = {}, 0
    for m in re.finditer(r"^\s*(TASK_\w+)(?:\s*=\s*(\d+))?,", config, re.M):
        number = int(m.group(2)) if m.group(2) else number + 1
        contexts[m.group(1)] = number
    rte = (folder / "RteConfig.cpp").read_text(encoding="utf-8")
    tasks = [(n, contexts[f"TASK_{c}"], int(p), int(f), int(k), int(h)) for n, c, p, f, k, h in
             re.findall(r'\{"(\w+)", TASK_(\w+), (\d+)U, (\d+)U, (\d+)U, (\d+)U\}', rte)]
    runnables = [(n, int(p), int(o), 0xFF if t == "NO_TASK" else int(t[:-1]), int(pt), int(ot)) for n, p, o, t, pt, ot in
                 re.findall(r'\{"([\w.]+)", &\w+, (\d+)U, (\d+)U, (NO_TASK|\d+U), (\d+)U, (\d+)U\}', rte)]
    return contexts, tasks, runnables


def expected_tables(exp: timing.TimingExpectation) -> tuple[dict[str, int], list[tuple], list[tuple]]:
    contexts = {f"TASK_{t.name.upper()}": t.priority for t in exp.tasks}
    tasks, first = [], 0
    for t in exp.app:
        tasks.append((t.name, t.priority, t.period_ms, first, len(t.runnables), t.hyper_ticks))
        first += len(t.runnables)
    index = {t.name: (t.index, t.period_ms) for t in exp.app}
    rows = []
    for r in exp.runnables:
        if r.kind == "init":
            rows.append((r.key, 0, 0, 0xFF, 0, 0))
        else:
            i, tp = index[r.task]
            rows.append((r.key, r.period_ms, r.offset_ms, i, r.period_ms // tp, r.offset_ms // tp))
    return contexts, tasks, rows


