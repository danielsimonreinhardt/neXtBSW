def file_offset(path: Path, address: int) -> int:
    img = elffile.load(path)
    sec = next(s for s in img.sections if s.has_content and s.addr <= address < s.addr + s.size)
    return sec.offset + address - sec.addr


def field_offset(path: Path, symbol: str, fields, row: int, name: str) -> tuple[int, str]:
    layout, size = timing.struct_layout(fields)
    offset, kind = layout[name]
    sym = elffile.load(path).symbol(symbol)
    fmt = {"p": "<I", "z": "<I", "u8": "<B", "u32": "<I"}[kind]
    return file_offset(path, sym.value + row * size + offset), fmt


def get_field(path: Path, symbol: str, fields, row: int, name: str) -> int:
    off, fmt = field_offset(path, symbol, fields, row, name)
    return struct.unpack_from(fmt, path.read_bytes(), off)[0]


def set_field(path: Path, symbol: str, fields, row: int, name: str, value: int) -> None:
    off, fmt = field_offset(path, symbol, fields, row, name)
    data = bytearray(path.read_bytes())
    struct.pack_into(fmt, data, off, value)
    path.write_bytes(bytes(data))


def replace_debug_string(path: Path, old: bytes, new: bytes) -> None:
    """Replaces a NUL-terminated string of .debug_str (same length): what every unit that names it sees."""
    assert len(old) == len(new)
    img = elffile.load(path)
    sec = img.section(".debug_str")
    data = bytearray(path.read_bytes())
    body = bytes(data[sec.offset:sec.offset + sec.size])
    hits = [m.start() for m in re.finditer(re.escape(old + b"\0"), body)]
    assert hits, f"{old!r} not in .debug_str"
    for hit in hits:
        data[sec.offset + hit:sec.offset + hit + len(new)] = new
    path.write_bytes(bytes(data))


T, R = timing.TASKS_SYMBOL, timing.RUNNABLES_SYMBOL
TF, RF = timing.TASK_FIELDS, timing.RUNNABLE_FIELDS


def table_mutants() -> list[tuple[str, object, str]]:
    """(name, mutation of the image, expected code): one per field the check reads."""
    def swap_functions(p):
        a, b = get_field(p, R, RF, 0, "function"), get_field(p, R, RF, 1, "function")
        set_field(p, R, RF, 0, "function", b)
        set_field(p, R, RF, 1, "function", a)

    def bump(symbol, fields, row, name, delta):
        return lambda p: set_field(p, symbol, fields, row, name, get_field(p, symbol, fields, row, name) + delta)

    return [
        ("task context +1 (FreeRTOS priority)", bump(T, TF, 0, "context", 1), "task-priority"),
        ("task period doubled (deadline of a cycle)", lambda p: set_field(
            p, T, TF, 0, "periodMs", 2 * get_field(p, T, TF, 0, "periodMs")), "task-period"),
        ("task runnable count -1", bump(T, TF, 0, "runnableCount", -1), "task-runnables"),
        ("task hyper period +1", bump(T, TF, 0, "hyperTicks", 1), "task-hyper"),
        ("runnable period +1 ms (SM-05 deadline)", bump(R, RF, 0, "periodMs", 1), "runnable-period"),
        ("runnable offset +1 ms", bump(R, RF, 1, "offsetMs", 1), "runnable-offset"),
        ("runnable in another task", lambda p: set_field(p, R, RF, 0, "task", 0xFF), "runnable-task"),
        ("runnable period ticks +1", bump(R, RF, 0, "periodTicks", 1), "runnable-ticks"),
        ("function pointers swapped", swap_functions, "runnable-function"),
        ("name of row 1 in row 0", lambda p: set_field(p, R, RF, 0, "name", get_field(p, R, RF, 1, "name")),
         "runnable-name"),
    ]


