def build_rte_image(gen: Path, work: Path, mcpu: str, name: str = "rte") -> Path:
    """Compiles the generated RTE of test/multitask with its components and links the tables into an ELF."""
    include = [f"-I{gen}", f"-I{gen / 'tasks'}", f"-I{REPO / 'libs/bsw/autosarBase/include'}",
               f"-I{REPO / 'tools/rtegen/test/can_host/stubs'}", f"-I{MULTI / 'MotorSwc/generated/src'}",
               f"-I{MULTI / 'AppSwc/generated/src'}"]
    flags = [f"-mcpu={mcpu}", "-mthumb", "-g3", "-O1"]
    work.mkdir(parents=True, exist_ok=True)
    objects = []
    for src in (gen / "Rte.c", MULTI / "MotorSwc/generated/src/MotorSwc.c", MULTI / "AppSwc/generated/src/AppSwc.c",
                gen / "RteConfig.cpp"):
        obj = work / f"{name}_{src.stem}.o"
        cc, std = (ARM_GXX, ["-std=c++17", "-fno-exceptions", "-fno-rtti"]) if src.suffix == ".cpp" else \
            (ARM_GCC, ["-std=c99"])
        r = subprocess.run([cc, *flags, *std, "-Wall", "-Werror", *include, "-c", str(src), "-o", str(obj)],
                           capture_output=True, text=True)
        if r.returncode:
            raise AssertionError(f"{src.name} does not compile for {mcpu}:\n{r.stderr[-3000:]}")
        objects.append(str(obj))
    elf = work / f"{name}.elf"
    r = subprocess.run([ARM_GXX, *flags, "-nostdlib", "-nostartfiles", "-Wl,-e,0",
                        "-Wl,--unresolved-symbols=ignore-all", *objects, "-o", str(elf)], capture_output=True, text=True)
    if r.returncode:
        raise AssertionError(f"link for {mcpu}:\n{r.stderr[-3000:]}")
    return elf


@unittest.skipUnless(ARM_GCC and ARM_GXX, "arm-none-eabi-gcc/g++ not found (PATH, NX_ARM_GCC_BIN)")
class TimingHostBuildTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.rtegen = import_tool("rtegen", REPO / "tools" / "rtegen")
        cls.tmp = Path(tempfile.mkdtemp(prefix="timing_host_"))
        cls.config = cls.rtegen.nxconfig.load(BT148)
        cls.gen = cls.generate(cls.tmp / "gen")
        cls.elf = build_rte_image(cls.gen, cls.tmp / "m4", "cortex-m4")
        cls.exp = timing.load_expectation(BT148, MULTI_TASKS, MULTI / "rte.yaml")
        cls.count = 0

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    @classmethod
    def generate(cls, out: Path, rte: Path = MULTI / "rte.yaml") -> Path:
        cls.rtegen.generate(rte, cls.config, out, REPO, MULTI_TASKS)
        return out

    def run_check(self, elf: Path, exp: timing.TimingExpectation | None = None):
        return timing.check_image(exp or self.exp, elf, interrupts=False)

    def fresh(self) -> Path:
        type(self).count += 1
        dst = self.tmp / f"mut{self.count}.elf"
        shutil.copy2(self.elf, dst)
        return dst

    def test_own_profile_passes_on_both_cores(self):
        self.assertEqual(list(self.run_check(self.elf)), [])
        m0 = build_rte_image(self.gen, self.tmp / "m0", "cortex-m0plus")
        self.assertEqual(list(self.run_check(m0)), [])
        image = timing.read_image(elffile.load(m0), check.Findings())
        self.assertEqual([(t["name"], t["context"], t["periodMs"]) for t in image.tasks], [("motor", 3, 1), ("app", 2, 10)])
        self.assertEqual(image.contexts[0]["TASK_GUARD"], 5)

    def test_image_mutants_turn_it_red(self):
        for name, mutate, code in table_mutants():
            with self.subTest(mutant=name):
                elf = self.fresh()
                mutate(elf)
                self.assertIn(code, codes(self.run_check(elf)), name)

    def test_generat_mutants_turn_it_red(self):
        """A generated file changed after rtegen (hand edit, stale file) is compiled into the image and found there."""
