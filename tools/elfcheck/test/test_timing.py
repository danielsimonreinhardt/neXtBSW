class TimingCSwcImageTest(unittest.TestCase):
    """PLAT-102: the firmware of the RTE-20 profile test/c_swc (target build target-c-swc: buildtest_s32k148_min with
    the C component LevelMonSwc next to DemoSwc) - the project that could not be checked at all before (TOOL-93)."""

    @classmethod
    def setUpClass(cls):
        cls.build = Path(os.environ.get("NX_CSWC_BUILD_DIR", ""))
        images = check.find_build_images(cls.build) if cls.build.name else {}
        cls.project = cls.build / "project" / "project.yaml"
        if "app" not in images or not cls.project.is_file():
            raise unittest.SkipTest(f"no target build of test/c_swc in '{cls.build}' (tools/test -k target-c-swc)")
        cls.app = images["app"]
        cls.tmp = Path(tempfile.mkdtemp(prefix="timing_cswc_"))

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def test_c_swc_firmware_passes(self):
        exp = timing.load_expectation(self.project)
        self.assertEqual(list(timing.check_build(exp, self.build)), [])
        image = timing.read_image(elffile.load(self.app), check.Findings())
        self.assertEqual([(r["name"], r["functions"], r["periodMs"]) for r in image.runnables if
                          r["name"].startswith("LevelMonSwc.")],
                         [("LevelMonSwc.Run10ms", ["LevelMonSwc_Run10ms"], 10),
                          ("LevelMonSwc.Run100ms", ["LevelMonSwc_Run100ms"], 100),
                          ("LevelMonSwc.LevelMonSwc_Init", ["LevelMonSwc_Init"], 0)])

    def test_mutants_turn_it_red(self):
        # swc.yaml says 200 ms, the firmware was built from 100 ms (stale image)
        folder = self.tmp / "LevelMonSwc"
        shutil.copytree(C_SWC / "LevelMonSwc", folder)
        data = yaml.safe_load((folder / "swc.yaml").read_text(encoding="utf-8"))
        data["runnables"][1]["period_ms"] = 200
        (folder / "swc.yaml").write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
        ecu = load_ecu(C_SWC / "rte.yaml")
        next(c for c in ecu["components"] if c["name"] == "LevelMonSwc")["path"] = str(folder)
        rte = self.tmp / "rte.yaml"
        rte.write_text(yaml.safe_dump(ecu, sort_keys=False), encoding="utf-8")
        self.assertIn("runnable-period", codes(timing.check_image(timing.load_expectation(self.project, rte_file=rte),
                                                                  self.app, interrupts=False)))
        # the firmware changed after the build: period of the C runnable LevelMonSwc.Run100ms in rte::RUNNABLES
        image = timing.read_image(elffile.load(self.app), check.Findings())
        row = [r["name"] for r in image.runnables].index("LevelMonSwc.Run100ms")
        elf = self.tmp / "app.elf"
        shutil.copy2(self.app, elf)
        set_field(elf, R, RF, row, "periodMs", 200)
        self.assertIn("runnable-period", codes(timing.check_image(timing.load_expectation(self.project), elf,
                                                                  interrupts=False)))

if __name__ == "__main__":
    unittest.main()
