"""Command line of tools/stackuse (SYS-65): worst-case stack per execution context, report as Markdown or JSON.

    python tools/stackuse --build <build dir> --elf <image> --profile <profile.yaml> [--out report.md] [--strict]
    python tools/stackuse --su-dir <dir> --disassembly <file> --profile <profile.yaml>      # without toolchain

PLAT-107: a context with `bsw_task` takes its stack from the build (<build>/generated/rte/tasks/BswTasks.h, or
--bsw-tasks-header) and its worst case is checked against the floor of that task in ecu/configuration/taskStacks.yaml
(or --task-stacks): a floor below the worst case fails.

Exit code: 0 when every context fits its stack; 1 when a context overflows or a task floor is below a worst case,
and with --strict also when a context is incomplete (unresolved indirect call, recursion, missing frame, dynamic frame, unknown entry) or its margin is
below --min-margin; 2 for unusable input.

SYS-132: the interrupt stack and its guard are taken from the image (linker symbols __StackTop - __StackLimit and
__StackGuardEnd - __StackGuardStart, read with arm-none-eabi-nm, or --image-symbols without toolchain): the project
value memory.application.isr_stack_size / isr_stack_guard_size is what the image was linked with, so the check runs
against it. isr_stack_bytes / isr_stack_guard_bytes of the profile only apply when the image has no such symbols.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from stackuse import stackuse as su
else:
    from . import stackuse as su


# PLAT-107: the stack manifest of the tree this tool lies in
DEFAULT_TASK_STACKS = Path(__file__).resolve().parents[2] / su.TASK_STACKS_MANIFEST


def _fmt(n: int | None) -> str:
    return "-" if n is None else str(n)


def report_markdown(analysis: su.Analysis, results: list[su.Result], profile: su.Profile, image: str,
                    floors: list[su.FloorCheck] | None = None, manifest: str = "") -> str:
    lines = [f"# Worst-case stack – profile `{profile.name}`", "",
             f"Image: `{image}`. Generated by `tools/stackuse` (SYS-65) from the `-fstack-usage` output and the "
             "call graph of the image; method and limits in `tools/stackuse/README.md`.", ""]
    both, equal, larger = analysis.cross_check()
    sites = [i for f in analysis.functions.values() for _, i in f.indirect]
    virtual = sum(1 for i in sites if "virtual" in i)
    lines += [f"Indirect calls in the image: {len(sites)} ({virtual} of them virtual calls); the profile resolves "
              f"{len(profile.indirect)} callers globally and "
              f"{sum(len(c.indirect) for c in profile.contexts)} per context. An indirect call reached by a context "
              "and not resolved makes that context incomplete.", ""]
    lines += [f"Cross-check of the frame sources: {both} functions have both a `.su` value and a disassembled "
              f"prologue; {equal} agree exactly, {larger} have a larger sum of stack decrements in the disassembly "
              "(taken instead of the `.su` value).", ""]
    lines += ["| Context | Kind | Level | Stack [B] | Worst case [B] | Margin [B] | Use | Complete |",
              "|---|---|---|---:|---:|---:|---:|---|"]
    for r in results:
        c = r.context
        use = "-" if not c.stack_bytes else f"{100 * r.depth / c.stack_bytes:.0f} %"
        mark = " (safety)" if c.name in profile.safety_contexts else ""
        complete = ("yes" if r.complete else "no – lower bound, accepted" if c.lower_bound_accepted
                    else "no – lower bound")
        lines.append(f"| {c.name}{mark} | {c.kind} | {_fmt(c.level)} | {_fmt(c.stack_bytes)} | {r.depth} | "
                     f"{_fmt(r.margin)} | {use} | {complete} |")
    if floors:
        lines += ["", "## Floors of the BSW task stacks", "",
                  f"PLAT-107: a context linked to a BSW task (`bsw_task`) takes its stack from the build and its worst "
                  f"case must fit below the floor of that task (`min_stack_bytes` of `{manifest}`) - the smallest "
                  "stack a project may set; below the default it needs a proof note (project.yaml "
                  "`bsw_tasks.<task>.evidence`).", "",
                  "| Context | Task | Stack [B] | Stack from | Floor [B] | Worst case [B] | Floor |",
                  "|---|---|---:|---|---:|---:|---|"]
        for f in floors:
            lines.append(f"| {f.context} | {f.task} | {_fmt(f.stack_bytes)} | {f.stack_source or '-'} | {f.floor} | "
                         f"{f.depth} | {f.status} |")
    isr = [r for r in results if r.context.kind == "isr"]
    if isr:
        total, levels = analysis.isr_nesting(results)
        budget = analysis.isr_stack_budget(results)
        margin = None if profile.isr_stack_bytes is None else profile.isr_stack_bytes - budget.total
        lines += ["", "## Interrupt stack (MSP), all levels nested", "",
                  f"Deepest handler per level plus one exception frame of {profile.exception_frame_bytes} B per "
                  f"level: **{total} B**."]
        if budget.below is not None:
            lines += ["", f"The start-up context `{budget.below.context.name}` runs on the same stack below every "
                      f"level ({budget.below.depth} B), so the interrupt stack must hold "
                      f"{budget.below.depth} + {total} = **{budget.total} B**."]
            if not budget.below.complete and budget.below.context.lower_bound_accepted:
                lines += ["", f"Its {budget.below.depth} B are a lower bound the profile accepts: "
                          f"{budget.below.context.lower_bound_accepted}"]
        source = "" if profile.isr_stack_source == "profile" else f" (linked: {profile.isr_stack_source})"
        lines += ["", f"Interrupt stack {_fmt(profile.isr_stack_bytes)} B{source}, worst case **{budget.total} B**, "
                  f"margin {_fmt(margin)} B{'' if budget.complete else ' (incomplete: lower bound)'}.", "",
                  "| Level | Deepest handler | Depth [B] |", "|---|---|---:|"]
        for lvl, r in levels:
            lines.append(f"| {_fmt(lvl) if lvl is not None else 'own'} | {r.context.name} | {r.depth} |")
        guard = analysis.guard_check(results)
        if guard is not None:
            fn, frame = guard.largest
            lines += ["", "## Guard below the interrupt stack", "",
                      f"Guard {guard.guard} B; largest frame on the interrupt stack {frame} B (`{fn}`), exception "
                      f"frame {profile.exception_frame_bytes} B: required {frame} + "
                      f"{max(frame, profile.exception_frame_bytes)} = {guard.required} B - "
                      f"**{'sufficient' if guard.ok else 'TOO SMALL'}** (a frame reserved without a write plus the "
                      "next frame or exception frame on top of it must end inside the guard; method in README.md)."]
        rows = analysis.vector_rows(results)
        if rows:
            used = [row for row in rows if row.status not in ("empty", "default", "trampoline", "wrapper")]
            unused = len(rows) - len(used)
            lines += ["", "## Vector table", "",
                      f"{len(rows)} vectors in `{profile.vectors.section}`; {unused} empty, default, a stub to the "
                      "default handler or its generated wrapper; the others:", "",
                      "| Vector | Handler | Covered by | Note |", "|---:|---|---|---|"]
            for row in used:
                lines.append(f"| {row.index} | `{row.handler or hex(row.address)}` | {row.status} | {row.detail} |")
    for r in results:
        c = r.context
        lines += ["", f"## {c.name}", ""]
        if c.note:
            lines += [c.note, ""]
        lines += [f"Context overhead {c.context_bytes} B; deepest path:", "",
                  "| # | Function | Frame [B] | Source |", "|---:|---|---:|---|"]
        for i, (k, frame) in enumerate(r.path, 1):
            lines.append(f"| {i} | `{k}` | {frame} | {analysis.frame_source(k)} |")
        if r.findings:
            lines += ["", "Open items (the number above is a lower bound until they are resolved):", ""]
            for f in sorted(r.findings, key=lambda f: (f.kind, f.function)):
                lines.append(f"- **{f.kind}** `{f.function}`: {f.detail}")
    return "\n".join(lines) + "\n"


def report_json(analysis: su.Analysis, results: list[su.Result], profile: su.Profile,
                floors: list[su.FloorCheck] | None = None) -> dict:
    total, _ = analysis.isr_nesting(results)
    budget = analysis.isr_stack_budget(results)
    guard = analysis.guard_check(results)
    return {
        "profile": profile.name,
        "contexts": [{
            "name": r.context.name, "kind": r.context.kind, "level": r.context.level,
            "stack_bytes": r.context.stack_bytes, "worst_case_bytes": r.depth, "margin_bytes": r.margin,
            "complete": r.complete, "path": [{"function": k, "frame": f} for k, f in r.path],
            "findings": [{"kind": f.kind, "function": f.function, "detail": f.detail} for f in r.findings],
            "on_isr_stack": r.context.on_isr_stack,
            "largest_frame": {"function": r.largest_frame[0], "frame": r.largest_frame[1]},
            "bsw_task": r.context.bsw_task or None, "stack_source": r.context.stack_source or None,
        } for r in results],
        "floors": [{"context": f.context, "task": f.task, "floor_bytes": f.floor, "worst_case_bytes": f.depth,
                    "complete": f.complete, "ok": f.ok} for f in floors or []],
        "isr_nesting_bytes": total, "isr_stack_bytes": profile.isr_stack_bytes,
        "isr_stack_worst_case_bytes": budget.total, "isr_stack_complete": budget.complete,
        "isr_stack_source": profile.isr_stack_source, "isr_stack_guard_bytes": profile.isr_stack_guard_bytes,
        "guard": None if guard is None else {"bytes": guard.guard, "required": guard.required, "ok": guard.ok,
                                             "largest_function": guard.largest[0], "largest_frame": guard.largest[1]},
        "uncovered_vectors": [{"index": v.index, "handler": v.handler, "address": v.address}
                              for v in budget.uncovered_vectors],
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="stackuse", description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--profile", required=True, type=Path)
    ap.add_argument("--build", type=Path, help="build directory: .su files below it")
    ap.add_argument("--su-dir", type=Path, help="directory with .su files (default: --build)")
    ap.add_argument("--elf", type=Path, help="linked image (disassembled with arm-none-eabi-objdump)")
    ap.add_argument("--disassembly", type=Path, help="output of objdump -d -C --no-show-raw-insn instead of --elf")
    ap.add_argument("--sections-dump", type=Path,
                    help="with --disassembly: output of objdump -s -j <section> for the sections the profile reads "
                         "(vector table, table:<section> references)")
    ap.add_argument("--image-symbols", type=Path,
                    help="SYS-132, with --disassembly: output of arm-none-eabi-nm of the image (interrupt stack and "
                         "guard as linked; with --elf nm is run)")
    ap.add_argument("--out", type=Path, help="write the Markdown report here (default: stdout)")
    ap.add_argument("--json", action="store_true", help="JSON instead of Markdown")
    ap.add_argument("--strict", action="store_true", help="incomplete contexts and small margins fail as well")
    ap.add_argument("--min-margin", type=int, default=0, help="with --strict: smallest accepted margin in bytes")
    ap.add_argument("--task-stacks", type=Path,
                    help="PLAT-107: stack manifest with the floors of the BSW tasks (default: "
                         "ecu/configuration/taskStacks.yaml of this tree)")
    ap.add_argument("--bsw-tasks-header", type=Path,
                    help="PLAT-107: generated tasks/BswTasks.h with the stacks of the build (default: "
                         "<build>/generated/rte/tasks/BswTasks.h if it exists, else the profile's stack_bytes)")
    args = ap.parse_args(argv)

    try:
        profile = su.load_profile(args.profile)
        su_dir = args.su_dir or args.build
        if su_dir is None:
            raise su.ProfileError("--build or --su-dir is needed")
        task_floors = None
        if any(c.bsw_task for c in profile.contexts):
            task_floors = su.load_task_floors(args.task_stacks or DEFAULT_TASK_STACKS)
            header = args.bsw_tasks_header or (args.build / su.BSW_TASKS_HEADER if args.build else None)
            if header is not None and header.is_file():
                su.apply_bsw_task_stacks(profile, su.parse_bsw_tasks_header(header.read_text(encoding="utf-8")),
                                         su.BSW_TASKS_HEADER.name)
            elif args.bsw_tasks_header is not None:
                raise su.ProfileError(f"{args.bsw_tasks_header}: not found")
        if args.disassembly:
            text = args.disassembly.read_text(encoding="utf-8", errors="replace")
            image = str(args.disassembly)
            sections = (su.parse_section_dump(args.sections_dump.read_text(encoding="utf-8", errors="replace"))
                        if args.sections_dump else {})
        elif args.elf:
            text = su.disassemble(args.elf)
            image = str(args.elf)
            sections = su.dump_sections(args.elf, profile.sections())
        else:
            raise su.ProfileError("--elf or --disassembly is needed")
        # SYS-132: interrupt stack and guard as linked (project value or template default) instead of the profile
        if args.image_symbols:
            symbols, symbols_source = (su.parse_symbols(args.image_symbols.read_text(encoding="utf-8",
                                                                                     errors="replace")),
                                       args.image_symbols.name)
        elif args.elf:
            symbols, symbols_source = su.image_symbols(args.elf), args.elf.name
        else:
            symbols, symbols_source = {}, ""
        for note in su.apply_image_stack(profile, su.image_stack(symbols), symbols_source):
            print(f"stackuse: note: {note}", file=sys.stderr)
        analysis, results = su.analyse(su_dir, text, profile, sections)
        budget = analysis.isr_stack_budget(results)
        guard = analysis.guard_check(results)
        floors = su.floor_checks(results, task_floors) if task_floors is not None else []
    except (OSError, ValueError) as exc:
        print(f"stackuse: {exc}", file=sys.stderr)
        return 2

    manifest = (task_floors.path.name if task_floors is not None else "")
    out = (json.dumps(report_json(analysis, results, profile, floors), indent=2) + "\n" if args.json
           else report_markdown(analysis, results, profile, image, floors, manifest))
    if args.out:
        args.out.write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out)

    failed = False
    for r in results:
        if r.margin is not None and r.margin < 0:
            print(f"stackuse: {r.context.name}: worst case {r.depth} B exceeds the stack of "
                  f"{r.context.stack_bytes} B", file=sys.stderr)
            failed = True
        elif args.strict and not r.complete and r.context.lower_bound_accepted:
            print(f"stackuse: {r.context.name}: incomplete ({len(r.findings)} open items), lower bound accepted by "
                  "the profile", file=sys.stderr)
        elif args.strict and not r.complete:
            print(f"stackuse: {r.context.name}: incomplete ({len(r.findings)} open items)", file=sys.stderr)
            failed = True
        elif args.strict and r.margin is not None and r.margin < args.min_margin:
            print(f"stackuse: {r.context.name}: margin {r.margin} B below {args.min_margin} B", file=sys.stderr)
            failed = True
    for f in floors:
        # PLAT-107 (decision PLAT-26/S1): a project may set the floor without proof, so the floor must hold the
        # worst case - also a lower bound above the floor shows that it is too small
        if not f.ok:
            print(f"stackuse: {f.context}: worst case {f.depth} B exceeds the floor {f.floor} B of task {f.task} "
                  f"({task_floors.path.name} min_stack_bytes): raise the floor", file=sys.stderr)
            failed = True
    if profile.isr_stack_bytes is not None and budget.total > profile.isr_stack_bytes:
        print(f"stackuse: interrupt stack: nested worst case {budget.total} B exceeds {profile.isr_stack_bytes} B",
              file=sys.stderr)
        failed = True
    elif (args.strict and profile.isr_stack_bytes is not None
          and profile.isr_stack_bytes - budget.total < args.min_margin):
        print(f"stackuse: interrupt stack: margin {profile.isr_stack_bytes - budget.total} B below "
              f"{args.min_margin} B", file=sys.stderr)
        failed = True
    if guard is not None and not guard.ok:
        print(f"stackuse: guard below the interrupt stack: {guard.guard} B, required {guard.required} B "
              f"(largest frame {guard.largest[1]} B in {guard.largest[0]})", file=sys.stderr)
        failed = True
    for row in budget.uncovered_vectors:
        # without --strict a report; the nested bound is marked incomplete either way
        if args.strict:
            print(f"stackuse: vector {row.index} ({row.handler or hex(row.address)}) is covered by no interrupt "
                  "context", file=sys.stderr)
            failed = True
    return 1 if failed else 0
