"""neXtBSW version and commit of a build for the diagnosis (COM-44): diag/DiagBuildId.h with NX_DIAG_NEXTBSW_VERSION.

The value `nextbsw.version` of the diagnostic stack (tools/diaggen STACK_VALUES, 0xF195 of the standard description
standard_diag.yaml) answers which neXtBSW an ECU runs: the version of the tree (VERSION, ARCH-55) and the commit it
was built from (`git describe --tags --always --dirty` of the neXtBSW tree, with a hash of the uncommitted changes
when it is dirty - the rule of the EPK, tools/a2lgen/epk.py describe(), so both name a build the same way).

Text: "<version> <git describe>", e.g. "0.1.0 v0.1.0-12-g46d7f048"; "nogit" without a checkout. Printable ASCII
only, at most MAX_LENGTH characters. The build runs this every time (ecu/uds/CMakeLists.txt, target diagBuildId);
the header is rewritten only when the text changes, so an unchanged tree compiles nothing again.

PLAT-93 (customer-project.md N13): the same header also names the commit of the customer workspace, the repository
that holds the project and pins the tree (`--workspace <root>`, NX_WORKSPACE of the build):

  NX_DIAG_NEXTBSW_VERSION    "<version> <git describe of the tree>"     DID 0xF195, nextbsw.version
  NX_DIAG_NEXTBSW_COMMIT     "<git describe of the tree>"               console "info" (commit)
  NX_DIAG_WORKSPACE_VERSION  "<git describe of the workspace>"          DID 0xF1F2, workspace.version, console
                             "-" without a workspace of its own (project inside the neXtBSW tree),
                             "nogit" for a workspace that is no git repository (archive, copied files)

The git state lives only here, never in the configuration identity (0xF1F1, tools/nxconfig/identity.py): the same
inputs still give the same image identity in every checkout. A workspace counts as a repository only if the folder
itself holds `.git`, so an unpacked workspace inside another checkout does not report that checkout's commit.

Usage: buildid.py -o <build>/generated/diag/diag/DiagBuildId.h [--tree <neXtBSW root>] [--workspace <root>]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE.parent / "a2lgen"))
from nxconfig import version as nxversion  # noqa: E402
import epk  # noqa: E402  (git describe with the hash of a dirty tree, RTE-26)

MAX_LENGTH = 64
WORKSPACE_MAX_LENGTH = 48           # length of the DID 0xF1F2 element (standard_diag.yaml)
NO_WORKSPACE = "-"


def printable(text: str) -> str:
    return "".join(ch if 0x20 <= ord(ch) < 0x7F and ch not in '"\\' else "_" for ch in text)


def text_of(tree: Path) -> str:
    try:
        version = nxversion.read_version(tree)
    except nxversion.VersionError:
        version = "?"
    return printable(f"{version} {epk.describe(tree)}")[:MAX_LENGTH]


def workspace_text_of(workspace: Path | None, tree: Path) -> str:
    """Commit of the customer workspace: "-" when there is none (no workspace, or its root is the tree itself),
    "nogit" when the folder holds no `.git`, otherwise git describe of its repository."""
    if workspace is None:
        return NO_WORKSPACE
    workspace = Path(workspace).resolve()
    if workspace == Path(tree).resolve():
        return NO_WORKSPACE
    if not (workspace / ".git").exists():
        return "nogit"
    return printable(epk.describe(workspace))[:WORKSPACE_MAX_LENGTH]


def header(text: str, workspace: str = NO_WORKSPACE) -> str:
    commit = text.split(" ", 1)[1] if " " in text else text
    return ("// Generated by tools/diaggen/buildid.py at build time - do not edit.\n"
            "// COM-44: neXtBSW version and commit of this build, the value nextbsw.version of the diagnosis (0xF195).\n"
            "// PLAT-93: the commit alone and the commit of the customer workspace (workspace.version, 0xF1F2); the\n"
            "// console (\"info\") shows both from here, so console and diagnosis cannot disagree.\n"
            "#pragma once\n"
            f"#define NX_DIAG_NEXTBSW_VERSION \"{text}\"\n"
            f"#define NX_DIAG_NEXTBSW_COMMIT \"{commit[:WORKSPACE_MAX_LENGTH]}\"\n"
            f"#define NX_DIAG_WORKSPACE_VERSION \"{printable(workspace)}\"\n")


def write(output: Path, text: str, workspace: str = NO_WORKSPACE) -> bool:
    """Writes the header if its content changes; True if written."""
    content = header(text, workspace)
    output = Path(output)
    if output.is_file() and output.read_text(encoding="utf-8") == content:
        return False
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8", newline="\n")
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-o", "--output", type=Path, required=True)
    ap.add_argument("--tree", type=Path, default=REPO, help="neXtBSW root (VERSION and git describe)")
    ap.add_argument("--workspace", type=Path, default=None,
                    help="root of the customer workspace (NX_WORKSPACE); omitted or equal to the tree: none")
    args = ap.parse_args(argv)
    text = text_of(args.tree)
    workspace = workspace_text_of(args.workspace, args.tree)
    if write(args.output, text, workspace):
        print(f"diag build id: {text}, workspace {workspace}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
