"""EPK of the application (RTE-26, calibration stage K1): the identity of a software build as a string in the image.

A calibration tool reads the string at ADDR_EPK from the ECU and compares it with EPK of the A2L; a2lgen takes both
from the image it describes (symbol xcp::EPK), so an A2L always matches the ELF it was made from, and a tool notices
an A2L that belongs to another build (doc/architecture/kalibrierung.md 6.3). The build runs this script every time
(ecu/xcp/CMakeLists.txt, target xcpEpk); the header is rewritten only when the text changes, so an unchanged tree
compiles nothing again.

Text: "<project> neXtBSW <version> <git describe of the project tree>", with a hash of the uncommitted changes
("+d1a2b3c4") when the tree is dirty, so two different dirty builds do not share one EPK. Printable ASCII only,
at most MAX_LENGTH characters.

Usage: epk.py -o <build>/generated/xcp/xcpEpk.h --name <project> --tree <neXtBSW root> [--project project.yaml]
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from nxconfig import version as nxversion  # noqa: E402
from nxconfig import genlicense  # noqa: E402  (PLAT-120)

MAX_LENGTH = 96


def _git(tree: Path, *args: str) -> bytes | None:
    try:
        done = subprocess.run(["git", "-C", str(tree), *args], capture_output=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    return done.stdout if done.returncode == 0 else None


def describe(tree: Path) -> str:
    """git describe of the tree plus a hash of the uncommitted changes; "nogit" without a checkout."""
    text = _git(tree, "describe", "--tags", "--always", "--dirty")
    if text is None:
        return "nogit"
    result = text.decode("utf-8", "replace").strip()
    if result.endswith("-dirty"):
        diff = _git(tree, "diff", "HEAD", "--binary") or b""
        result += "+" + hashlib.sha1(diff).hexdigest()[:8]
    return result


def epk_text(name: str, tree: Path, project: Path | None = None) -> str:
    try:
        version = nxversion.read_version(tree)
    except nxversion.VersionError:
        version = "?"
    where = Path(project).resolve().parent if project is not None else tree
    state = describe(where)
    if state == "nogit" and where != tree:
        state = describe(tree)          # a project outside any checkout: the state of the neXtBSW tree
    text = f"{name} neXtBSW {version} {state}"
    text = "".join(ch if 0x20 <= ord(ch) < 0x7F and ch not in '"\\' else "_" for ch in text)
    return text[:MAX_LENGTH]


def header(text: str) -> str:
    return genlicense.stamp("// Generated by tools/a2lgen/epk.py at build time - do not edit.\n"
            "// EPK: identity of this build, in the image as xcp::EPK and in the A2L as EPK/ADDR_EPK (RTE-26).\n"
            "#pragma once\n"
            f"#define NX_XCP_EPK \"{text}\"\n", "epk.h")


def write(output: Path, text: str) -> bool:
    """Writes the header if its content changes; True if written."""
    content = header(text)
    output = Path(output)
    if output.is_file() and output.read_text(encoding="utf-8") == content:
        return False
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8", newline="\n")
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-o", "--output", type=Path, required=True)
    ap.add_argument("--name", required=True, help="project name (NX_PROJECT_NAME)")
    ap.add_argument("--tree", type=Path, default=HERE.parents[1], help="neXtBSW root (VERSION)")
    ap.add_argument("--project", type=Path, help="project.yaml: git describe of the tree it lives in")
    args = ap.parse_args(argv)
    text = epk_text(args.name, args.tree, args.project)
    if write(args.output, text):
        print(f"epk: {text}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
