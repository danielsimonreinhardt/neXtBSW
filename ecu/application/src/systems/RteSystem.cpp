void DemCommand::executeCommand(::util::command::CommandContext& context, uint8_t const idx)
{
    ::util::format::SharedStringWriter out(context);
    auto& memory = demMemory.manager();
    switch (idx)
    {
        case DEM_ID_STATUS:
            ::dem::console::printStatus(
                out,
                memory,
                ::rte::demtables::CYCLE_NAMES,
                ::rte::DEM_CYCLE_COUNT,
                ::rte::demtables::CONDITION_NAMES,
                ::rte::DEM_CONDITION_COUNT);
            break;
        case DEM_ID_LIST: ::dem::console::printList(out, memory); break;
        case DEM_ID_DATA: ::dem::console::printData(out, memory); break;
#ifndef NX_PRODUCT_BUILD // SYS-119
        case DEM_ID_CLEAR:
        {
            uint32_t group = ::dem::GROUP_ALL_DTCS;
            if (context.hasToken())
            {
                group = context.scanIntToken<uint32_t>();
            }
            if (!context.checkEol())
            {
                return;
            }
            bool const cleared = memory.clear(group);
            (void)out.printf(cleared ? "dem: %06X cleared\r\n" : "dem: no DTC %06X\r\n", static_cast<unsigned>(group));
            break;
        }
        case DEM_ID_CYCLE:
        {
            auto const restart = [&memory]()
            {
                uint8_t const running = memory.memoryInfo().cyclesRunning;
                for (uint8_t c = 0U; c < ::rte::DEM_CYCLE_COUNT; ++c)
                {
                    if ((running & (1U << c)) != 0U)
                    {
                        memory.setCycle(c, true);
                    }
                }
                demMemory.handOver();
            };
            ::console::runInOwnerContext(NVM_CONTEXT, restart);
            (void)out.printf("dem: running operation cycles ended and restarted\r\n");
            break;
        }
        case DEM_ID_SETTING:
        {
            // SYS-163 (SR-110-2 a): 0 or 1 without wrap-around - scanIntToken<uint8_t> read 256 as 0 and switched the
            // DTC setting off
            uint32_t on = 0U;
            if (!::consolecommands::scanUnsigned(context, 1U, on) || !context.checkEol())
            {
                return;
            }
            memory.setDtcSetting(on != 0U);
            (void)out.printf("dem: DTC setting %s\r\n", (on != 0U) ? "on" : "off");
            break;
        }
#endif
        default: break;
    }
}

