void readRteStatus(uint32_t& violations)
{
    uint32_t sum = 0U;
    auto const add = [&sum](uint32_t const value)
    { sum = (value > (0xFFFFFFFFU - sum)) ? 0xFFFFFFFFU : (sum + value); };
    for (size_t i = 0U; i < ::rte::TASK_COUNT; ++i)
    {
        add(::deadlineViolations.task[i]);
    }
    for (size_t i = 0U; i < ::rte::RUNNABLE_TABLE_SIZE; ++i)
    {
        add(::deadlineViolations.runnable[i]);
    }
    violations = sum;
}

void readCalibrationStatus(uint32_t& layout, uint32_t& dataset, uint8_t& status)
{
#ifdef NX_CALIBRATION_SEGMENT
    ::calibration::State const& state = ::calibration::state();
    if (!state.checked)
    {
        layout  = 0U;
        dataset = 0U;
        status  = 0xFEU; // the start-up check has not run yet
        return;
    }
    // SYS-91: a deviation the run-time check found is the newer finding
    ::calibration::RunTimeCheck const& runTime = ::calibration::runTimeCheck();
    bool const deviates = runTime.armed && (runTime.last != ::calibration::Status::VALID);
    layout              = state.header.layout;
    dataset             = state.header.dataset;
    status              = static_cast<uint8_t>(deviates ? runTime.last : state.status);
#else
    layout  = 0U;
    dataset = 0U;
    status  = 0xFFU; // the project has no calibration segment
#endif
}

