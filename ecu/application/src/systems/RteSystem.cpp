void RteSystem::init()
{
#ifdef NX_RTE_HAS_MODE_RUNNABLES
    // RTE-17: the RTE calls every mode switch runnable through callMode (before the first task cycle, run())
    _modeSystem = this;
    ::rte::setModeRunnableCall(&RteSystem::callMode);
#endif
#ifdef NX_RTE_HAS_NVM
    // NVM-02: stored values (or defaults) into the buffers before the init runnables read them
    nvmStart();
#endif
#ifdef NX_RTE_HAS_DEM
    // NVM-03: the fault memory from its NvM blocks; its operation cycles begin with the ECU
    demStart();
    // NVM-19: the events of the NvM start (repaired copy, lost block) into the fault memory, per block under the
    // BSW event names of nvm::DEM_EVENTS (nvm/NvmEvents.h); a block that was not read (no memory) gets no result
    if (::dem::registry.memory != nullptr)
    {
        (void)::nvm::reportToFaultMemory(nvmEvents, nvmBlocks.manager(), *::dem::registry.memory);
    }
#endif
#ifdef NX_CALIBRATION_SEGMENT
    // SYS-89: check the segment (development profile: fill the working page) before the init runnables read it
    calibrationRefused = !::calibration::start();
#ifdef NX_RTE_HAS_DEM
    reportCalibrationToDem(::calibration::state().status == ::calibration::Status::VALID);
#endif
#elif defined(NX_RTE_HAS_PARAMETER_CHECKS)
    // SYS-90: no calibration segment - the values of the image are checked in place; there is no on_invalid and no
    // other copy, so implausible values of a safety-relevant parameter always refuse
    calibrationRefused = !::calibration::plausibility::startUp(
        ::calibration::plausibility::IN_PLACE, ::calibration::plausibility::Source::IMAGE);
#endif
#ifdef NX_RTE_CALIBRATION_GATE
    if (calibrationRefused)
    {
        // on_invalid refuse: no init runnable, no RTE start, no application task (run()); NvM, fault memory, the
        // diagnostics and the console keep running, so a valid image can be downloaded
        transitionDone();
        return;
    }
#endif
#ifdef NX_RTE_HAS_SAFE_STATE_TEST
    // SYS-141: the start test of the active short (pwm.<group>.safe_state_test) - once per start, after the BSP (the
    // PWM timers are clocked) and before the first runnable of the application (it has not enabled a group yet).
    // SYS-143: the shorts are built only after a power-on (E4), with the enable read back off (E3), bounded (E2).
    if (!safeStateTestsDone)
    {
        safeStateTestsDone = true;
        (void)::safestate::startTests<::safestate::FamilyService, SafeStateClock, SafeStateLog, SafeStateProbe>(
            ::rte::SAFE_STATE_TESTS, ::rte::SAFE_STATE_TEST_COUNT, safeStateStart(), safeStateTestRecord);
    }
#endif
    for (size_t i = ::rte::PERIODIC_RUNNABLE_COUNT; i < ::rte::RUNNABLE_COUNT; ++i)
    {
        call(i);
    }
    ::rte::init();
    transitionDone();
}

void RteSystem::run()
{
#ifdef NX_RTE_CALIBRATION_GATE
    size_t const taskCount = calibrationRefused ? 0U : ::rte::TASK_COUNT; // SYS-89/SYS-90: refuse
#else
    size_t const taskCount = ::rte::TASK_COUNT;
#endif
    for (size_t i = 0U; i < taskCount; ++i)
    {
        ::async::scheduleAtFixedRate(
            ::rte::TASKS[i].context,
            _tasks[i],
            _tasks[i]._timeout,
            ::rte::TASKS[i].periodMs,
            ::async::TimeUnit::MILLISECONDS);
    }
#ifdef NX_RTE_HAS_NVM
    ::async::scheduleAtFixedRate(
        NVM_CONTEXT, nvmCycle, nvmCycle.timeout, NVM_CYCLE_MS, ::async::TimeUnit::MILLISECONDS);
#endif
#ifdef NX_RTE_HAS_DEM
    ::async::scheduleAtFixedRate(
        NVM_CONTEXT, demCycle, demCycle.timeout, ::rte::DEM_CYCLE_MS, ::async::TimeUnit::MILLISECONDS);
#endif
    transitionDone();
}

void RteSystem::shutdown()
{
    for (size_t i = 0U; i < ::rte::TASK_COUNT; ++i)
    {
        _tasks[i]._timeout.cancel();
    }
#ifdef NX_RTE_HAS_NVM
    // NVM-02: runs in NVM_CONTEXT (constructor). The application tasks are stopped, the last values they handed
    // over are in the images; every changed block is written before the lifecycle goes further down.
    nvmCycle.timeout.cancel();
#ifdef NX_RTE_HAS_DEM
    // NVM-03: the operation cycles end (pending bits, aging), the state goes to the images before the NvM writes
    demCycle.timeout.cancel();
    demMemory.stop();
#endif
    uint32_t const nowMs = getSystemTimeMs32Bit();
    ecuStatistics.flush(nowMs); // NVM-05
    size_t const written = nvmBlocks.manager().writeAll(nowMs);
    ::util::logger::Logger::info(
        ::util::logger::LIFECYCLE, "NvM: %u blocks written at the run-down", static_cast<unsigned>(written));
#endif
    transitionDone();
}

void RteSystem::call(size_t const index)
{
    uint32_t const start = getSystemTimeUs32Bit();
    ::rte::RUNNABLES[index].function();
#ifdef NX_RTE_LOAD_TEST_US
    if (index == static_cast<size_t>(NX_RTE_LOAD_TEST_INDEX))
    {
        // busy wait, not a delay: the task must really keep the CPU so that the overrun counter reacts
        while ((getSystemTimeUs32Bit() - start) < static_cast<uint32_t>(NX_RTE_LOAD_TEST_US))
        {
        }
    }
#endif
    uint32_t const duration = getSystemTimeUs32Bit() - start;
    record(_statistics[index], duration);
    // SYS-05: deadline of a runnable is its own period (init runnables have periodMs 0 and no deadline)
    uint32_t const deadlineUs = ::rte::RUNNABLES[index].periodMs * 1000U;
    if ((deadlineUs != 0U) && (duration > deadlineUs))
    {
        countDeadlineViolation(deadlineViolations.runnable[index]); // COM-45
    }
#ifdef NX_DEM_RTE_DEADLINE
    if (deadlineUs != 0U)
    {
        deadlineLevels.runnableFailing[index] = duration > deadlineUs; // COM-47: met again -> passes
    }
#endif
    if ((deadlineUs != 0U) && (duration > deadlineUs) && !timing.runnableLatched[index])
    {
        timing.runnableLatched[index] = true;
        reportTimingViolation(VIOLATION_RUNNABLE, index, duration - deadlineUs);
    }
}

void RteSystem::record(RunnableStatistics& s, uint32_t const duration)
{
    if ((s.calls == 0U) || (duration < s.minUs))
    {
        s.minUs = duration;
    }
    ++s.calls;
    s.lastUs = duration;
    s.mean.add(duration);
    if (duration > s.maxUs)
    {
        s.maxUs = duration;
    }
}

void RteSystem::resetStatistics()
{
    for (size_t i = 0U; i < ::rte::TASK_COUNT; ++i)
    {
        _tasks[i].reset();
    }
    for (size_t i = 0U; i < ::rte::RUNNABLE_COUNT; ++i)
    {
        _statistics[i] = RunnableStatistics();
    }
    timing = TimingSupervision(); // SYS-05: new measurement window, every source may report again
#if defined(NX_RTE_HAS_DEM) && !defined(NX_DEM_RTE_DEADLINE)
    reportDeadlineToDem(::dem::Result::PASSED); // NVM-03: the window starts without a violation
#endif
#ifdef NX_RTE_HAS_MODE_RUNNABLES
    for (size_t i = 0U; i < ::rte::MODE_RUNNABLE_COUNT; ++i)
    {
        _modeStatistics[i] = RunnableStatistics();
    }
#endif
}

void RteSystem::TaskRunner::reset()
{
    _cycles      = 0U;
    _overruns    = 0U;
    _minUs       = 0U;
    _maxUs       = 0U;
    _mean        = Mean();
    _lastStartUs = 0U;
    _minDeltaUs  = 0U;
    _maxDeltaUs  = 0U;
}

void RteSystem::TaskRunner::execute()
{
    ::rte::Task const& task = ::rte::TASKS[_index];
    uint32_t const start    = getSystemTimeUs32Bit();
    if (_cycles != 0U)
    {
        // distance between two cycle starts: the activation jitter of this task (tools/schedana)
        uint32_t const delta = start - _lastStartUs;
        if ((_minDeltaUs == 0U) || (delta < _minDeltaUs))
        {
            _minDeltaUs = delta;
        }
        if (delta > _maxDeltaUs)
        {
            _maxDeltaUs = delta;
        }
    }
    _lastStartUs = start;
    ::rte::readInputs(_index);
    for (size_t i = task.firstRunnable; i < (task.firstRunnable + task.runnableCount); ++i)
    {
        if (::rte::isDue(::rte::RUNNABLES[i], _tick))
        {
            _system->call(i);
        }
    }
    ::rte::writeOutputs(_index);
    _tick                   = ((_tick + 1U) < task.hyperTicks) ? (_tick + 1U) : 0U;
    uint32_t const duration = getSystemTimeUs32Bit() - start;
    if ((_cycles == 0U) || (duration < _minUs))
    {
        _minUs = duration;
    }
    ++_cycles;
    _mean.add(duration);
    if (duration > _maxUs)
    {
        _maxUs = duration;
    }
    uint32_t const deadlineUs = task.periodMs * 1000U;
#ifdef NX_DEM_RTE_DEADLINE
    deadlineLevels.taskFailing[_index] = duration > deadlineUs; // COM-47: met again -> passes
    deadlineLevels.taskChecked[_index] = true;
#endif
    if (duration > deadlineUs)
    {
        ++_overruns;
        countDeadlineViolation(deadlineViolations.task[_index]); // COM-45
        // SYS-05: the cycle missed its deadline - an event for the safe supervisor, once per window
        if (!timing.taskLatched[_index])
        {
            timing.taskLatched[_index] = true;
            reportTimingViolation(VIOLATION_TASK_CYCLE, _index, duration - deadlineUs);
        }
    }
}

