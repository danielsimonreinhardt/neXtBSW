/**
 * SYS-05: runtime supervision of the generated RTE. The deadline of a task cycle is the task period and the
 * deadline of a runnable is its own period - both come from the ECU description of the project through
 * rte::TASKS / rte::RUNNABLES, so the supervision adds no configuration value of its own and needs no
 * threshold in reusable code. A violation is an event for the safe supervisor; what happens then (log,
 * limp home, reset) is the supervisor's configured reaction, not the RTE's decision. The fault memory entry
 * follows with NVM-03.
 *
 * The state is at file scope, not in RteSystem: the header of the class is shared and one ECU runs one RTE
 * (the same assumption as _modeSystem). Every entry belongs to exactly one task - a runnable runs in the task
 * that owns it - so the task that writes an entry is the only writer; the console reads single words.
 * Latched: each source reports once per measurement window, so an overloaded system does not flood the
 * supervisor with one event per cycle. "rte reset" opens a new window.
 */
constexpr size_t TIMING_TASKS     = (::rte::TASK_COUNT > 0U) ? ::rte::TASK_COUNT : 1U;
constexpr size_t TIMING_RUNNABLES = (::rte::RUNNABLE_TABLE_SIZE > 0U) ? ::rte::RUNNABLE_TABLE_SIZE : 1U;

/** Kind of violation, high byte of the context word the supervisor records with the event. */
enum TimingViolation : uint32_t
{
    VIOLATION_TASK_CYCLE = 1U, // the cycle of a task took longer than the task period
    VIOLATION_RUNNABLE   = 2U  // a runnable took longer than its own period
};

struct TimingSupervision
{
    bool taskLatched[TIMING_TASKS];
    bool runnableLatched[TIMING_RUNNABLES];
};

TimingSupervision timing{};

/**
 * COM-45: deadline violations since the start, for the diagnosis (bsw.rte.deadline_violations of diag.yaml, read by
 * bswstatus::rte::readRteStatus below). Every violation counts, not only the first of a window, and "rte reset" keeps
 * them. One counter per task cycle and per runnable: each has exactly one writer (the task that owns it), the reader
 * adds single words, so no lock is needed. Saturating.
 */
struct DeadlineViolations
{
    uint32_t task[TIMING_TASKS];
    uint32_t runnable[TIMING_RUNNABLES];
};

DeadlineViolations deadlineViolations{};

void countDeadlineViolation(uint32_t& counter)
{
    if (counter < 0xFFFFFFFFU)
    {
        ++counter;
    }
}

#ifdef NX_DEM_RTE_DEADLINE
/**
 * COM-47: whether the last check of each task cycle and each periodic runnable missed its deadline - the level of the
 * BSW event rte.deadline (dem/DeadlineReport.h), read once per cycle of the fault memory by readDeadlineState. Unlike
 * the latch of the safe supervisor it is not a window: a deadline met again clears it, "rte reset" leaves it alone.
 * One writer per entry (the task that owns it), the reader takes single words.
 */
struct DeadlineLevels
{
    bool taskChecked[TIMING_TASKS];
    bool taskFailing[TIMING_TASKS];
    bool runnableFailing[TIMING_RUNNABLES];
};

DeadlineLevels deadlineLevels{};
#endif

/**
 * Context word of the event: kind in bits 31..24, index of the task or runnable in bits 23..16, overshoot in
 * milliseconds in bits 15..0 (saturating). One word, because that is what safeMonitor stores per monitor.
 * The index is the row of rte::TASKS or rte::RUNNABLES, in the order "rte runnables" prints them, so the
 * logged number can be resolved to a name without a second table in the supervisor.
 */
uint32_t violationContext(uint32_t const kind, size_t const index, uint32_t const overshootUs)
{
    uint32_t const overshootMs = overshootUs / 1000U;
    return (kind << 24U) | (static_cast<uint32_t>(index & 0xFFU) << 16U)
           | ((overshootMs > 0xFFFFU) ? 0xFFFFU : overshootMs);
}

// COM-47: with a DTC of rte.deadline (NX_DEM_RTE_DEADLINE) the fault memory gets a level instead (DeadlineLevels)
#if defined(NX_RTE_HAS_DEM) && !defined(NX_DEM_RTE_DEADLINE)
/**
 * NVM-03: a DTC whose event is the BSW name "rte.deadline" (diag.yaml dtcs[].event.bsw) records the violations of
 * SYS-05 in the fault memory - only recording, the reaction stays with the safe supervisor. -1: no such DTC.
 */
int32_t deadlineDtc = -1;

void reportDeadlineToDem(::dem::Result const result)
{
    ::dem::IFaultMemory* const memory = ::dem::registry.memory;
    if ((memory != nullptr) && (deadlineDtc >= 0))
    {
        memory->report(static_cast<uint16_t>(deadlineDtc), result);
    }
}
#endif

void reportTimingViolation(uint32_t const kind, size_t const index, uint32_t const overshootUs)
{
    uint32_t const context = violationContext(kind, index, overshootUs);
#if defined(NX_RTE_HAS_DEM) && !defined(NX_DEM_RTE_DEADLINE)
    reportDeadlineToDem(::dem::Result::FAILED);
#endif
#ifdef NX_RTE_SAFE_SUPERVISOR
    ::safety::SafeSupervisor::getInstance().rteTimingMonitor.trigger(context);
#else
    (void)context;
#endif
}

