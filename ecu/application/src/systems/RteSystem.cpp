void readDeadlineState(DeadlineState& state)
{
    // COM-47: single words written by the tasks; a check that is running meanwhile shows up in the next cycle
    bool checked = false;
    bool failing = false;
    for (size_t i = 0U; i < ::rte::TASK_COUNT; ++i)
    {
        checked = checked || ::deadlineLevels.taskChecked[i];
        failing = failing || ::deadlineLevels.taskFailing[i];
    }
    for (size_t i = 0U; i < ::rte::RUNNABLE_TABLE_SIZE; ++i)
    {
        failing = failing || ::deadlineLevels.runnableFailing[i];
    }
    state.checked = checked;
    state.failing = failing;
    ::bswstatus::rte::readRteStatus(state.violations); // COM-45 counters, the same sum the diagnosis reads
}
