void RteSystem::Command::executeCommand(::util::command::CommandContext& context, uint8_t const idx)
{
    // SYS-13: this runs in the console context (TASK_IDLE). What belongs to a task - its cycle statistics, the
    // statistics of its runnables, the RTE buffers - is copied in that task (RunInOwner), then printed here.
    ::util::format::SharedStringWriter out(context);
    RteSystem& system = _system;

    /** Values of RteSystem for RteConsole.h; a local class has the access rights of this member function. */
    class Source
    {
    public:
        explicit Source(RteSystem& s) : _s(s) {}

        size_t taskCount() const { return ::rte::TASK_COUNT; }

        uint32_t taskContext(size_t const t) const { return ::rte::TASKS[t].context; }

        size_t runnableCount(size_t const t) const { return ::rte::TASKS[t].runnableCount; }

        size_t initCount() const { return ::rte::RUNNABLE_COUNT - ::rte::PERIODIC_RUNNABLE_COUNT; }

        void takeTask(size_t const t, rteconsole::TaskSnapshot& task, rteconsole::RunnableSnapshot* const runnables)
        {
            ::rte::Task const& config = ::rte::TASKS[t];
            TaskRunner const& runner  = _s._tasks[t];
            task.name                 = config.name;
            task.context              = config.context;
            task.periodMs             = config.periodMs;
            task.cycles               = runner._cycles;
            task.overruns             = runner._overruns;
            task.minUs                = runner.shortestUs();
            task.meanUs               = runner.meanUs();
            task.maxUs                = runner._maxUs;
            task.minDeltaUs           = runner._minDeltaUs;
            task.maxDeltaUs           = runner._maxDeltaUs;
            for (size_t i = 0U; i < config.runnableCount; ++i)
            {
                take(config.firstRunnable + i, runnables[i]);
            }
        }

        void takeInit(rteconsole::RunnableSnapshot* const runnables)
        {
            for (size_t i = ::rte::PERIODIC_RUNNABLE_COUNT; i < ::rte::RUNNABLE_COUNT; ++i)
            {
                take(i, runnables[i - ::rte::PERIODIC_RUNNABLE_COUNT]);
            }
        }

#ifdef NX_RTE_HAS_MODE_RUNNABLES
        // RTE-17: rows of rte::MODE_RUNNABLES of one task (the table is grouped by task, a few rows at most)
        size_t modeCount(size_t const t) const
        {
            size_t count = 0U;
            for (size_t i = 0U; i < ::rte::MODE_RUNNABLE_COUNT; ++i)
            {
                count += (static_cast<size_t>(::rte::MODE_RUNNABLES[i].task) == t) ? 1U : 0U;
            }
            return count;
        }

        void takeModes(size_t const t, rteconsole::ModeSnapshot* const modes) const
        {
            size_t n = 0U;
            for (size_t i = 0U; i < ::rte::MODE_RUNNABLE_COUNT; ++i)
            {
                ::rte::ModeRunnable const& config = ::rte::MODE_RUNNABLES[i];
                if (static_cast<size_t>(config.task) != t)
                {
                    continue;
                }
                RunnableStatistics const& s  = _s._modeStatistics[i];
                rteconsole::ModeSnapshot& m  = modes[n];
                m.runnable                   = rteconsole::RunnableSnapshot();
                m.runnable.name              = config.name;
                m.runnable.calls             = s.calls;
                m.runnable.lastUs            = s.lastUs;
                m.runnable.minUs             = s.shortestUs();
                m.runnable.meanUs            = s.meanUs();
                m.runnable.maxUs             = s.maxUs;
                m.task                       = ::rte::TASKS[t].name;
                m.event                      = eventName(config.activation);
                m.mode                       = config.mode;
                m.fromMode                   = (config.fromMode != nullptr) ? config.fromMode : "";
                ++n;
            }
        }

        static char const* eventName(::rte::ModeActivation const activation)
        {
            switch (activation)
            {
                case ::rte::ModeActivation::ON_ENTRY: return "entry";
                case ::rte::ModeActivation::ON_EXIT: return "exit";
                case ::rte::ModeActivation::ON_TRANSITION: return "transition";
                default: return "?";
            }
        }
#endif

        size_t signalCount() const { return ::rte::SIGNAL_COUNT; }

        // As before SYS-13, the buffers are read in the first application task (the RTE hands values between
        // its tasks over under a lock in readInputs/writeOutputs); one call copies SIGNALS_PER_SNAPSHOT signals.
        uint32_t signalContext() const { return ::rte::TASKS[0].context; }

        void takeSignals(size_t const first, size_t const count, rteconsole::SignalSnapshot* const signals)
        {
#ifdef NX_RTE_HAS_SIGNAL_SCALING
            // RTE-29: SIGNAL_SCALINGS is ascending by row - skip the rows before this chunk once
            size_t k = 0U;
            while ((k < ::rte::SIGNAL_SCALING_COUNT) && (::rte::SIGNAL_SCALINGS[k].signal < first))
            {
                ++k;
            }
#endif
            for (size_t i = 0U; i < count; ++i)
            {
                ::rte::Signal const& signal = ::rte::SIGNALS[first + i];
                signals[i].name             = signal.name;
                signals[i].bsw              = signal.bsw;
                signals[i].value            = rteconsole::takeValue(signal);
#ifdef NX_RTE_HAS_SIGNAL_SCALING
                signals[i].scaling = rteconsole::Scaling();
                if ((k < ::rte::SIGNAL_SCALING_COUNT) && (::rte::SIGNAL_SCALINGS[k].signal == (first + i)))
                {
                    ::rte::SignalScaling const& s = ::rte::SIGNAL_SCALINGS[k];
                    signals[i].scaling            = rteconsole::Scaling{
                        s.unit, s.numerator[0], s.numerator[1], s.denominator, s.decimals};
                    ++k;
                }
#endif
            }
        }

    private:
        void take(size_t const index, rteconsole::RunnableSnapshot& r) const
        {
            ::rte::Runnable const& config = ::rte::RUNNABLES[index];
            RunnableStatistics const& s   = _s._statistics[index];
            r.name                        = config.name;
            r.periodMs                    = config.periodMs;
            r.offsetMs                    = config.offsetMs;
            r.calls                       = s.calls;
            r.lastUs                      = s.lastUs;
            r.minUs                       = s.shortestUs();
            r.meanUs                      = s.meanUs();
            r.maxUs                       = s.maxUs;
        }

        RteSystem& _s;
    };

    // Snapshot of the runnables of one task (at most all runnables) or of the init runnables; one command at a
    // time, so one buffer (zero initialised, no guard).
    static rteconsole::RunnableSnapshot buffer[MAX_RUNNABLES];
#ifdef NX_RTE_HAS_MODE_RUNNABLES
    static rteconsole::ModeSnapshot modeBuffer[MAX_MODE_RUNNABLES];
#endif
    Source source(system);
    switch (idx)
    {
        case ID_SIGNALS:
        {
            rteconsole::writeSignals(out, source, RunInOwner());
            break;
        }
        case ID_RUNNABLES:
        {
#ifdef NX_RTE_LOAD_TEST_US
            (void)out.printf("load test build: runnable %u busy waits %u us\r\n",
                static_cast<unsigned>(NX_RTE_LOAD_TEST_INDEX),
                static_cast<unsigned>(NX_RTE_LOAD_TEST_US));
#endif
            rteconsole::writeStatistics(out, source, RunInOwner(), buffer, rteconsole::Format::TEXT);
#ifdef NX_RTE_HAS_MODE_RUNNABLES
            rteconsole::writeModeStatistics(out, source, RunInOwner(), modeBuffer, rteconsole::Format::TEXT);
#endif
            // SYS-05: no line of its own here. The text of "rte runnables" is a machine interface
            // (tools/schedana parses it, test_schedana.py pins the format strings of this block), and the
            // violation is already visible twice: as the overrun counter of the task and as the event the
            // safe supervisor logs with its context word. A line per missed runnable deadline needs the
            // parser and its test as well and is therefore not part of SYS-05.
            break;
        }
        case ID_JSON:
        {
            // Header with the counts and the time; the end marker tells tools/schedana that no line is missing.
            (void)out.printf("{\"t\":\"rte\",\"v\":1,\"tasks\":%u,\"runnables\":%u,\"periodic\":%u,\"up_us\":%u",
                static_cast<unsigned>(::rte::TASK_COUNT),
                static_cast<unsigned>(::rte::RUNNABLE_COUNT),
                static_cast<unsigned>(::rte::PERIODIC_RUNNABLE_COUNT),
                static_cast<unsigned>(getSystemTimeUs32Bit()));
#ifdef NX_RTE_LOAD_TEST_US
            (void)out.printf(",\"load_test_us\":%u,\"load_test_index\":%u",
                static_cast<unsigned>(NX_RTE_LOAD_TEST_US),
                static_cast<unsigned>(NX_RTE_LOAD_TEST_INDEX));
#endif
#ifdef NX_RTE_HAS_MODE_RUNNABLES
            // RTE-17: number of mode lines, so that tools/schedana notices a lost one
            (void)out.printf(",\"modes\":%u", static_cast<unsigned>(::rte::MODE_RUNNABLE_COUNT));
#endif
            (void)out.printf("}\r\n");
            rteconsole::writeStatistics(out, source, RunInOwner(), buffer, rteconsole::Format::JSON);
#ifdef NX_RTE_HAS_MODE_RUNNABLES
            rteconsole::writeModeStatistics(out, source, RunInOwner(), modeBuffer, rteconsole::Format::JSON);
#endif
            (void)out.printf("{\"t\":\"end\",\"v\":1}\r\n");
            break;
        }
        case ID_RESET:
        {
            // Each task clears its own statistics in its own context (before SYS-13 the first task cleared all
            // of them, while the other tasks were writing theirs); the init runnables belong to the first task.
            for (size_t t = 0U; t < ::rte::TASK_COUNT; ++t)
            {
                auto const clear = [&system, t]()
                {
                    ::rte::Task const& task = ::rte::TASKS[t];
                    system._tasks[t].reset();
                    // SYS-05: the latch of a task and of its runnables belongs to that task as well
                    timing.taskLatched[t] = false;
                    for (size_t i = task.firstRunnable; i < (task.firstRunnable + task.runnableCount); ++i)
                    {
                        system._statistics[i]     = RunnableStatistics();
                        timing.runnableLatched[i] = false;
                    }
#ifdef NX_RTE_HAS_MODE_RUNNABLES
                    for (size_t i = 0U; i < ::rte::MODE_RUNNABLE_COUNT; ++i)
                    {
                        if (static_cast<size_t>(::rte::MODE_RUNNABLES[i].task) == t)
                        {
                            system._modeStatistics[i] = RunnableStatistics();
                        }
                    }
#endif
                    if (t == 0U)
                    {
                        for (size_t i = ::rte::PERIODIC_RUNNABLE_COUNT; i < ::rte::RUNNABLE_COUNT; ++i)
                        {
                            system._statistics[i]     = RunnableStatistics();
                            timing.runnableLatched[i] = false;
                        }
                    }
                };
                RunInOwner()(::rte::TASKS[t].context, clear);
            }
            (void)out.printf("rte statistics cleared\r\n");
            break;
        }
#ifdef NX_RTE_HAS_CAN
        case ID_CAN:
        {
            // The tables the RTE keeps per message (rte::CAN_RX_STATUS / CAN_TX_STATUS, COM-02/COM-03). They had
            // no console output at all, so a timeout was only visible as the signal value falling back to its DBC
            // start value, and the qualifier counters of COM-03 were not visible anywhere (COM-09).
            // "bus" is the state the qualifier uses (COM-12): everything but "error active" and
            // "error passive" makes every received message QLF_ERROR. "can status" shows where it comes
            // from (phy readiness vs. fault confinement of the controller).
            // SYS-13: one message per snapshot, copied in the first application task as before (the generated
            // RTE does not name the index of its CAN task yet; with one task it is the same).
            ::async::ContextType const owner = ::rte::TASKS[0].context;
            bool attached                    = false;
            char const* busState             = "";
            auto const takeBus               = [&attached, &busState]()
            {
                attached = ::rte::isCanAttached();
                busState = ::rte::canBusStateName();
            };
            ::console::runInOwnerContext(owner, takeBus);
            (void)out.printf(
                "can task every %u ms, transceiver %s, bus %s\r\n",
                static_cast<unsigned>(::rte::CAN_PERIOD_MS),
                attached ? "attached" : "not attached",
                busState);
            for (size_t i = 0U; i < ::rte::CAN_RX_COUNT; ++i)
            {
                ::rte::CanRxStatus s{};
                auto const takeRx = [&s, i]() { s = ::rte::CAN_RX_STATUS[i]; };
                ::console::runInOwnerContext(owner, takeRx);
                (void)out.printf("rx %s id ", s.name);
                printCanId(out, s.id);
                (void)out.printf(
                    ": qlf %s%s%s, received %u, length errors %u\r\n",
                    qualifierName(s.qlf),
                    s.valid ? "" : ", never valid",
                    s.timedOut ? ", timed out" : "",
                    static_cast<unsigned>(s.received),
                    static_cast<unsigned>(s.lengthErrors));
                (void)out.printf(
                    "   timeout %u ms (%u times), age %u ms, debounce %u ms, crc errors %u, alive errors %u, "
                    "error %u ms, on error %s\r\n",
                    static_cast<unsigned>(s.timeoutMs),
                    static_cast<unsigned>(s.timeouts),
                    static_cast<unsigned>(s.ageMs),
                    static_cast<unsigned>(s.debounceMs),
                    static_cast<unsigned>(s.crcErrors),
                    static_cast<unsigned>(s.aliveErrors),
                    static_cast<unsigned>(s.errorMs),
                    s.startOnError ? "init" : "hold");
            }
            for (size_t i = 0U; i < ::rte::CAN_TX_COUNT; ++i)
            {
                ::rte::CanTxStatus s{};
                auto const takeTx = [&s, i]() { s = ::rte::CAN_TX_STATUS[i]; };
                ::console::runInOwnerContext(owner, takeTx);
                (void)out.printf("tx %s id ", s.name);
                printCanId(out, s.id);
                (void)out.printf(
                    ": every %u ms, sent %u, failed %u, protect errors %u\r\n",
                    static_cast<unsigned>(s.cycleMs),
                    static_cast<unsigned>(s.sent),
                    static_cast<unsigned>(s.failed),
                    static_cast<unsigned>(s.protectErrors));
            }
            break;
        }
#endif
        default:
        {
            break;
        }
    }
}

