/**
 * NVM-02: the NvM of the RTE blocks. It reads every block before the init runnables (RteSystem::init, first
 * application task), writes changed blocks at the run-down (RteSystem::shutdown) and on "nvm write", and runs its
 * cyclic part (blocks with write policy CHANGE) in the lowest BSW task, so that a write that waits for the memory
 * never delays an application task. All writes run in that one context (NVM_CONTEXT); the RTE hands values over
 * under its lock. The memory is never prepared here: a FlexNVM that is not partitioned stays as it is and the
 * blocks keep their defaults ("nvm status" says why).
 */
constexpr ::async::ContextType NVM_CONTEXT = TASK_BACKGROUND;
constexpr uint32_t NVM_CYCLE_MS            = 100U; // resolution of minIntervalMs, one record per cycle at most

::nvm::NvmRteBlocks nvmBlocks;
char const* nvmState   = "not started";
char const* nvmDetail  = "";
uint32_t nvmUsable     = 0U;

// NVM-19: the events of the NvM start (nvm/NvmEvents.h). readAll() runs before the fault memory is up, so they are
// counted here and handed to the fault memory right after demStart() (nvm::reportToFaultMemory).
::nvm::EventLog<::nvm::NvmRteBlocks::COUNT> nvmEvents;

// NVM-05: operating time and reset statistics on the NvM block EcuStatistics (stats/EcuStatisticsNvm.h), counted once
// per start of the MCU (the lifecycle may run RteSystem::init again without a reset)
::ecustats::NvmStatistics<::nvm::NvmRteBlocks::ManagerType, ::async::LockType> ecuStatistics;
bool ecuStatisticsStarted = false;

class NvmCycle final : public ::async::IRunnable
{
public:
    void execute() override
    {
        uint32_t const nowMs = getSystemTimeMs32Bit();
        // NVM-05: before the cyclic part of the NvM, so a record handed over now is written in this cycle if due
        ecuStatistics.cycle(nowMs, ::ecustats::handover::supplyStartReasonsOrZero());
        (void)nvmBlocks.manager().mainFunction(nowMs);
    }

    ::async::TimeoutType timeout;
};

NvmCycle nvmCycle;

#ifdef NX_ROM_CHECK_IMAGE
// SYS-44: every write of the NvM suspends the ROM check (SM-14) of the family while it lasts
::etl::typed_storage<::nvm::FlashWriteBracket<::safety::FlashWriteScope>> nvmBracket;
#endif

void nvmStart()
{
    ::eeprom::IEepromDriver* memory = ::platform::nvmEeprom(
        ::rte::NVM_WINDOW_START, ::rte::NVM_WINDOW_SIZE, nvmUsable, nvmState, nvmDetail);
#ifdef NX_ROM_CHECK_IMAGE
    if (memory != nullptr)
    {
        memory = &nvmBracket.create(*memory);
    }
#endif
    nvmBlocks.manager().setEventSink(&nvmEvents); // NVM-19
    nvmBlocks.start(memory, nvmUsable);
    size_t stored = 0U;
    for (size_t i = 0U; i < ::nvm::NvmRteBlocks::COUNT; ++i)
    {
        // NVM-19: an ASIL block with a repaired copy (or only one good copy) holds its stored value as well
        stored += (nvmBlocks.manager().status(i).quality == ::nvm::Quality::STORED) ? 1U : 0U;
    }
    // numbers only (SYS-16: every %s needs a proven bound); the text of the memory state is in "nvm status"
    ::util::logger::Logger::info(
        ::util::logger::LIFECYCLE,
        "NvM: %u of %u blocks stored, memory %u bytes usable",
        static_cast<unsigned>(stored),
        static_cast<unsigned>(::nvm::NvmRteBlocks::COUNT),
        static_cast<unsigned>(nvmUsable));
    uint32_t const repaired = nvmEvents.count(::nvm::BlockEvent::COPY_REPAIRED);
    uint32_t const failed   = nvmEvents.count(::nvm::BlockEvent::COPY_REPAIR_FAILED);
    uint32_t const lost     = nvmEvents.count(::nvm::BlockEvent::DEFAULT_LOADED);
    uint32_t const places   = nvmEvents.count(::nvm::BlockEvent::PLACE_DEFECTIVE); // NVM-30, QM
    if ((repaired + failed + lost + places) != 0U)
    {
        ::util::logger::Logger::warn(
            ::util::logger::LIFECYCLE,
            "NvM: %u copies repaired, %u repairs failed, %u blocks lost (default), %u places defective",
            static_cast<unsigned>(repaired),
            static_cast<unsigned>(failed),
            static_cast<unsigned>(lost),
            static_cast<unsigned>(places));
    }
    // NVM-05: the record of the statistics from its block (read just now); the start is counted in the NvM cycle
    if (!ecuStatisticsStarted)
    {
        ecuStatisticsStarted = true;
        ecuStatistics.start(
            nvmBlocks.manager(), ::nvm::NvmRteBlocks::COUNT, getSystemTimeMs32Bit(), ::ecustate::mcuStartReasons());
        ::ecustats::Record const& r = ecuStatistics.statistics().record();
        ::util::logger::Logger::info(
            ::util::logger::LIFECYCLE,
            "ECU statistics: operating time %u s, %u starts before, persistent %u",
            static_cast<unsigned>(r.operatingSeconds),
            static_cast<unsigned>(r.starts),
            (ecuStatistics.binding() == ::ecustats::Binding::BOUND) ? 1U : 0U);
    }
}

