// NVM-02, NVM-19: the NvM of the blocks the generated RTE describes (rte::NVM_BLOCKS, targets nvm.<Block> of the ECU
// description) on the NvM core of libs/bsw/nvm (nvm/Nvm.h, NVM-18). Owns what the core needs per ECU - block table in
// the form of the core with the integrity (QM or ASIL) and the quality buffer (nvm.qlf.<Block>) of every block, status
// per block, scratch for one record - and runs the start: attach the memory, read every block into its image (ASIL:
// check and compare both copies, repair a defective one), load the images and the qualities into the RTE buffers
// (rte::nvmRestore) before the init runnables. Used by systems::RteSystem and the SIL host tests of tools/rtegen.

#pragma once

#include <nvm/Nvm.h>

#include <RteConfig.h> // generated by tools/rtegen

#ifdef NX_RTE_HAS_NVM
#include <async/Types.h>

namespace nvm
{

class NvmRteBlocks
{
public:
    using ManagerType = Manager<::async::LockType>;

    NvmRteBlocks() : _configs(), _status(), _scratch(), _manager(_configs, _status, COUNT, _scratch, sizeof(_scratch))
    {
        for (size_t i = 0U; i < COUNT; ++i)
        {
            ::rte::NvmBlock const& b = ::rte::NVM_BLOCKS[i];
            _configs[i]              = BlockConfig{
                b.name,
                b.id,
                b.size,
                b.address,
                b.image,
                b.defaults,
                b.changed,
                (b.write == ::rte::NvmWrite::CHANGE) ? WritePolicy::CHANGE : WritePolicy::SHUTDOWN,
                b.minIntervalMs,
                // NVM-19: asil_a..asil_d are one format (two copies with CRC-32 and write counter)
                (b.integrity == ::rte::NvmIntegrity::ASIL) ? Integrity::ASIL : Integrity::QM,
                b.quality};
        }
    }

    NvmRteBlocks(NvmRteBlocks const&)            = delete;
    NvmRteBlocks& operator=(NvmRteBlocks const&) = delete;

    /**
     * Start, before the init runnables: \p memory is the virtual EEPROM of the platform port (nullptr: none ready,
     * every block keeps its default), \p usableBytes its size. Never prepares (initialises) the memory. The events of
     * the read (repaired copy, default after a defect) go to the sink set with manager().setEventSink() before.
     */
    void start(::eeprom::IEepromDriver* const memory, uint32_t const usableBytes)
    {
        _manager.attach(memory, usableBytes);
        _manager.readAll();
        ::rte::nvmRestore();
    }

    ManagerType& manager() { return _manager; }

    ManagerType const& manager() const { return _manager; }

    static constexpr size_t COUNT = ::rte::NVM_BLOCK_COUNT;

private:
    static_assert(::rte::NVM_SLOT_MAX >= RECORD_OVERHEAD, "slot size of the generated layout");

    BlockConfig _configs[COUNT];
    BlockStatus _status[COUNT];
    uint8_t _scratch[::rte::NVM_SLOT_MAX];
    ManagerType _manager;
};

} // namespace nvm

#endif // NX_RTE_HAS_NVM
