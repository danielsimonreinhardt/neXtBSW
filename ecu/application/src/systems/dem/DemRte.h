// NVM-03: the fault memory of the ECU (libs/bsw/dem) on the tables and sources the generated RTE derives from the
// diagnostic description (RteDem.h, rte::demSample/demCondition/demCycleState, NvM blocks DemEvents/DemEntries).
// Owns what the core needs per ECU - state per DTC, entries, stored data, scratch - and runs it:
//   start()   after the NvM read its blocks (RteSystem::init): state from the images, autostart cycles begin, the
//             memory is registered for its users (dem::registry: diagnostic services, console, BSW monitors)
//   cycle()   every rte::DEM_CYCLE_MS in the context of the NvM: one sample per event, then a changed state goes to
//             the NvM images (write policy CHANGE, fault_memory.write_interval_ms)
//   stop()    at the run-down, before the NvM writes: the operation cycles end (pending, aging), last hand-over
// On a memory that is not prepared (FlexNVM not partitioned) the NvM keeps the zero defaults: the fault memory starts
// cleared after every start and works in RAM - nothing here depends on the board.

#pragma once

#include <RteConfig.h> // generated by tools/rtegen

#if defined(NX_RTE_HAS_DEM) && defined(NX_RTE_HAS_NVM)
#include <RteDem.h>
#include <async/Types.h>
#include <dem/Dem.h>

#include <cstddef>
#include <cstdint>

namespace dem
{

class DemRte final : private ISource
{
public:
    using ManagerType = Manager<::async::LockType>;

    DemRte()
    : _states(), _entries(), _data(), _scratch(), _manager(::rte::demtables::CONFIG, _states, _entries, _data, _scratch)
    {}

    DemRte(DemRte const&)            = delete;
    DemRte& operator=(DemRte const&) = delete;

    /** After the NvM filled the images of DemEvents/DemEntries (stored state or zeros). true: stored state loaded. */
    bool start()
    {
        ::rte::NvmBlock const& events  = ::rte::NVM_BLOCKS[::rte::DEM_NVM_EVENTS];
        ::rte::NvmBlock const& entries = ::rte::NVM_BLOCKS[::rte::DEM_NVM_ENTRIES];
        bool loaded                    = false;
        {
            ::async::LockType const lock;
            loaded = _manager.load(
                static_cast<uint8_t const*>(events.image),
                events.size,
                static_cast<uint8_t const*>(entries.image),
                entries.size);
        }
        _manager.start();
        registry.memory = &_manager;
        handOver();
        return loaded;
    }

    /** One cycle of the fault memory (every rte::DEM_CYCLE_MS, context of the NvM). */
    void cycle()
    {
        _manager.mainFunction(*this);
        handOver();
    }

    /** Run-down: the running operation cycles end, the state goes to the NvM images (written by writeAll). */
    void stop()
    {
        _manager.stop();
        handOver();
    }

    /** A changed state into the NvM images; the NvM writes it (policy CHANGE) or at the run-down. */
    void handOver()
    {
        if (_manager.takeEventsDirty())
        {
            put(::rte::NVM_BLOCKS[::rte::DEM_NVM_EVENTS], true);
        }
        if (_manager.takeEntriesDirty())
        {
            put(::rte::NVM_BLOCKS[::rte::DEM_NVM_ENTRIES], false);
        }
    }

    ManagerType& manager() { return _manager; }

    ManagerType const& manager() const { return _manager; }

private:
    static constexpr size_t DTCS    = ::rte::DEM_DTC_COUNT;
    static constexpr size_t ENTRIES = ::rte::DEM_MAX_ENTRIES;
    static constexpr size_t DATA    = ::rte::DEM_ENTRY_DATA_BYTES;

    void put(::rte::NvmBlock const& block, bool const events)
    {
        ::async::LockType const lock; // the NvM takes the image under the same lock
        if (events)
        {
            _manager.serializeEvents(static_cast<uint8_t*>(block.image), block.size);
        }
        else
        {
            _manager.serializeEntries(static_cast<uint8_t*>(block.image), block.size);
        }
        *block.changed = true;
    }

    Result sample(uint16_t const dtc) override { return static_cast<Result>(::rte::demSample(dtc)); }

    bool condition(uint8_t const condition) override { return ::rte::demCondition(condition); }

    uint8_t cycleState(uint8_t const cycle) override { return ::rte::demCycleState(cycle); }

    DtcState _states[DTCS];
    Entry _entries[ENTRIES];
    uint8_t _data[ENTRIES * DATA];
    uint8_t _scratch[DATA];
    ManagerType _manager;
};

} // namespace dem

#endif
