#if defined(NX_ROM_CHECK_IMAGE) && defined(NX_CALIBRATION_SEGMENT)
/* SYS-91: the calibration segment is not in the ROM check list - a dataset flashed without a build must reach the
 * start-up check of ecu/calibration (on_invalid), not hold the ECU in the safe state first (board 2026-09-28). The
 * ROM check re-checks it in every pass against its own reference (CALV header), so a flash fault in it during
 * operation keeps the SM-14 reaction (ROM_CHECK_FAILURE, S1 held); after the power cycle the start-up check refuses
 * the damaged segment and UDS stays reachable. */
::safety::RomCheck::OwnArea calibrationSegmentCheck()
{
    ::calibration::Status const status = ::calibration::recheckSegment();
    return ::safety::RomCheck::OwnArea{
        status == ::calibration::Status::VALID,
        ::calibration::segmentAddress(),
        static_cast<uint32_t>(status)};
}
#endif

