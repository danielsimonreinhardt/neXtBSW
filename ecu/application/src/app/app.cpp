void staticInit()
{
    Uart::getInstance(Uart::Id::TERMINAL).init();
    Uart::getInstance(Uart::Id::TERMINAL).waitForTxReady();
}

void run()
{
    staticInit();
    etl::print("hello\r\n");

    idleHandler.init();

    AsyncAdapter::run(AsyncAdapter::StartAppFunctionType::create<&startApp>());
}

void startApp()
{
    /* runlevel 1 */
    ::platform::platformLifecycleAdd(lifecycleManager, 1U);

    lifecycleManager.addComponent(
        "runtime", runtimeSystem.create(TASK_BACKGROUND, runtimeMonitor), 1U);
    lifecycleManager.addComponent("safety", safetySystem.create(TASK_SAFETY, lifecycleManager), 1U);
    lifecycleManager.addComponent(
        "ecu",
        ecuStateSystem.create(
            ::integration::powerSupplyContext(),
            lifecycleManager,
            ::integration::powerSupply(),
            ecuStateConfig,
            MaxNumLevels,
            EcuStateLevel),
        EcuStateLevel);

    /* runlevel 2 */
    ::platform::platformLifecycleAdd(lifecycleManager, 2U);

#ifdef PLATFORM_SUPPORT_UDS
    /* runlevel 3: UDS on the diagnostics CAN bus (after CAN), runs in the CAN task */
    lifecycleManager.addComponent(
        "uds", diagSystem.create(TASK_CAN, ::systems::getCanSystem(), lifecycleManager), 3U);
#endif
#ifdef NX_XCP
    /* runlevel 3: XCP on CAN (TOOL-01), in the CAN task, which delivers the received frames */
    lifecycleManager.addComponent("xcp", xcpSystem.create(TASK_CAN, ::systems::getCanSystem()), 3U);
#endif

    /* runlevel 8 */
    lifecycleManager.addComponent(
        "sysadmin", sysAdminSystem.create(TASK_SYSADMIN, lifecycleManager), 8U);

    /* runlevel 9: RTE, runnables in the application tasks (RTE_APPLICATION_TASKS) */
    lifecycleManager.addComponent("rte", rteSystem.create(), 9U);

    lifecycleManager.transitionToLevel(MaxNumLevels);

    runtimeMonitor.start();
    idleHandler.start();
}

