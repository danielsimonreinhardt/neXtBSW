class IdleHandler : private ::async::RunnableType
{
public:
    void init()
    {
#if defined(NX_ROM_CHECK_IMAGE) && defined(NX_CALIBRATION_SEGMENT)
        ::safety::RomCheck::setOwnAreaCheck(&calibrationSegmentCheck); // SYS-91, armed by calibration::start()
#endif
#if NX_CONSOLE
        ::logger::init();

        ::console::init();
        ::console::enable();
#endif
    }

    void start() { ::async::execute(AsyncAdapter::TASK_IDLE, *this); }

private:
    void execute() override
    {
#if NX_CONSOLE
        ::logger::run();
        ::console::run();
#endif
#ifdef NX_ROM_CHECK_IMAGE
        // SYS-44: a pass when the period of the project has elapsed (nothing before SafetyManager::init(), once per
        // start with period 0). Lowest priority, no lock: every supervised task preempts the pass (SSR-025).
        ::safety::RomCheck::idle();
#endif
        if (lifecycleMonitor.isReadyForReset())
        {
            shutdown();
        }
        else
        {
            ::async::execute(AsyncAdapter::TASK_IDLE, *this);
        }
    }

    void shutdown()
    {
#if NX_CONSOLE
        Logger::info(LIFECYCLE, "Lifecycle shutdown complete");
        ::logger::flush();
#endif

        softwareSystemReset();
    }
};

IdleHandler idleHandler;

