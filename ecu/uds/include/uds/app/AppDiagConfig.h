#pragma once

/* Diagnostic addresses of the application's UDS stack. Every value here is generated from the project
 * (projects/<project>/project.yaml section `diagnostics`, checked by tools/nxconfig/diag.py, written by
 * tools/bswgen/blgen.py into <build>/generated/board/bootloader/bl_diag.h, COM-11). The bootloader core uses
 * the same macros, so one tester serves application and bootloader; nothing in this file is written by hand.
 *
 * The data identifiers, routines and security levels the application serves come from the diagnostic
 * description of the project (diag.yaml, generated by tools/diaggen, COM-28), not from this file.
 */

#include <bl_config.h>

#include <cstdint>

namespace uds
{
namespace app
{
/* DoCAN normal addressing, identical to the bootloader so that one tester serves both. */
static constexpr uint32_t CAN_ID_REQUEST_PHYS = BL_CAN_ID_REQUEST_PHYS;
static constexpr uint32_t CAN_ID_REQUEST_FUNC = BL_CAN_ID_REQUEST_FUNC;
static constexpr uint32_t CAN_ID_RESPONSE     = BL_CAN_ID_RESPONSE;

/* ISO 15765-2 parameters (classic CAN, 8 byte frames) */
static constexpr uint8_t ISOTP_PADDING      = BL_ISOTP_PADDING;
static constexpr uint8_t ISOTP_BLOCK_SIZE   = BL_ISOTP_BLOCK_SIZE;
static constexpr uint32_t ISOTP_STMIN_US    = BL_ISOTP_STMIN_MS * 1000UL;
static constexpr uint32_t ISOTP_N_CR_MS     = BL_ISOTP_N_CR_MS;
static constexpr uint32_t ISOTP_N_BS_MS     = BL_ISOTP_N_BS_MS;

/* Transport addresses: tester (1 byte, see TransportConfiguration) and this ECU */
static constexpr uint16_t TESTER_ADDRESS = NX_DIAG_TESTER_ADDRESS;
static constexpr uint16_t ECU_ADDRESS    = NX_DIAG_ECU_ADDRESS;

/* Area searched for the bootloader version string: the bootloader's flash without the area the family
 * reserves (s32k1xx: vector table and flash configuration field 0x400..0x40F), up to the application. */
static constexpr uint32_t BOOTLOADER_SCAN_START = NX_DIAG_BL_SCAN_START;
static constexpr uint32_t BOOTLOADER_SCAN_END   = NX_DIAG_BL_SCAN_END;
/* Prefix of BL_VERSION_STRING, without the version number */
static constexpr char const BOOTLOADER_VERSION_PREFIX[] = BL_VERSION_PREFIX " ";
/* Former name of the bootloader software (bl_config.h, PLAT-08): bootloaders flashed before the rename report it */
static constexpr char const BOOTLOADER_VERSION_PREFIX_FORMER[] = BL_VERSION_PREFIX_FORMER " ";

} // namespace app
} // namespace uds
