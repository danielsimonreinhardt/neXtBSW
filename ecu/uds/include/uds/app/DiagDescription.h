#pragma once

/* Tables of the diagnostic description (COM-28). The generator tools/diaggen turns
 * projects/<project>/diag.yaml (ARCH-51) into these tables and into one read, write or step function per
 * data identifier and routine; the services of DiagDescriptionServices.h serve them. Nothing here knows an
 * identifier, a routine or a board: a project without diag.yaml gets the tables of
 * tools/diaggen/default_diag.yaml. */

#include "uds/app/ApplicationIdentification.h"

#include <uds/DiagReturnCode.h>
#include <uds/connection/PositiveResponse.h>

#include <etl/span.h>

#include <cstdint>

namespace uds
{
namespace app
{
/** Values the diagnostic stack itself provides (`source: {bsw: ...}` of diag.yaml, see tools/diaggen). */
struct DiagValues
{
    ::etl::span<uint8_t const> bootSoftwareId;        // bootloader.version: text found in the bootloader flash
    ::etl::span<uint8_t const> applicationSoftwareId; // application.version
    uint8_t activeSession;                            // uds.session: session type of the active session
    ::etl::span<uint8_t const> chipUid;               // chip.uid: UID of the chip (COM-30), empty if unknown
    // COM-44 (uds/app/ApplicationIdentification.h)
    ::etl::span<uint8_t const> hardwareNumber;        // hardware.number: "<board>/<derivative>", empty if unknown
    ::etl::span<uint8_t const> nextbswVersion;        // nextbsw.version: version and commit, empty if unknown
    CompatibilityRecord compatibility;                // compatibility.*: the record of 0xF1A0
    ::etl::span<uint8_t const> configurationIdentity; // configuration.identity (PLAT-79), empty if unknown
    ::etl::span<uint8_t const> workspaceVersion;      // workspace.version (PLAT-93), empty if unknown
};

/** Appends the data record of one identifier behind its identifier. OK, a negative response code (e.g. 0x22
 * when a value is not available) or ISO_RESPONSE_TOO_LONG when the response buffer is full. */
using DidReadFunction = DiagReturnCode::Type (*)(DiagValues const& values, PositiveResponse& response);
/** Takes the data record of a write; its length is checked before. OK, ISO_REQUEST_OUT_OF_RANGE for a value
 * outside the described range, nothing is written then. */
using DidWriteFunction = DiagReturnCode::Type (*)(uint8_t const data[], uint16_t length);
/** Range check of the request parameters of a routine step (length checked before): OK or
 * ISO_REQUEST_OUT_OF_RANGE. Separate from the step, because 13.2 checks the parameters before the sequence. */
using RoutineCheckFunction = DiagReturnCode::Type (*)(uint8_t const request[], uint16_t length);
/** One step of a routine: request parameters (length and range checked before) in, response parameters
 * appended. */
using RoutineStepFunction
    = DiagReturnCode::Type (*)(uint8_t const request[], uint16_t length, PositiveResponse& response);

/* Session masks: bit i stands for DiagDescriptionTables::sessions[i]. Security masks: bit i stands for
 * DiagDescriptionTables::securityLevels[i], 0 means no security access is needed. */
struct DidEntry
{
    uint16_t identifier;
    uint16_t readLength;  // bytes a read appends, always exactly (texts filled up with NUL, COM-33)
    uint16_t writeLength; // bytes of the data record a write takes, 0: not writable
    uint8_t readSessions; // 0: not readable
    uint8_t writeSessions;
    uint8_t readSecurity;
    uint8_t writeSecurity;
    DidReadFunction read;   // nullptr: not readable
    DidWriteFunction write; // nullptr: not writable
};

struct RoutineStep
{
    uint16_t requestLength;     // bytes of the routineControlOptionRecord
    RoutineCheckFunction check; // nullptr: nothing to check
    RoutineStepFunction run;    // nullptr: the routine has no such step
};

struct RoutineEntry
{
    uint16_t identifier;
    uint8_t sessions;
    uint8_t security;
    RoutineStep steps[3]; // start (01), stop (02), requestResults (03)
};

/* Methods of the key calculation (diag.yaml security[].method, COM-30). The numbers are those of the
 * bootloader's security access (bl_config.h BL_SECURITY_METHOD_*, tools/nxconfig/diag.py SECURITY_METHOD_IDS). */
static constexpr uint8_t SECURITY_METHOD_HMAC_SHA256 = 1U;

struct SecurityLevel
{
    uint8_t requestSeed; // odd sub-function; sendKey is requestSeed + 1
    uint8_t seedBytes;
    uint8_t keyBytes;
    uint8_t attempts;    // wrong keys in a row before the delay starts
    uint32_t delayMs;
    uint8_t sessions;
    uint8_t method;      // SECURITY_METHOD_*
};

struct DiagDescriptionTables
{
    ::etl::span<uint8_t const> sessions; // session types of the description
    ::etl::span<DidEntry const> dids;
    ::etl::span<RoutineEntry const> routines;
    ::etl::span<SecurityLevel const> securityLevels;
    uint8_t maxDidsPerRequest; // more identifiers in one 22 request: NRC 0x13
};

/** Generated by tools/diaggen (DiagDescription.cpp). */
DiagDescriptionTables const& diagDescription();

/** Storage of `uds.ram_test` (a RAM value of the stack for write tests), empty if the description has none. */
::etl::span<uint8_t> diagRamTest();

/** Bit of the session type \p session in the session masks, 0 if the description does not know it. */
uint8_t sessionBit(DiagDescriptionTables const& tables, uint8_t session);

} // namespace app
} // namespace uds
