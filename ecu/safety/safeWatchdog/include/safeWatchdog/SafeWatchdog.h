#pragma once

#include <integration/safeLifecycleConfiguration.h>

#include <cstdint>

namespace safety
{
class SafeWatchdog
{
public:
    // [PUBLIC_API_START]
    /**
     * Initializes the last watchdog service counter with maximum value, the counter will be
     * corrected in first cyclic() call.
     */
    SafeWatchdog();

    /**
     * Initializes the last watchdog service counter and calls the SafeWatchdog::enableMcuWatchdog
     * method.
     */
    void init();
    /**
     * Checks if the watchdog is running with the initial settings. If check fails, triggers
     * safeMonitor event which causes the software system reset. Checks if the watchdog is
     * not serviced more often than allowed, if fails triggers the reset through safeMonitor.
     * After these checks, it services the watchdog.
     */
    void cyclic();
    /**
     * Calls the enableMcuWatchdog method of bspMcuWatchdog by passing the watchdog timeout value.
     */
    static void enableMcuWatchdog();
    // [PUBLIC_API_END]

private:
    // MCU watchdog time-out, project value modules.safeLifecycle.watchdog_timeout_ms of the family's safety task
    // (SYS-25, generated by tools/bswgen). It has to hold three services of the safety task: tools/nxconfig derives
    // the service interval from it (SafetyManager::WATCHDOG_CYCLIC_COUNTER = floor(time-out / (3 x period)), demo
    // 3 x 8 x 10 ms = 240 <= 250 ms) and checks it against the family's watchdog counter (checks.py safety_timing).
    static constexpr uint32_t WATCHDOG_TIMEOUT_MS = NX_MODULE_SAFELIFECYCLE_PARAM_WATCHDOG_TIMEOUT_MS;
    uint32_t const SERVICE_COUNTER_INIT       = 0xFFFFFFFFU;
    uint32_t _serviceCounter;
};

} // namespace safety
