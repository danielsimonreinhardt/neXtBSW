"""Host tests of the ECU state management (SYS-01), compiled with zig c++ and run on the PC.

Run: .venv/Scripts/python -m unittest libs/bsw/ecuState/test/test_ecustate_host.py

- EcuStateHostTest.cpp: state machine and controller without SBC (fake supply, permanent supply, lifecycle model)
- EcuStartReasonHostTest.cpp: SYS-18, start reasons from both sources (role power_supply and the MCU's own reset
  status, ecuState/McuStartReasons.h), board with and without a supply device, family without a reset status
- EcuShutdownHostTest.cpp: run-down before the sleep (SYS-02) with scripted steps, missing NvM, failures, timeouts;
  SYS-174: safe outputs step, IShutdownStep::abort() of a timed-out step, no step_error continue past the NvM step
- EcuRestartSupervisionHostTest.cpp: SYS-173, the restart of every SM-53 reaction supervised; a lifecycle that never
  completes it is ended by the direct reset of the family port (ecuState/DirectReset.h)
- EcuSafeOutputsStepHostTest.cpp: SYS-174, run-down step SAFE_OUTPUTS of the s32k1xx port (SafeOutputsShutdownStep.h)
- EcuOutputFlushHostTest.cpp: output flush before the power down (SYS-09): log, flush, power down in this order,
  limit, sleep timeout from the request, no log line after the start of the flush (SYS-11); limit and drain
  detection of the s32k1xx console flush (IdleOutputDrain.h)
- Uja113xPowerSupplyHostTest.cpp: role power_supply of the UJA113x (start reasons, wake-up sources, Sleep)
- EcuStateIntegrationHostTest.cpp: EcuStateConfig.h generated by tools/rtegen from the test profile PROFILE
- ArmV6mTest (PLAT-28): the module compiled for Cortex-M0+ (ARMv6-M, no exclusive access instructions) with the real
  interrupt lock of the platform references no libatomic function (__atomic_*); needs arm-none-eabi-g++ from PATH or
  NX_ARM_GCC_BIN, otherwise skipped
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO / "tools" / "rtegen"))

import rtegen  # noqa: E402

FLAGS = ["-std=c++17", "-O1", "-Wall", "-Wextra", "-Wconversion", "-Wno-sign-conversion", "-Werror"]
MODULE = ["libs/bsw/ecuState/src/ecuState/EcuStateMachine.cpp", "libs/bsw/ecuState/src/ecuState/EcuStateController.cpp",
          "libs/bsw/ecuState/src/ecuState/EcuStateRte.cpp"]
# PLAT-62: own full-featured test profile (synthetic board with SBC and two CAN buses) instead of the eval board
# project, which stays private (PLAT-46 F10); the eval board project is checked as well where it exists.
DEMO_PROJECT = REPO / "tools" / "nxconfig" / "test" / "profiles" / "projects" / "testproject_full" / "project.yaml"
EVAL_PROJECT = REPO / "projects" / "evalboard_s32k144_demo" / "project.yaml"
# PLAT-28: host stub of the interrupt lock of the platform (OpenBSW interrupts/SuspendResumeAllInterruptsScopedLock.h)
STUBS = "libs/bsw/ecuState/test/host/stubs"

GCC_PATH = os.pathsep.join(p for p in (os.environ.get("NX_ARM_GCC_BIN"), os.environ.get("PATH")) if p)
ARM_GXX = shutil.which("arm-none-eabi-g++", path=GCC_PATH)
ARM_NM = shutil.which("arm-none-eabi-nm", path=GCC_PATH)
OPENBSW = REPO / "external" / "openbsw"
# The interrupt lock as a target build sees it: OpenBSW contract + implementation of a Cortex-M platform (PRIMASK)
TARGET_LOCK_INCLUDES = [OPENBSW / "libs/bsp/bspInterrupts/include",
                        OPENBSW / "platforms/s32k1xx/bsp/bspInterruptsImpl/freertos/include"]

# Test profile of the project entry modules.ecuState (values checked in EcuStateIntegrationHostTest.cpp):
# every value differs from the module default, the times sit on the manifest minimums.
PROFILE = {"min_run_ms": 0, "post_run_ms": 750, "shutdown_timeout_ms": 100, "sleep_timeout_ms": 101,
           "nvm_timeout_ms": 10, "can_stop_timeout_ms": 20,
           "wakeup_can": "CAN0", "wakeup_local": "LOCAL3", "wakeup_cyclic_ms": 5,
           "wakeup_during_shutdown": "sleep", "after_watchdog_reset": "sleep", "step_error": "continue",
           "verify": True}


class EcuStateHostTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_host_test(self, name, includes, sources):
        exe = self.tmp / f"{name}.exe"
        cmd = [sys.executable, "-m", "ziglang", "c++", *FLAGS, *[f"-I{REPO / i}" for i in [*includes, STUBS]],
               *[str(REPO / s) for s in sources], "-o", str(exe)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr[-3000:])
        r = subprocess.run([str(exe)], capture_output=True, text=True)
        print("\n" + r.stdout.strip().splitlines()[-1], file=sys.stderr)
        self.assertEqual(r.returncode, 0, r.stdout[-3000:])
        self.assertRegex(r.stdout, r"\d+ checks, 0 failures")
        return r.stdout

    def test_state_machine_without_sbc(self):
        self.run_host_test("ecu_state", ["libs/bsw/ecuState/include"],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuStateHostTest.cpp"])

    def test_start_reasons_from_both_sources(self):
        """SYS-18: role power_supply and the MCU's own reset status, board with and without a supply device."""
        self.run_host_test("ecu_start_reason", ["libs/bsw/ecuState/include"],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuStartReasonHostTest.cpp"])

    def test_run_down_before_sleep(self):
        """SYS-02: order of the run-down steps, missing NvM, failed step, timeout per step."""
        self.run_host_test("ecu_shutdown", ["libs/bsw/ecuState/include"],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuShutdownHostTest.cpp"])

    def test_restart_supervised_with_direct_reset(self):
        """SYS-173: a lifecycle that never carries the restart out is ended by the direct reset of the family port."""
        self.run_host_test("ecu_restart_supervision", ["libs/bsw/ecuState/include"],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuRestartSupervisionHostTest.cpp"])

    def test_safe_outputs_step_of_the_family_port(self):
        """SYS-174: run-down step SAFE_OUTPUTS of the s32k1xx port - lock, table walk, PWM inhibit, last step."""
        self.run_host_test("ecu_safe_outputs_step",
                           ["libs/bsw/ecuState/include", "platforms/s32k1xx/port/main/src/integration"],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuSafeOutputsStepHostTest.cpp"])

    def test_output_flush_before_power_down(self):
        """SYS-09: the log reaches the console before the power down; console flush of the board integration."""
        self.run_host_test("ecu_output_flush",
                           ["libs/bsw/ecuState/include", "platforms/s32k1xx/port/main/src/integration"],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuOutputFlushHostTest.cpp"])

    def test_uja113x_power_supply(self):
        self.run_host_test(
            "uja113x_power_supply",
            ["libs/bsw/ecuState/include", "libs/bsw/sbcUja113x/include", "libs/bsp/bspSpi/include"],
            MODULE + ["libs/bsw/sbcUja113x/src/sbc/Uja113x.cpp",
                      "libs/bsw/sbcUja113x/test/host/Uja113xPowerSupplyHostTest.cpp"])

    def test_generated_parameters(self):
        # SYS-08: the parameters are project values (project.yaml modules.ecuState), the ECU description stays as is
        project = yaml.safe_load(DEMO_PROJECT.read_text(encoding="utf-8"))
        project["project"]["board"] = (DEMO_PROJECT.parent / project["project"]["board"]).resolve().as_posix()
        # TOOL-114: the RTE is required on a real board - the demo's rte.yaml, by its absolute path
        project["project"]["rte"] = (DEMO_PROJECT.parent / project["project"]["rte"]).resolve().as_posix()
        project["project"].pop("diag", None)  # the copy has no diag.yaml next to it (ARCH-51)
        # SYS-174: step_error continue of PROFILE is refused for a project with an NvM step - this copy has none
        project.pop("nvm", None)
        project.setdefault("modules", {})["ecuState"] = PROFILE
        project_file = self.tmp / "project" / "project.yaml"
        project_file.parent.mkdir(parents=True)
        project_file.write_text(yaml.safe_dump(project, sort_keys=False), encoding="utf-8")
        gen = self.tmp / "gen"
        rtegen.generate(DEMO_PROJECT.parent / "rte.yaml", rtegen.nxconfig.load(project_file), gen, REPO)
        self.run_host_test("ecu_state_integration", ["libs/bsw/ecuState/include", gen],
                           MODULE + ["libs/bsw/ecuState/test/host/EcuStateIntegrationHostTest.cpp"])

    def test_demo_project_uses_the_defaults(self):
        self.check_defaults(DEMO_PROJECT)

    @unittest.skipUnless(EVAL_PROJECT.is_file(), "private eval board project not in this tree (exported open tree, PLAT-62)")
    def test_eval_board_project_uses_the_defaults(self):
        self.check_defaults(EVAL_PROJECT)

    def check_defaults(self, project_file):
        gen = self.tmp / "gen"
        rtegen.generate_project(project_file, gen, REPO)
        header = (gen / "EcuStateConfig.h").read_text(encoding="utf-8")
        manifest = rtegen.ecu_state_manifest(None)
        # COM-05: the project sets wakeup_can explicitly (CAN0, the passive transceiver of CAN1 cannot wake)
        demo = yaml.safe_load(project_file.read_text(encoding="utf-8"))
        explicit = (demo.get("modules") or {}).get("ecuState") or {}
        self.assertEqual(explicit.get("wakeup_can"), "CAN0")
        for name, spec in manifest.parameters.items():
            self.assertIn(f"#define NX_ECU_STATE_PARAM_{name.upper()} ", header)
            if name != "wakeup_can":
                self.assertIn(f"// {name} (default)", header)
        self.assertIn("#define NX_ECU_STATE_VERIFY 0", header)


@unittest.skipIf(ARM_GXX is None or ARM_NM is None, "arm-none-eabi-g++/nm not found (PATH, NX_ARM_GCC_BIN)")
# PLAT-62: the interrupt lock comes from the OpenBSW submodule, which an exported tree does not carry
@unittest.skipUnless(all(i.is_dir() for i in TARGET_LOCK_INCLUDES),
                     "external/openbsw not checked out (git submodule update --init external/openbsw)")
class ArmV6mTest(unittest.TestCase):
    """PLAT-28: ecuState must link on ARMv6-M without libatomic (PLAT-12 finding 6: __atomic_exchange_1)."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def undefined_symbols(self, cpu_flags):
        symbols = set()
        for source in MODULE:
            obj = self.tmp / (Path(source).stem + ".o")
            cmd = [ARM_GXX, *cpu_flags, "-mthumb", "-std=c++17", "-O2", "-fno-exceptions", "-fno-rtti",
                   "-Wall", "-Wextra", "-Werror", f"-I{REPO / 'libs/bsw/ecuState/include'}",
                   *[f"-I{i}" for i in TARGET_LOCK_INCLUDES], "-c", str(REPO / source), "-o", str(obj)]
            r = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr[-3000:])
            r = subprocess.run([ARM_NM, "-u", str(obj)], capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            symbols |= set(re.findall(r"^\s*U\s+(\S+)$", r.stdout, flags=re.M))
        return symbols

    def test_cortex_m0plus_needs_no_libatomic(self):
        symbols = self.undefined_symbols(["-mcpu=cortex-m0plus", "-mfloat-abi=soft"])
        self.assertTrue(symbols, "nm found no undefined symbol at all - the check would prove nothing")
        self.assertEqual(sorted(s for s in symbols if s.startswith("__atomic")), [])

    def test_cortex_m4f_needs_no_libatomic(self):
        symbols = self.undefined_symbols(["-mcpu=cortex-m4", "-mfloat-abi=hard", "-mfpu=fpv4-sp-d16"])
        self.assertEqual(sorted(s for s in symbols if s.startswith("__atomic")), [])


if __name__ == "__main__":
    unittest.main()
