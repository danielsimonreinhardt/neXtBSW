#pragma once

#include "can/CanBusState.h"

#include <cstdint>

namespace can
{

/**
 * What a CAN bus does after bus off, when the bus off keeps coming back (COM-35).
 *
 * Board finding 2026-09-22 (COM-26 P9, CANH shorted to CANL on CAN1): one frame hung in a transmit buffer. The
 * controller left bus off by itself after 128 x 11 recessive bits, retried the frame, collected 32 bit errors and
 * was bus off again - every 30-120 ms, 9812 times in about 10 minutes, each time one ERROR and one INFO line in
 * the log, and the frame was never given up. Three measures, one instance per bus:
 *
 *   log        the first bus off of a series and its recovery are logged as before; further bus offs of the
 *              series are only counted and summarised in one line per summaryMs; one line when the series ends
 *              (no bus off for quietMs)
 *   pause      the controller is held in bus off (FlexCAN CTRL1[BOFFREC] = 1, bxCAN ABOM = 0, FDCAN CCCR[INIT]
 *              stays set) and released after a pause that doubles with every bus off of the series, from
 *              firstPauseMs up to maxPauseMs
 *   discard    from the discardAfter-th bus off of a series on, the frames waiting in the transmit buffers are
 *              dropped before the release: a frame that has already cost that many bus offs will cost the next
 *              one as well
 *
 * Hardware independent: the caller reads its controller, feeds the bus state monitor (feedMonitor()) and asks
 * cycle() what to do; it holds, releases and discards on its controller. The class touches no register and needs
 * no clock (elapsed time of the supervision cycle as argument), so the host test runs the board finding in a model.
 *
 * Board neutral: nothing here knows FlexCAN (since COM-37 in libs/bsw/canSystem, usable by every family port). A
 * controller without a way to hold bus off runs with maxPauseMs 0 (automatic recovery of the controller, as before
 * COM-35); logging and discarding work the same.
 *
 * The values are project values per bus (COM-37): project.yaml can.<bus>.bus_off, generated by tools/bswgen as
 * ::bsp::can::<bus>_BUS_OFF_CONFIG (bsp/can/canBusOffConfiguration.h). The family port gives every bus its own
 * instance with the values of that bus.
 */
class CanBusOffRecovery
{
public:
    struct Config
    {
        /** Pause before the first release of a series (ms). */
        uint16_t firstPauseMs;
        /** Upper limit of the doubling pause (ms); 0 = do not hold, the controller recovers by itself. */
        uint16_t maxPauseMs;
        /** From this bus off of a series on the pending transmit frames are dropped; 0 = never. */
        uint8_t discardAfter;
        /** A series ends after this long without bus off (ms). */
        uint16_t quietMs;
        /** At most one summary line per this period while a series lasts (ms). */
        uint16_t summaryMs;
    };

    /**
     * Defaults of the project values (COM-37: can.<bus>.bus_off of project.yaml without an entry, the schema in
     * tools/nxconfig/model.py CanBusOff has the same numbers - tools/bswgen/test_bswgen.py compares them). Reasons:
     *   firstPauseMs 10    one supervision cycle (CanSupervisionCycle::BUS_STATE_CYCLE_MS): a single bus off (e.g.
     *                      a transceiver switched while a frame was on the bus, board 2026-09-18) is over as fast
     *                      as before (about 20 ms instead of 20-30 ms)
     *   maxPauseMs 1000    10, 20, 40, ... 640, then 1000 ms: at most one bus off per second in a lasting fault
     *                      (board: about 16 per second), the bus is back within 1 s after the fault is removed;
     *                      the slow step of a CanSM-like recovery in AUTOSAR is of the same order
     *   discardAfter 3     three series of 32 failed attempts each for the same frame (96 attempts); periodic
     *                      frames come again anyway, a transport (DoCAN) runs into its own timeout
     *   quietMs 2000       longer than the longest pause, so a lasting fault stays one series
     *   summaryMs 10000    one line per 10 s instead of 32 lines per second (board: 9812 bus offs, 19624 lines)
     */
    static constexpr Config DEFAULT_CONFIG = {10U, 1000U, 3U, 2000U, 10000U};

    /** What the caller has to do after one supervision cycle (several may be set). */
    struct Step
    {
        bool discard;     // drop the frames in the transmit buffers (before the release)
        bool release;     // let the controller leave bus off (idempotent while it is still bus off)
        bool logDiscard;  // first discard of the series: one line
        bool logSummary;  // summary line: summaryBusOffs() in summaryWindowMs(), series counters
        bool logSeriesEnd; // the series is over: seriesBusOffs() in seriesMs(), discards
    };

    constexpr explicit CanBusOffRecovery(Config const& config = DEFAULT_CONFIG) : _config(config) {}

    Config const& config() const { return _config; }

    /** True if the controller is held in bus off and released by cycle() (maxPauseMs > 0). */
    bool holdsRecovery() const { return _config.maxPauseMs > 0U; }

    /**
     * Feeds one reading into the bus state monitor and returns its events in order (at most two).
     *
     * \p enteredBusOff is the latched "went bus off" flag of the controller since the last reading (FlexCAN
     * ESR1[BOFFINT], cleared by the caller after reading). It matters when the controller was released, came back
     * and went bus off again between two readings: FLTCONF says bus off both times and the monitor alone would see
     * one long bus off - the recovery that happened in between would be lost and the caller would wait for a
     * recovery that never comes. With the flag the monitor sees both edges. The same for a bus off that was over
     * before the reading (only possible without holding).
     *
     * \return number of events written to \p events (0..2)
     */
    static uint8_t feedMonitor(
        CanBusMonitor& monitor,
        CanBusState const state,
        bool const enteredBusOff,
        uint32_t const elapsedMs,
        CanBusMonitor::Event (&events)[2])
    {
        uint8_t count = 0U;
        if (state == CanBusState::UNKNOWN)
        {
            events[0] = monitor.stop();
            return 1U;
        }
        if (enteredBusOff && monitor.isBusOff())
        {
            // released, back on the bus, and off again between two readings
            events[count++] = monitor.update(CanBusState::ERROR_ACTIVE, elapsedMs);
            events[count++] = monitor.update(state, 0U);
            return count;
        }
        if (enteredBusOff && (state != CanBusState::BUS_OFF))
        {
            // off and back again between two readings (controller recovering by itself)
            events[count++] = monitor.update(CanBusState::BUS_OFF, elapsedMs);
            events[count++] = monitor.update(state, 0U);
            return count;
        }
        events[count++] = monitor.update(state, elapsedMs);
        return count;
    }

    /**
     * The monitor reported WENT_BUS_OFF. Starts a series or continues it, starts the pause.
     * \return true if this bus off is to be logged (the first one of a series)
     */
    bool wentBusOff()
    {
        bool const first = !_inSeries;
        if (first)
        {
            _inSeries       = true;
            _seriesBusOffs  = 0U;
            _seriesMs       = 0U;
            _seriesDiscards = 0U;
            _summaryBusOffs = 0U;
            _summaryMs      = 0U;
        }
        _seriesBusOffs  = increment(_seriesBusOffs);
        _summaryBusOffs = (first) ? 0U : increment(_summaryBusOffs);
        _quietMs        = 0U;
        _waitedMs       = 0U;
        _pauseMs        = pauseFor(_seriesBusOffs);
        _holding        = holdsRecovery();
        _discardDue     = (_config.discardAfter > 0U) && (_seriesBusOffs >= _config.discardAfter);
        return first;
    }

    /**
     * The monitor reported RECOVERED.
     * \return true if this recovery is to be logged (the recovery of the first bus off of a series)
     */
    bool recovered()
    {
        _holding    = false;
        _discardDue = false; // the controller is back: the frames go out or cause the next bus off
        return _inSeries && (_seriesBusOffs == 1U);
    }

    /** The controller was closed: no series, no hold (the counters of the monitor stay). */
    void stop()
    {
        _inSeries   = false;
        _holding    = false;
        _discardDue = false;
    }

    /**
     * One supervision cycle, after feeding the monitor.
     * \param busOff     the monitor's state after this cycle's reading
     * \param elapsedMs  time since the last cycle
     */
    Step cycle(bool const busOff, uint32_t const elapsedMs)
    {
        Step step = {false, false, false, false, false};
        if (!_inSeries)
        {
            return step;
        }
        _seriesMs = addSaturating(_seriesMs, elapsedMs);
        if (busOff)
        {
            // Held: discard and release together when the pause is over, while the controller is still off the bus
            // (no frame in transmission). Not held: discard at once, the controller may already be back.
            bool const pauseOver = !_holding || (_waitedMs >= _pauseMs);
            if (_discardDue && pauseOver)
            {
                _discardDue     = false;
                step.discard    = true;
                step.logDiscard = (_seriesDiscards == 0U);
                _seriesDiscards = increment(_seriesDiscards);
                _totalDiscards  = increment(_totalDiscards);
            }
            if (_holding)
            {
                // stays "holding" after the release: if the controller is still off at the next cycle, release
                // again (idempotent; a controller that missed a release must not stay off for ever)
                step.release = pauseOver;
                // the reading that saw the bus off is not part of the pause, only the cycles after it
                _waitedMs = addSaturating(_waitedMs, elapsedMs);
            }
        }
        else
        {
            _quietMs = addSaturating(_quietMs, elapsedMs);
            if (_quietMs >= _config.quietMs)
            {
                _inSeries         = false;
                step.logSeriesEnd = (_seriesBusOffs > 1U); // a single bus off was logged with its recovery
                return step;
            }
        }
        _summaryMs = addSaturating(_summaryMs, elapsedMs);
        if (_summaryMs >= _config.summaryMs)
        {
            step.logSummary = (_summaryBusOffs > 0U);
            _lastSummaryBusOffs = _summaryBusOffs;
            _lastSummaryMs      = _summaryMs;
            _summaryBusOffs     = 0U;
            _summaryMs          = 0U;
        }
        return step;
    }

    /** Pause before the release of the n-th bus off of a series (n >= 1). */
    uint32_t pauseFor(uint32_t const busOffInSeries) const
    {
        uint32_t pause = _config.firstPauseMs;
        for (uint32_t n = 1U; (n < busOffInSeries) && (pause < _config.maxPauseMs); ++n)
        {
            pause *= 2U;
        }
        return (pause > _config.maxPauseMs) ? _config.maxPauseMs : pause;
    }

    bool inSeries() const { return _inSeries; }

    /** Bus offs of the running (or last) series. */
    uint32_t seriesBusOffs() const { return _seriesBusOffs; }

    /** Duration of the running (or last) series (ms). */
    uint32_t seriesMs() const { return _seriesMs; }

    /** Discards in the running (or last) series. */
    uint32_t seriesDiscards() const { return _seriesDiscards; }

    /** Discards since start. */
    uint32_t totalDiscards() const { return _totalDiscards; }

    /** Pause of the current (or last) bus off (ms). */
    uint32_t pauseMs() const { return _pauseMs; }

    /** For the summary line: bus offs not logged in the period that just ended, and its length (ms). */
    uint32_t summaryBusOffs() const { return _lastSummaryBusOffs; }

    uint32_t summaryWindowMs() const { return _lastSummaryMs; }

private:
    static uint32_t addSaturating(uint32_t const value, uint32_t const add)
    {
        return (value > (UINT32_MAX - add)) ? UINT32_MAX : (value + add);
    }

    static uint32_t increment(uint32_t const value) { return addSaturating(value, 1U); }

    Config _config;
    bool _inSeries             = false;
    bool _holding              = false;
    bool _discardDue           = false;
    uint32_t _seriesBusOffs    = 0U;
    uint32_t _seriesMs         = 0U;
    uint32_t _seriesDiscards   = 0U;
    uint32_t _totalDiscards    = 0U;
    uint32_t _summaryBusOffs   = 0U;
    uint32_t _summaryMs        = 0U;
    uint32_t _lastSummaryBusOffs = 0U;
    uint32_t _lastSummaryMs    = 0U;
    uint32_t _quietMs          = 0U;
    uint32_t _waitedMs         = 0U;
    uint32_t _pauseMs          = 0U;
};

} // namespace can
